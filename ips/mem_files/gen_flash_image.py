#!/usr/bin/env python3
"""
RISCFORGE 1TOPS — SPI flash image generator.

Turns the word-oriented RISC-V .hex images in this folder into the
byte-oriented preload file consumed by the Infineon S25FS512S model
(spi_slave_infinion/S25fs512s/model/s25fs512s.sv, `mem_file_name` parameter).

Reuses the vendor-supplied converters in the model folder:

  spi_unified_mem_instr_data.py   load_word_mem() / merge_mem()
      Merges a word-addressed instruction image and data image into one
      little-endian byte stream starting at flash byte 0. This is the layout
      the RISCFORGE bootloader expects: it issues a standard 0x03 read from
      byte address 0, walks forward 4 bytes at a time, and byte-swaps each
      RX-FIFO word on capture (bootloader.sv:525). The first NUM_INSTR_WORDS
      words land in ISRAM, the remainder in DSRAM (bootloader.sv:547).

  spi_mem_conversion.py
      Emits the same bytes with explicit "@AAAAAAA" address markers. Its
      input/output filenames are module-level constants, so it cannot be
      imported and re-pointed at a different file; its output format is
      reproduced here instead (see write_addressed_image). The flash model
      parses both forms — a bare byte list simply loads from address 0.

Usage:
    python gen_flash_image.py

Outputs (this folder):
    riscforge_timer0_flash.mem      flat byte stream   <- used by the testbench
    riscforge_timer0_flash_spi.mem  @-addressed bytes  (equivalent, for reference)
"""

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
MODEL_DIR = HERE.parent / "spi_slave_infinion" / "S25fs512s" / "model"

if not MODEL_DIR.is_dir():
    sys.exit(f"Error: SPI flash model folder not found: {MODEL_DIR}")

sys.path.insert(0, str(MODEL_DIR))

try:
    from spi_unified_mem_instr_data import load_word_mem, merge_mem
except ImportError as exc:
    sys.exit(f"Error: could not import the vendor converter from {MODEL_DIR}: {exc}")


# -- Image definition ---------------------------------------------------------
# Instruction words are loaded to ISRAM (0x0001_0000), data words to DSRAM
# (0x0002_0000). Keep NUM_INSTR_WORDS / NUM_DATA_WORDS in the testbench in
# sync with the line counts reported below.
INSTR_FILE = HERE / "riscforge_timer0_test.hex"
DATA_FILE = HERE / "riscforge_timer0_dmem.hex"
FLAT_OUT = HERE / "riscforge_timer0_flash.mem"
ADDR_OUT = HERE / "riscforge_timer0_flash_spi.mem"

# The model skips any preload byte equal to MaxData (s25fs512s.sv:1059), leaving
# it at the erased value — which is 0xFF anyway, so the image is unaffected.
ERASED_BYTE = 0xFF


def write_addressed_image(byte_list, out_path):
    """Emit bytes in spi_mem_conversion.py's '@AAAAAAA' + 'DD' format.

    preload_address_width in the model is 7 (s25fs512s.sv:969), so addresses
    are written as exactly 7 hex digits.
    """
    with out_path.open("w") as f:
        f.write("// RISCFORGE flash image - generated by gen_flash_image.py\n")
        f.write(f"@{0:07X}\n")
        for b in byte_list:
            f.write(f"{int(b, 16):02X}\n")


def count_words(path):
    n = 0
    with path.open("r") as f:
        for line in f:
            line = line.strip()
            if line and not line.startswith("//") and not line.startswith("@"):
                n += 1
    return n


def main():
    for p in (INSTR_FILE, DATA_FILE):
        if not p.is_file():
            sys.exit(f"Error: missing input image: {p}")

    n_instr = count_words(INSTR_FILE)
    n_data = count_words(DATA_FILE)

    # Vendor merge: instruction bytes first, then data bytes, little-endian.
    merge_mem(INSTR_FILE, DATA_FILE, FLAT_OUT)

    # Same content, with the explicit address marker form.
    merged = load_word_mem(INSTR_FILE) + load_word_mem(DATA_FILE)
    write_addressed_image(merged, ADDR_OUT)

    erased = sum(1 for b in merged if int(b, 16) == ERASED_BYTE)

    print()
    print("=====================================")
    print("RISCFORGE flash image")
    print("=====================================")
    print(f"NUM_INSTR_WORDS   : {n_instr}   -> ISRAM 0x0001_0000")
    print(f"NUM_DATA_WORDS    : {n_data}   -> DSRAM 0x0002_0000")
    print(f"Total flash bytes : {len(merged)}")
    if erased:
        print(f"NOTE: {erased} byte(s) equal 0xFF and are skipped by the model's")
        print("      preloader; they read back as 0xFF (erased), which matches.")
    print(f"Addressed form    : {ADDR_OUT.name}")
    print("=====================================")
    print()
    print("Set these in the testbench:")
    print(f"    localparam int unsigned NUM_INSTR_WORDS = {n_instr};")
    print(f"    localparam int unsigned NUM_DATA_WORDS  = {n_data};")
    print()


if __name__ == "__main__":
    main()
