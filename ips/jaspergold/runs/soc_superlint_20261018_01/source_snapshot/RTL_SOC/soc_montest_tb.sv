// =============================================================================
// RISCFORGE 1TOPS — Bus Timeout Monitor Testbench
// =============================================================================
// Boots the full riscforge_soc_subsystem from the Infineon S25FS512S flash
// model, then runs the monitor-test firmware (ips/mem_files/montest/montest.c)
// on the real RV32 core. Where soc_regtest_tb proves the registers work, this
// one proves the bus does not hang when a slave stops answering:
//
//     apb_timeout_monitor       one per APB slot   (ips/bus_monitors/)
//     axi_lite_timeout_monitor  core master port
//
// Stall injection
//   Only the SPI master can stall by itself. Every other slave ties PREADY
//   high, so this testbench forces it low on request from the firmware. The
//   force targets are scalar signals, never members of a packed struct, so
//   `force`/`release` behave the same on every simulator:
//     0 dut.i2c_pready                              4 dut.spi_pready
//     1 dut.timer0_pready                           5 dut.timer1_pready
//     2 dut.uart_pready
//     3 dut.i_gpio_apb_wrap.s_bridge_pready
//     6 dut.i_axi_lite_to_apb.apb_rresp_ready
//   Target 6 is the AXI case. Holding the bridge's response-channel ready low
//   freezes its FSM in Setup (axi_lite_to_apb.sv:298), so it never drives PSEL:
//   the AXI transaction hangs with no APB activity at all, which is exactly the
//   fabric deadlock the AXI backstop exists for, and it proves the APB monitors
//   cannot cover it.
//
// Firmware -> TB result words (DSRAM 0x0002_0000, 7 words), same layout as
// soc_regtest_tb, with five commands added:
//   0x10 STALL    ADDR = target above
//   0x11 RELEASE  release every force
//   0x12 MONCLR   zero the per-monitor fire counters
//   0x13 MONCHK   ADDR = monitor id (0..5 APB, 6 AXI wr, 7 AXI rd, 0xFF none),
//                 EXP  = its fire count; every other monitor must be at 0
//   0x14 STICKY   EXP  = expected {axi_rd, axi_wr, apb_timeout_sticky_o}
//
// Checks the testbench makes on its own, which the firmware cannot
//   - Exact threshold: an independent counter of consecutive
//     PSEL & PENABLE & !PREADY cycles must equal APB_THRESH[i]-1 at the fire,
//     or 0 when the slot was already blocked from a previous abort.
//   - Real PREADY wins: a monitor may never fire in a cycle where the slave
//     itself is asserting PREADY.
//   - Response shaping: on a fire the bridge sees PREADY=1, PSLVERR=1 and
//     0xDEADBEEF, while the slave side is still holding PREADY low — the
//     slave's own PREADY is never driven, so an aborted SPI RXFIFO read pops
//     nothing (spi_master_apb_if.sv:236).
//   - AXI threshold measured the same way, per outstanding transaction.
//   - Beat conservation: on both sides of the AXI monitor, every AR is
//     answered by exactly one R and every AW by exactly one B. A swallowed
//     orphan that leaked through, or an injected response that was also
//     delivered by the fabric, shows up here.
//   - Every non-OKAY response on the core's AXI port matches a trap taken.
//   - Timer guard: no timer IRQ while that channel's CTRL.EN = 0.
//   - SPI CS0 (the flash) is never selected at runtime; CS0 and CS1 are never
//     low together.
//
// -----------------------------------------------------------------------------
// Build the firmware + flash image first (needs the RISC-V GCC toolchain):
//     cd ips/mem_files/montest && python build.py
//
// Run from RTL_SOC/ (all relative paths assume it):
//     xrun -f rtl/soc_montest.f               # normal run
//     xrun -f rtl/soc_montest.f +VERBOSE      # also print every PASS
// Waveforms are written every run to soc_montest_tb.shm; no flag needed.
// =============================================================================
`timescale 1ns/1ps

module soc_montest_tb;

  import gpio_reg_pkg::GPIOCount;

  // Generated by build.py: FW_NUM_INSTR_WORDS, FW_NUM_DATA_WORDS, FW_RESULT_ADDR
  `include "montest_params.svh"

  // ───────────────────────────────────────────────────────────────────────
  //  Configuration
  // ───────────────────────────────────────────────────────────────────────
  localparam int unsigned TIMER0_CNT           = 2;
  localparam int unsigned TIMER1_CNT           = 2;
  localparam int unsigned FLASH_POWERUP_CYCLES = 30_000;   // S25FS512S tPU = 300 us
  localparam time         CLK_PERIOD           = 10ns;     // 100 MHz

  localparam int unsigned NUM_APB_SLAVES = 6;

  // Must match APB_TIMEOUT_CYCLES / AXI_TIMEOUT_* in riscforge_soc_subsystem.sv
  localparam int unsigned APB_THRESH [NUM_APB_SLAVES] = '{16, 16, 16, 16, 65536, 16};
  localparam int unsigned AXI_THRESH_APB  = 131072;
  localparam int unsigned AXI_THRESH_DFLT = 64;
  localparam logic [31:0] APB_TIMEOUT_DATA = 32'hDEAD_BEEF;

  localparam int unsigned IMAGE_WORDS = FW_NUM_INSTR_WORDS + FW_NUM_DATA_WORDS;

  localparam longint unsigned BOOT_TIMEOUT_CYCLES = 200_000 + 400 * IMAGE_WORDS;
  // Budget: 6 forced slots (slot 4 alone costs 2 x 65536), the SPI natural
  // aborts (3 x 65536), the legitimate 32768-cycle transfer and two AXI
  // timeouts at 131072 each.
  localparam longint unsigned RUN_TIMEOUT_CYCLES  = 3_000_000;

  localparam logic [31:0] ISRAM_BASE  = 32'h0001_0000;
  localparam logic [31:0] DSRAM_BASE  = 32'h0002_0000;
  localparam int unsigned DSRAM_WORDS = 8192;
  localparam int unsigned RES_WORD   = (FW_RESULT_ADDR - DSRAM_BASE) >> 2;
  localparam int unsigned RES_WORDS  = 16;   // .result words is 64 B (link.ld)

  localparam string FLASH_IMAGE = "../mem_files/montest/montest_flash.mem";
  localparam string IMEM_HEX    = "../mem_files/montest/montest_imem.hex";
  localparam string DMEM_HEX    = "../mem_files/montest/montest_dmem.hex";
  localparam string OTP_FILE    = "../spi_slave_infinion/S25fs512s/model/s25fs512sOTP.mem";

  // Must match phase2_spi_natural() / phase4_no_false_fire() in montest.c
  localparam logic [63:0] SPI1_PATTERN = 64'hC3A5_5A3C_0F1E_2D4B;
  localparam int unsigned SPI1_EXPECTED_SELECTS = 2;

  // Result-word commands (montest.c)
  localparam logic [31:0] CMD_PASS    = 32'h01;
  localparam logic [31:0] CMD_FAIL    = 32'h02;
  localparam logic [31:0] CMD_SECTION = 32'h03;
  localparam logic [31:0] CMD_STALL   = 32'h10;
  localparam logic [31:0] CMD_RELEASE = 32'h11;
  localparam logic [31:0] CMD_MONCLR  = 32'h12;
  localparam logic [31:0] CMD_MONCHK  = 32'h13;
  localparam logic [31:0] CMD_STICKY  = 32'h14;
  localparam logic [31:0] CMD_DONE    = 32'hD0;

  localparam int unsigned N_MON   = 8;     // 0..5 APB, 6 AXI write, 7 AXI read
  localparam int unsigned MON_NONE = 8'hFF;

  // ───────────────────────────────────────────────────────────────────────
  //  Clock & reset
  // ───────────────────────────────────────────────────────────────────────
  logic clk;
  logic hard_rst_ni;
  logic soft_rst_ni;

  initial clk = 1'b0;
  always #(CLK_PERIOD/2) clk = ~clk;

  longint unsigned cyc_cnt;
  always_ff @(posedge clk) cyc_cnt <= cyc_cnt + 1;

  // ───────────────────────────────────────────────────────────────────────
  //  DUT pins
  // ───────────────────────────────────────────────────────────────────────
  localparam int unsigned NR_GPIOS = GPIOCount;

  logic                        boot_done;

  wire                         i2c_scl_i, i2c_sda_i;
  logic                        i2c_scl_o, i2c_scl_oen_o;
  logic                        i2c_sda_o, i2c_sda_oen_o;
  logic                        i2c_interrupt_o;

  logic [(TIMER0_CNT*2)-1:0]   timer0_irq;
  logic [(TIMER1_CNT*2)-1:0]   timer1_irq;

  logic                        uart_sin_i;
  logic                        uart_sout_o, uart_int_o;

  wire  [NR_GPIOS-1:0]         gpio_in_i;
  logic [NR_GPIOS-1:0]         gpio_out_o, gpio_tx_en_o, gpio_in_sync_o;
  logic                        gpio_global_interrupt_o;
  logic [NR_GPIOS-1:0]         gpio_pin_level_interrupts_o;

  logic                        spi_clk_o, spi_csn0_o, spi_csn1_o, spi_sdo0_o;
  wire                         spi_sdi1_i;
  logic [1:0]                  spi_events_o;

  logic [NUM_APB_SLAVES-1:0]   apb_timeout_sticky;
  logic                        axi_wr_timeout_sticky, axi_rd_timeout_sticky;

  initial uart_sin_i = 1'b1;           // UART RX idle

  tri1 i2c_scl_bus, i2c_sda_bus;
  assign i2c_scl_bus = (i2c_scl_oen_o === 1'b0) ? i2c_scl_o : 1'bz;
  assign i2c_sda_bus = (i2c_sda_oen_o === 1'b0) ? i2c_sda_o : 1'bz;
  assign i2c_scl_i   = i2c_scl_bus;
  assign i2c_sda_i   = i2c_sda_bus;

  assign gpio_in_i = gpio_out_o;

  // ───────────────────────────────────────────────────────────────────────
  //  SPI: flash on CS0, slave model on CS1
  // ───────────────────────────────────────────────────────────────────────
  wire flash_si, flash_so, flash_wpn, flash_resetn;
  assign flash_si     = spi_sdo0_o;
  assign flash_wpn    = 1'b1;
  assign flash_resetn = 1'b1;

  s25fs512s #(
    .UserPreload   ( 1           ),
    .mem_file_name ( FLASH_IMAGE ),
    .otp_file_name ( OTP_FILE    )
  ) u_flash (
    .SI       ( flash_si     ),
    .SO       ( flash_so     ),
    .SCK      ( spi_clk_o    ),
    .CSNeg    ( spi_csn0_o   ),
    .WPNeg    ( flash_wpn    ),
    .RESETNeg ( flash_resetn )
  );

  logic [63:0] spi1_shreg;
  int unsigned spi1_select_cnt;
  always @(negedge spi_csn1_o) begin
    spi1_shreg <= SPI1_PATTERN;
    spi1_select_cnt++;
  end
  always @(negedge spi_clk_o)
    if (spi_csn1_o === 1'b0) spi1_shreg <= {spi1_shreg[62:0], 1'b0};

  assign spi_sdi1_i = (spi_csn1_o === 1'b0) ? spi1_shreg[63] : flash_so;

  // ───────────────────────────────────────────────────────────────────────
  //  DUT
  // ───────────────────────────────────────────────────────────────────────
  riscforge_soc_subsystem #(
    .TIMER0_CNT           ( TIMER0_CNT           ),
    .TIMER1_CNT           ( TIMER1_CNT           ),
    .SPI_BUFFER_DEPTH     ( 10                   ),
    .NUM_INSTR_WORDS      ( FW_NUM_INSTR_WORDS   ),
    .NUM_DATA_WORDS       ( FW_NUM_DATA_WORDS    ),
    .FLASH_POWERUP_CYCLES ( FLASH_POWERUP_CYCLES ),
    .NUM_APB_SLAVES       ( NUM_APB_SLAVES       )
  ) dut (
    .clk_i                       ( clk                         ),
    .hard_rst_ni                 ( hard_rst_ni                 ),
    .soft_rst_ni                 ( soft_rst_ni                 ),
    .test_mode_i                 ( 1'b0                        ),
    .fetch_enable_i              ( 1'b1                        ),
    .boot_addr_i                 ( 32'h0000_0000               ),
    .boot_done_o                 ( boot_done                   ),

    .i2c_scl_i                   ( i2c_scl_i                   ),
    .i2c_scl_o                   ( i2c_scl_o                   ),
    .i2c_scl_oen_o               ( i2c_scl_oen_o               ),
    .i2c_sda_i                   ( i2c_sda_i                   ),
    .i2c_sda_o                   ( i2c_sda_o                   ),
    .i2c_sda_oen_o               ( i2c_sda_oen_o               ),
    .i2c_interrupt_o             ( i2c_interrupt_o             ),

    .timer0_irq_o                ( timer0_irq                  ),
    .timer1_irq_o                ( timer1_irq                  ),

    .uart_sin_i                  ( uart_sin_i                  ),
    .uart_sout_o                 ( uart_sout_o                 ),
    .uart_int_o                  ( uart_int_o                  ),

    .gpio_in_i                   ( gpio_in_i                   ),
    .gpio_out_o                  ( gpio_out_o                  ),
    .gpio_tx_en_o                ( gpio_tx_en_o                ),
    .gpio_in_sync_o              ( gpio_in_sync_o              ),
    .gpio_global_interrupt_o     ( gpio_global_interrupt_o     ),
    .gpio_pin_level_interrupts_o ( gpio_pin_level_interrupts_o ),

    .spi_clk_o                   ( spi_clk_o                   ),
    .spi_csn0_o                  ( spi_csn0_o                  ),
    .spi_csn1_o                  ( spi_csn1_o                  ),
    .spi_sdo0_o                  ( spi_sdo0_o                  ),
    .spi_sdi1_i                  ( spi_sdi1_i                  ),
    .spi_events_o                ( spi_events_o                ),

    .apb_timeout_sticky_o        ( apb_timeout_sticky          ),
    .axi_wr_timeout_sticky_o     ( axi_wr_timeout_sticky       ),
    .axi_rd_timeout_sticky_o     ( axi_rd_timeout_sticky       )
  );

  // ───────────────────────────────────────────────────────────────────────
  //  Hierarchical probes
  // ───────────────────────────────────────────────────────────────────────
  `define ISRAM_W(i)    dut.i_isram.u_imem.mem_array[i]
  `define DSRAM_W(i)    dut.i_dsram.mem[i]
  `define CORE_PC       dut.i_riscv_core.Fetch.PCF
  `define TMR(inst, ch) dut.inst.TIMER_GEN[ch].timer_i

  wire core_running = (dut.core_rst_n === 1'b1);

  // Per-slot views of the APB monitors. Built with a genvar loop because a
  // generate-block instance cannot be indexed by a run-time variable.
  logic [NUM_APB_SLAVES-1:0] mon_waiting;   // slave is in ACCESS and not ready
  logic [NUM_APB_SLAVES-1:0] mon_blocked;   // monitor already aborted this slot
  logic [NUM_APB_SLAVES-1:0] mon_pulse;
  logic [NUM_APB_SLAVES-1:0] slv_pready;
  logic [NUM_APB_SLAVES-1:0] mst_pready;
  logic [NUM_APB_SLAVES-1:0] mst_pslverr;

  for (genvar g = 0; g < NUM_APB_SLAVES; g++) begin : gen_mon_probe
    assign mon_waiting[g] = dut.apb_req[g].psel & dut.apb_req[g].penable &
                            ~dut.apb_resp_slv[g].pready;
    assign mon_blocked[g] = dut.gen_apb_timeout_mon[g].i_apb_timeout_monitor.blocked_q;
    assign mon_pulse[g]   = dut.apb_timeout_pulse[g];
    assign slv_pready[g]  = dut.apb_resp_slv[g].pready;
    assign mst_pready[g]  = dut.apb_resp[g].pready;
    assign mst_pslverr[g] = dut.apb_resp[g].pslverr;
  end

  // ───────────────────────────────────────────────────────────────────────
  //  Scoreboard state
  // ───────────────────────────────────────────────────────────────────────
  bit          verbose;
  bit          fw_running, fw_done;
  int unsigned fw_pass, fw_fail;
  int unsigned tb_pass, tb_fail;
  logic [31:0] done_pass, done_fail, done_traps;
  string       last_section;
  longint unsigned run_start_cyc;

  int unsigned mon_cnt   [N_MON];   // fires since the last MONCLR
  int unsigned mon_total [N_MON];   // fires since reset

  // Per-slot scoreboard. Every firmware check carries the IP it belongs to, so
  // each one is filed against its monitor's row and the end-of-run table says
  // per slot how much was tested and what failed. EXP_FIRES is the golden
  // number of aborts each monitor should produce over the whole run: without
  // it, a phase that silently failed to execute would shrink the totals and
  // still report PASSED.
  localparam int unsigned N_ROWS = 8;   // 0..5 APB slots, 6 AXI, 7 cross-IP
  localparam int unsigned EXP_FIRES [N_MON] = '{3, 3, 3, 3, 6, 3, 1, 1};

  int unsigned row_pass   [N_ROWS];
  int unsigned row_fail   [N_ROWS];
  string       row_detail [N_ROWS];

  function automatic int unsigned row_of_ip(input string ip);
    case (ip)
      "I2C":    return 0;
      "TIMER0": return 1;
      "UART":   return 2;
      "GPIO":   return 3;
      "SPI":    return 4;
      "TIMER1": return 5;
      "AXI":    return 6;
      default:  return 7;     // "BUS" (mixed traffic), "CORE" (trap accounting)
    endcase
  endfunction

  function automatic string row_name(input int unsigned r);
    case (r)
      0: return "APB[0] I2C";
      1: return "APB[1] TIMER0";
      2: return "APB[2] UART";
      3: return "APB[3] GPIO";
      4: return "APB[4] SPI";
      5: return "APB[5] TIMER1";
      6: return "AXI-Lite core port";
      default: return "cross-peripheral / core";
    endcase
  endfunction

  task automatic tb_check(input string label, input bit cond);
    if (cond) begin
      tb_pass++;
      if (verbose) $display("[TB]   PASS  %s", label);
    end else begin
      tb_fail++;
      $display("[TB]   FAIL  %s   (cyc %0d, section %s)", label, cyc_cnt, last_section);
    end
  endtask

  function automatic string resp_name(input logic [1:0] r);
    case (r)
      2'b00:   return "OKAY";
      2'b01:   return "EXOKAY";
      2'b10:   return "SLVERR";
      default: return "DECERR";
    endcase
  endfunction

  function automatic string mon_name(input int unsigned id);
    case (id)
      0: return "APB[0] I2C";
      1: return "APB[1] TIMER0";
      2: return "APB[2] UART";
      3: return "APB[3] GPIO";
      4: return "APB[4] SPI";
      5: return "APB[5] TIMER1";
      6: return "AXI write";
      7: return "AXI read";
      default: return "<none>";
    endcase
  endfunction

  function automatic string fw_str(input logic [31:0] ptr);
    string       s;
    logic [31:0] a;
    logic [31:0] w;
    logic [7:0]  c;
    s = "";
    if (ptr == 32'h0) return s;
    if (ptr < DSRAM_BASE || ptr >= DSRAM_BASE + 4 * DSRAM_WORDS)
      return $sformatf("<ptr 0x%08h outside DSRAM>", ptr);
    for (int i = 0; i < 160; i++) begin
      a = ptr + i;
      if (a >= DSRAM_BASE + 4 * DSRAM_WORDS) break;
      w = `DSRAM_W((a - DSRAM_BASE) >> 2);
      c = w[8 * a[1:0] +: 8];
      if (c == 8'h00) break;
      s = $sformatf("%s%c", s, c);
    end
    return s;
  endfunction

  // ───────────────────────────────────────────────────────────────────────
  //  Stall injection
  // ───────────────────────────────────────────────────────────────────────
  bit          stall_active;
  int unsigned stall_target;
  logic        stall_pre_val;      // value of the target before it was forced
  bit          rel_check_armed;
  longint unsigned rel_check_at;

  function automatic logic stall_sig(input int unsigned t);
    case (t)
      0: return dut.i2c_pready;
      1: return dut.timer0_pready;
      2: return dut.uart_pready;
      3: return dut.i_gpio_apb_wrap.s_bridge_pready;
      4: return dut.spi_pready;
      5: return dut.timer1_pready;
      6: return dut.i_axi_lite_to_apb.apb_rresp_ready;
      default: return 1'b1;
    endcase
  endfunction

  function automatic string stall_name(input int unsigned t);
    case (t)
      0: return "i2c_pready";
      1: return "timer0_pready";
      2: return "uart_pready";
      3: return "gpio s_bridge_pready";
      4: return "spi_pready";
      5: return "timer1_pready";
      6: return "axi_lite_to_apb.apb_rresp_ready";
      default: return "<bad target>";
    endcase
  endfunction

  task automatic release_all();
    release dut.i2c_pready;
    release dut.timer0_pready;
    release dut.uart_pready;
    release dut.i_gpio_apb_wrap.s_bridge_pready;
    release dut.spi_pready;
    release dut.timer1_pready;
    release dut.i_axi_lite_to_apb.apb_rresp_ready;
  endtask

  task automatic apply_stall(input int unsigned t);
    if (stall_active) begin
      $display("[TB]   note: CMD_STALL(%0d) while %s was still forced; releasing first",
               t, stall_name(stall_target));
      release_all();
    end
    stall_pre_val = stall_sig(t);
    case (t)
      0: force dut.i2c_pready    = 1'b0;
      1: force dut.timer0_pready = 1'b0;
      2: force dut.uart_pready   = 1'b0;
      3: force dut.i_gpio_apb_wrap.s_bridge_pready = 1'b0;
      4: force dut.spi_pready    = 1'b0;
      5: force dut.timer1_pready = 1'b0;
      6: force dut.i_axi_lite_to_apb.apb_rresp_ready = 1'b0;
      default: begin
        tb_fail++;
        $display("[TB]   FAIL  CMD_STALL with unknown target %0d", t);
      end
    endcase
    stall_active = 1'b1;
    stall_target = t;
    if (verbose)
      $display("[TB]   stall  %s held low (cyc %0d)", stall_name(t), cyc_cnt);
  endtask

  // A `release` on a variable only restores the driver's value when the driver
  // is re-evaluated. Check a few cycles later that it really did, so a silent
  // simulator difference cannot be mistaken for a monitor bug.
  always @(posedge clk) begin
    if (rel_check_armed && cyc_cnt >= rel_check_at) begin
      rel_check_armed = 1'b0;
      tb_check($sformatf("%s returned to %0b after release (now %0b)",
                         stall_name(stall_target), stall_pre_val, stall_sig(stall_target)),
               stall_sig(stall_target) === stall_pre_val);
    end
  end

  // ───────────────────────────────────────────────────────────────────────
  //  Independent APB timing: consecutive cycles the slave held PREADY low
  //  inside one ACCESS phase. At an unblocked fire this must equal the
  //  configured threshold - 1; at a blocked fire it must be 0.
  // ───────────────────────────────────────────────────────────────────────
  int unsigned wait_cnt [NUM_APB_SLAVES];

  always_ff @(posedge clk) begin
    for (int i = 0; i < NUM_APB_SLAVES; i++) begin
      if (mon_waiting[i]) wait_cnt[i] <= wait_cnt[i] + 1;
      else                wait_cnt[i] <= 0;
    end
  end

  always @(posedge clk) begin
    for (int i = 0; i < NUM_APB_SLAVES; i++) begin
      if (mon_pulse[i] === 1'b1) begin
        mon_cnt[i]++;
        mon_total[i]++;
        if (verbose)
          $display("[TB]   fire   %s after %0d wait cycles%s (cyc %0d)",
                   mon_name(i), wait_cnt[i], mon_blocked[i] ? " [blocked]" : "", cyc_cnt);

        if (mon_blocked[i] === 1'b1)
          tb_check($sformatf("%s blocked abort is immediate (%0d wait cycles)",
                             mon_name(i), wait_cnt[i]), wait_cnt[i] == 0);
        else
          tb_check($sformatf("%s aborted at exactly %0d cycles (threshold %0d)",
                             mon_name(i), wait_cnt[i] + 1, APB_THRESH[i]),
                   wait_cnt[i] == APB_THRESH[i] - 1);

        // real PREADY wins: never override a slave that answered
        tb_check($sformatf("%s did not fire against a ready slave", mon_name(i)),
                 slv_pready[i] === 1'b0);
        // the bridge is answered with an error, the slave is left alone
        tb_check($sformatf("%s drives PREADY+PSLVERR to the bridge only", mon_name(i)),
                 mst_pready[i] === 1'b1 && mst_pslverr[i] === 1'b1 &&
                 dut.apb_resp[i].prdata === APB_TIMEOUT_DATA);
      end
    end
  end

  // ───────────────────────────────────────────────────────────────────────
  //  Independent AXI timing and beat conservation (core master port)
  // ───────────────────────────────────────────────────────────────────────
  wire core_ar_hs = dut.core_axi_req.ar_valid  && dut.core_axi_resp.ar_ready;
  wire core_r_hs  = dut.core_axi_resp.r_valid  && dut.core_axi_req.r_ready;
  wire core_aw_hs = dut.core_axi_req.aw_valid  && dut.core_axi_resp.aw_ready;
  wire core_w_hs  = dut.core_axi_req.w_valid   && dut.core_axi_resp.w_ready;
  wire core_b_hs  = dut.core_axi_resp.b_valid  && dut.core_axi_req.b_ready;

  wire xbar_ar_hs = dut.xbar_slv_req[0].ar_valid  && dut.xbar_slv_resp[0].ar_ready;
  wire xbar_r_hs  = dut.xbar_slv_resp[0].r_valid  && dut.xbar_slv_req[0].r_ready;
  wire xbar_aw_hs = dut.xbar_slv_req[0].aw_valid  && dut.xbar_slv_resp[0].aw_ready;
  wire xbar_w_hs  = dut.xbar_slv_req[0].w_valid   && dut.xbar_slv_resp[0].w_ready;
  wire xbar_b_hs  = dut.xbar_slv_resp[0].b_valid  && dut.xbar_slv_req[0].b_ready;

  int unsigned n_core_ar, n_core_r, n_core_aw, n_core_w, n_core_b;
  int unsigned n_xbar_ar, n_xbar_r, n_xbar_aw, n_xbar_w, n_xbar_b;

  logic        rd_busy_q, wr_busy_q;
  int unsigned rd_wait_q, wr_wait_q;
  int unsigned rd_fire_wait, wr_fire_wait;

  always_ff @(posedge clk or negedge hard_rst_ni) begin
    if (!hard_rst_ni) begin
      rd_busy_q <= 1'b0; rd_wait_q <= 0;
      wr_busy_q <= 1'b0; wr_wait_q <= 0;
    end else begin
      if (!rd_busy_q) begin
        if (dut.core_axi_req.ar_valid) begin rd_busy_q <= 1'b1; rd_wait_q <= 0; end
      end else if (core_r_hs) begin
        rd_busy_q <= 1'b0;
      end else begin
        rd_wait_q <= rd_wait_q + 1;
      end

      if (!wr_busy_q) begin
        if (dut.core_axi_req.aw_valid) begin wr_busy_q <= 1'b1; wr_wait_q <= 0; end
      end else if (core_b_hs) begin
        wr_busy_q <= 1'b0;
      end else begin
        wr_wait_q <= wr_wait_q + 1;
      end
    end
  end

  always @(posedge clk) begin
    if (core_ar_hs) n_core_ar++;
    if (core_r_hs)  n_core_r++;
    if (core_aw_hs) n_core_aw++;
    if (core_w_hs)  n_core_w++;
    if (core_b_hs)  n_core_b++;
    if (xbar_ar_hs) n_xbar_ar++;
    if (xbar_r_hs)  n_xbar_r++;
    if (xbar_aw_hs) n_xbar_aw++;
    if (xbar_w_hs)  n_xbar_w++;
    if (xbar_b_hs)  n_xbar_b++;

    if (dut.axi_rd_timeout_pulse === 1'b1) begin
      mon_cnt[7]++;
      mon_total[7]++;
      rd_fire_wait = rd_wait_q;
      if (verbose)
        $display("[TB]   fire   AXI read after %0d outstanding cycles (cyc %0d)",
                 rd_wait_q, cyc_cnt);
      // Every core transaction decodes as the APB region, so the threshold in
      // force is always AXI_THRESH_APB. +/-8 covers the one-cycle difference
      // between this counter and the monitor's own.
      tb_check($sformatf("AXI read aborted near the %0d cycle threshold (measured %0d)",
                         AXI_THRESH_APB, rd_wait_q),
               rd_wait_q >= AXI_THRESH_APB - 8 && rd_wait_q <= AXI_THRESH_APB + 8);
      tb_check("AXI read abort did not race a real R beat", !core_r_hs);
    end

    if (dut.axi_wr_timeout_pulse === 1'b1) begin
      mon_cnt[6]++;
      mon_total[6]++;
      wr_fire_wait = wr_wait_q;
      if (verbose)
        $display("[TB]   fire   AXI write after %0d outstanding cycles (cyc %0d)",
                 wr_wait_q, cyc_cnt);
      tb_check($sformatf("AXI write aborted near the %0d cycle threshold (measured %0d)",
                         AXI_THRESH_APB, wr_wait_q),
               wr_wait_q >= AXI_THRESH_APB - 8 && wr_wait_q <= AXI_THRESH_APB + 8);
      tb_check("AXI write abort did not race a real B beat", !core_b_hs);
    end
  end

  // ───────────────────────────────────────────────────────────────────────
  //  Bus error monitor on the core's port (every error must become a trap)
  // ───────────────────────────────────────────────────────────────────────
  int unsigned bus_err_cnt;

  always @(posedge clk) begin
    if (fw_running) begin
      if (core_b_hs && dut.core_axi_resp.b.resp !== 2'b00) begin
        bus_err_cnt++;
        if (verbose) $display("[BUS]  %s on write (cyc %0d)",
                              resp_name(dut.core_axi_resp.b.resp), cyc_cnt);
      end
      if (core_r_hs && dut.core_axi_resp.r.resp !== 2'b00) begin
        bus_err_cnt++;
        if (verbose) $display("[BUS]  %s on read (cyc %0d)",
                              resp_name(dut.core_axi_resp.r.resp), cyc_cnt);
      end
    end
  end

  // ───────────────────────────────────────────────────────────────────────
  //  Result words
  // ───────────────────────────────────────────────────────────────────────
  task automatic check_monitors(input int unsigned id, input int unsigned expect_cnt);
    bit    ok;
    string others;

    ok     = 1'b1;
    others = "";
    for (int i = 0; i < N_MON; i++) begin
      if (i == id) begin
        if (mon_cnt[i] != expect_cnt) ok = 1'b0;
      end else if (mon_cnt[i] != 0) begin
        ok     = 1'b0;
        others = $sformatf("%s %s=%0d", others, mon_name(i), mon_cnt[i]);
      end
    end

    if (ok) begin
      tb_pass++;
      if (verbose)
        $display("[TB]   PASS  monitor fires: %s = %0d, all others 0",
                 (id < N_MON) ? mon_name(id) : "none", expect_cnt);
    end else begin
      tb_fail++;
      $display("[TB]   FAIL  monitor fires: expected %s = %0d and all others 0",
               (id < N_MON) ? mon_name(id) : "none", expect_cnt);
      $display("[TB]         got  APB %0d %0d %0d %0d %0d %0d, AXI wr %0d, AXI rd %0d%s",
               mon_cnt[0], mon_cnt[1], mon_cnt[2], mon_cnt[3], mon_cnt[4], mon_cnt[5],
               mon_cnt[6], mon_cnt[7], (others == "") ? "" : $sformatf("  (%s)", others));
    end
  endtask

  task automatic handle_report(input logic [31:0] cmd);
    string       ip, nm, sub, full;
    logic [31:0] addr, exp, got;
    logic [7:0]  sticky_now;
    int unsigned row;

    ip   = fw_str(`DSRAM_W(RES_WORD + 1));
    nm   = fw_str(`DSRAM_W(RES_WORD + 2));
    sub  = fw_str(`DSRAM_W(RES_WORD + 3));
    addr = `DSRAM_W(RES_WORD + 4);
    exp  = `DSRAM_W(RES_WORD + 5);
    got  = `DSRAM_W(RES_WORD + 6);
    full = (ip == "") ? nm : $sformatf("%s.%s", ip, nm);
    // Resolved once into a plain variable: using a function call directly as
    // an index of ++ makes xmvlog warn (LVLFNC) about side effects.
    row  = row_of_ip(ip);

    case (cmd)
      CMD_PASS: begin
        fw_pass++;
        if (ip != "") row_pass[row]++;
        if (verbose)
          $display("[FW]   PASS  %s : %s @0x%08h = %0d", full, sub, addr, got);
      end
      CMD_FAIL: begin
        fw_fail++;
        if (ip != "") begin
          row_fail[row]++;
          row_detail[row] =
            $sformatf("%s\n[TB]           %s : %s : exp 0x%08h  got 0x%08h",
                      row_detail[row], full, sub, exp, got);
        end
        $display("[FW]   FAIL  %s : %s @0x%08h  exp 0x%08h (%0d)  got 0x%08h (%0d)",
                 full, sub, addr, exp, exp, got, got);
      end
      CMD_SECTION: begin
        last_section = nm;
        $display("[FW] ---- %s   (cyc %0d)", nm, cyc_cnt);
      end

      CMD_STALL:   apply_stall(addr[2:0]);

      CMD_RELEASE: begin
        release_all();
        stall_active    = 1'b0;
        // Late enough that the freed transaction has drained and the bus is
        // idle again; the firmware always idles for at least 64 cycles here.
        rel_check_armed = 1'b1;
        rel_check_at    = cyc_cnt + 32;
        if (verbose) $display("[TB]   release all forces (cyc %0d)", cyc_cnt);
      end

      CMD_MONCLR: begin
        for (int i = 0; i < N_MON; i++) mon_cnt[i] = 0;
      end

      CMD_MONCHK: check_monitors(addr[7:0], exp);

      CMD_STICKY: begin
        sticky_now = {axi_rd_timeout_sticky, axi_wr_timeout_sticky, apb_timeout_sticky};
        tb_check($sformatf("sticky status 0x%02h (expected 0x%02h)", sticky_now, exp[7:0]),
                 sticky_now === exp[7:0]);
      end

      CMD_DONE: begin
        done_pass  = addr;
        done_fail  = exp;
        done_traps = got;
        fw_done    = 1'b1;
      end

      default: begin
        tb_fail++;
        $display("[TB]   FAIL  unknown result command 0x%08h", cmd);
      end
    endcase
  endtask

  // The firmware writes CMD last; the arguments are already in the array.
  always @(posedge clk) begin
    if (fw_running && !fw_done &&
        dut.dsram_cs === 1'b1 && dut.dsram_we === 1'b1 &&
        dut.dsram_addr == RES_WORD)
      handle_report(dut.dsram_wdata);
  end

  // ───────────────────────────────────────────────────────────────────────
  //  Timer guard: a channel with CTRL.EN = 0 must never raise IRQ
  // ───────────────────────────────────────────────────────────────────────
  int unsigned timer_irq_violations, timer_irq_pulses;

  task automatic timer_guard(input string name, input logic [1:0] irq, input logic en);
    if (irq !== 2'b00) begin
      timer_irq_pulses++;
      if (en !== 1'b1) begin
        timer_irq_violations++;
        if (timer_irq_violations <= 5)
          $display("[TB]   FAIL  %s raised irq=2'b%02b while CTRL.EN=0 (cyc %0d)",
                   name, irq, cyc_cnt);
      end
    end
  endtask

  always @(posedge clk) begin
    if (core_running) begin
      timer_guard("TIMER0 CH0", `TMR(i_apb_timer0, 0).irq_o, `TMR(i_apb_timer0, 0).regs_q[1][0]);
      timer_guard("TIMER0 CH1", `TMR(i_apb_timer0, 1).irq_o, `TMR(i_apb_timer0, 1).regs_q[1][0]);
      timer_guard("TIMER1 CH0", `TMR(i_apb_timer1, 0).irq_o, `TMR(i_apb_timer1, 0).regs_q[1][0]);
      timer_guard("TIMER1 CH1", `TMR(i_apb_timer1, 1).irq_o, `TMR(i_apb_timer1, 1).regs_q[1][0]);
    end
  end

  // ───────────────────────────────────────────────────────────────────────
  //  SPI chip-select checks
  // ───────────────────────────────────────────────────────────────────────
  int unsigned cs_both_low_cnt, cs0_runtime_sel_cnt;
  always @(posedge clk)
    if (spi_csn0_o === 1'b0 && spi_csn1_o === 1'b0) cs_both_low_cnt++;
  always @(negedge spi_csn0_o)
    if (fw_running) cs0_runtime_sel_cnt++;

  // ───────────────────────────────────────────────────────────────────────
  //  Flash backdoor readback
  // ───────────────────────────────────────────────────────────────────────
  task automatic flash_read_word(input int unsigned word_addr, output logic [31:0] data);
    integer b0, b1, b2, b3;
    u_flash.memory_features_i0.read_mem_w(b0, word_addr * 4 + 0);
    u_flash.memory_features_i0.read_mem_w(b1, word_addr * 4 + 1);
    u_flash.memory_features_i0.read_mem_w(b2, word_addr * 4 + 2);
    u_flash.memory_features_i0.read_mem_w(b3, word_addr * 4 + 3);
    data = {b3[7:0], b2[7:0], b1[7:0], b0[7:0]};
  endtask

  // ───────────────────────────────────────────────────────────────────────
  //  Main sequence
  // ───────────────────────────────────────────────────────────────────────
  logic [31:0] golden_i [0:FW_NUM_INSTR_WORDS-1];
  logic [31:0] golden_d [0:FW_NUM_DATA_WORDS-1];

  initial begin
    longint unsigned wcnt;
    logic [31:0]     fw;
    int unsigned     mism;

    verbose      = $test$plusargs("VERBOSE");
    last_section = "(none)";

    // Waveform database, written on every run (no command-line flag).
    `ifdef XCELIUM
      $shm_open("soc_montest_tb.shm");
      $shm_probe(soc_montest_tb, "ASMC");
      $display("[TB] waveforms -> soc_montest_tb.shm");
    `else
      $dumpfile("soc_montest_tb.vcd");
      $dumpvars(0, soc_montest_tb);
      $display("[TB] waveforms -> soc_montest_tb.vcd");
    `endif

    $readmemh(IMEM_HEX, golden_i);
    $readmemh(DMEM_HEX, golden_d);

    hard_rst_ni = 1'b0;
    soft_rst_ni = 1'b1;
    repeat (10) @(posedge clk);

    $display("[TB] --- RISCFORGE SoC — bus timeout monitor test");
    $display("[TB]  Flash image : %s", FLASH_IMAGE);
    $display("[TB]  Image       : %0d ISRAM words + %0d DSRAM words",
             FW_NUM_INSTR_WORDS, FW_NUM_DATA_WORDS);
    $display("[TB]  Thresholds  : APB %0d %0d %0d %0d %0d %0d,  AXI apb %0d / other %0d",
             APB_THRESH[0], APB_THRESH[1], APB_THRESH[2], APB_THRESH[3],
             APB_THRESH[4], APB_THRESH[5], AXI_THRESH_APB, AXI_THRESH_DFLT);

    // ── Phase A: flash preload ────────────────────────────────────────
    $display("[TB] --- A: flash image preload");
    flash_read_word(0, fw);
    tb_check($sformatf("flash word 0 = 0x%08h (expected 0x%08h)", fw, golden_i[0]),
             fw === golden_i[0]);
    flash_read_word(IMAGE_WORDS - 1, fw);
    tb_check($sformatf("flash last word = 0x%08h (expected 0x%08h)",
                       fw, golden_d[FW_NUM_DATA_WORDS-1]),
             fw === golden_d[FW_NUM_DATA_WORDS-1]);
    if (tb_fail != 0) begin
      $display("[TB]   Flash preload failed: check that build.py ran and that the working");
      $display("[TB]   directory is RTL_SOC/ (image path %s).", FLASH_IMAGE);
    end

    // ── Phase B: cold boot ────────────────────────────────────────────
    $display("[TB] --- B: cold boot from SPI flash");
    hard_rst_ni = 1'b1;
    wcnt = 0;
    while (!boot_done && wcnt < BOOT_TIMEOUT_CYCLES) begin
      @(posedge clk);
      wcnt++;
      if (wcnt % 200_000 == 0)
        $display("[TB]   ... booting, cyc %0d, bootloader %s, word %0d of %0d",
                 cyc_cnt, dut.i_bootloader.state_q.name(),
                 dut.i_bootloader.word_cnt_q, IMAGE_WORDS);
    end
    if (!boot_done) begin
      $display("[TB]   FAIL  boot_done not asserted after %0d cycles (bootloader %s, word %0d)",
               BOOT_TIMEOUT_CYCLES, dut.i_bootloader.state_q.name(), dut.i_bootloader.word_cnt_q);
      tb_fail++;
      summary();
    end
    $display("[TB]   boot_done @cyc %0d", cyc_cnt);

    // ── Phase C: image placement ──────────────────────────────────────
    $display("[TB] --- C: image placement in ISRAM / DSRAM");
    mism = 0;
    for (int i = 0; i < FW_NUM_INSTR_WORDS; i++)
      if (`ISRAM_W(i) !== golden_i[i]) begin
        if (mism < 5) $display("[TB]   ISRAM[%0d] = 0x%08h, expected 0x%08h",
                               i, `ISRAM_W(i), golden_i[i]);
        mism++;
      end
    tb_check($sformatf("ISRAM holds all %0d instruction words (%0d mismatches)",
                       FW_NUM_INSTR_WORDS, mism), mism == 0);
    mism = 0;
    for (int i = RES_WORDS; i < FW_NUM_DATA_WORDS; i++)
      if (`DSRAM_W(i) !== golden_d[i]) begin
        if (mism < 5) $display("[TB]   DSRAM[%0d] = 0x%08h, expected 0x%08h",
                               i, `DSRAM_W(i), golden_d[i]);
        mism++;
      end
    tb_check($sformatf("DSRAM holds data words %0d..%0d (%0d mismatches)",
                       RES_WORDS, FW_NUM_DATA_WORDS - 1, mism), mism == 0);

    // All monitors must be idle before the firmware starts.
    tb_check($sformatf("no monitor fired during boot (sticky 0x%02h)",
                       {axi_rd_timeout_sticky, axi_wr_timeout_sticky, apb_timeout_sticky}),
             {axi_rd_timeout_sticky, axi_wr_timeout_sticky, apb_timeout_sticky} === 8'h00);

    // ── Phase D: firmware run ─────────────────────────────────────────
    $display("[TB] --- D: bus timeout monitor firmware");
    run_start_cyc = cyc_cnt;
    fw_running    = 1'b1;
    wcnt = 0;
    while (!fw_done && wcnt < RUN_TIMEOUT_CYCLES) begin
      @(posedge clk);
      wcnt++;
    end
    if (!fw_done) begin
      tb_fail++;
      $display("[TB]   FAIL  firmware did not finish within %0d cycles", RUN_TIMEOUT_CYCLES);
      $display("[TB]         last section : %s", last_section);
      $display("[TB]         PC           : 0x%08h", `CORE_PC);
      $display("[TB]         stall active : %0d (%s)", stall_active, stall_name(stall_target));
      $display("[TB]         AXI outstanding: rd %0d (%0d cyc), wr %0d (%0d cyc)",
               rd_busy_q, rd_wait_q, wr_busy_q, wr_wait_q);
    end

    summary();
  end

  // ───────────────────────────────────────────────────────────────────────
  //  Summary
  // ───────────────────────────────────────────────────────────────────────
  // Printed on every run, not only with +VERBOSE: this table is the statement
  // of which monitor was exercised, how often it aborted, and what failed.
  task automatic print_coverage();
    int unsigned fires, n_chk, n_bad;

    n_bad = 0;

    $display("[TB] ------------------------------------------------------------------");
    $display("[TB]  MONITOR COVERAGE");
    $display("[TB] ------------------------------------------------------------------");
    $display("[TB]   MONITOR                    THRESHOLD   FIRES  EXP  CHECKS  RESULT");
    for (int r = 0; r < N_ROWS; r++) begin
      n_chk = row_pass[r] + row_fail[r];
      if (r < NUM_APB_SLAVES) begin
        fires = mon_total[r];
        $display("[TB]   %-25s %9d  %6d %4d  %6d  %s",
                 row_name(r), APB_THRESH[r], fires, EXP_FIRES[r], n_chk,
                 (row_fail[r] == 0 && fires == EXP_FIRES[r]) ? "PASS" :
                 $sformatf("FAIL (%0d)", row_fail[r]));
        if (fires != EXP_FIRES[r])
          $display("[TB]           aborted %0d times, expected %0d", fires, EXP_FIRES[r]);
      end else if (r == 6) begin
        fires = mon_total[6] + mon_total[7];
        $display("[TB]   %-25s %9d  %6d %4d  %6d  %s",
                 row_name(r), AXI_THRESH_APB, fires, EXP_FIRES[6] + EXP_FIRES[7], n_chk,
                 (row_fail[r] == 0 && fires == EXP_FIRES[6] + EXP_FIRES[7]) ? "PASS" :
                 $sformatf("FAIL (%0d)", row_fail[r]));
        $display("[TB]           write %0d of %0d, read %0d of %0d",
                 mon_total[6], EXP_FIRES[6], mon_total[7], EXP_FIRES[7]);
      end else begin
        $display("[TB]   %-25s %9s  %6s %4s  %6d  %s",
                 row_name(r), "-", "-", "-", n_chk,
                 (row_fail[r] == 0) ? "PASS" : $sformatf("FAIL (%0d)", row_fail[r]));
      end
      if (row_fail[r] != 0) begin
        n_bad++;
        $display("%s", row_detail[r]);
      end
    end
    $display("[TB] ------------------------------------------------------------------");

    for (int m = 0; m < N_MON; m++)
      tb_check($sformatf("%s aborted exactly %0d times (saw %0d)",
                         mon_name(m), EXP_FIRES[m], mon_total[m]),
               mon_total[m] == EXP_FIRES[m]);
    tb_check($sformatf("no monitor row failed (%0d of %0d rows)", n_bad, N_ROWS), n_bad == 0);
    $display("[TB] ------------------------------------------------------------------");
  endtask

  task automatic summary();
    repeat (5) @(posedge clk);

    print_coverage();

    $display("[TB] --- E: TB-side checks");
    if (fw_done) begin
      tb_check($sformatf("firmware PASS total matches (fw %0d, tb %0d)", done_pass, fw_pass),
               done_pass == fw_pass);
      tb_check($sformatf("firmware FAIL total matches (fw %0d, tb %0d)", done_fail, fw_fail),
               done_fail == fw_fail);
      tb_check($sformatf("every core bus error became a trap (%0d errors, %0d traps)",
                         bus_err_cnt, done_traps), bus_err_cnt == done_traps);
    end

    tb_check($sformatf("no force left applied at the end (%0d)", stall_active), !stall_active);

    tb_check($sformatf("core port: every AR answered by one R (%0d / %0d)", n_core_ar, n_core_r),
             n_core_ar == n_core_r);
    tb_check($sformatf("core port: every AW answered by one B (%0d / %0d)", n_core_aw, n_core_b),
             n_core_aw == n_core_b);
    tb_check($sformatf("core port: AW and W beats match (%0d / %0d)", n_core_aw, n_core_w),
             n_core_aw == n_core_w);
    tb_check($sformatf("crossbar port: every AR answered by one R (%0d / %0d)", n_xbar_ar, n_xbar_r),
             n_xbar_ar == n_xbar_r);
    tb_check($sformatf("crossbar port: every AW answered by one B (%0d / %0d)", n_xbar_aw, n_xbar_b),
             n_xbar_aw == n_xbar_b);
    tb_check($sformatf("crossbar port: AW and W beats match (%0d / %0d)", n_xbar_aw, n_xbar_w),
             n_xbar_aw == n_xbar_w);

    tb_check($sformatf("no timer IRQ while CTRL.EN=0 (%0d violations, %0d IRQ cycles)",
                       timer_irq_violations, timer_irq_pulses), timer_irq_violations == 0);
    tb_check($sformatf("SPI CS0 and CS1 never low together (%0d cycles)", cs_both_low_cnt),
             cs_both_low_cnt == 0);
    tb_check($sformatf("SPI CS1 selected %0d times by the firmware (expected %0d)",
                       spi1_select_cnt, SPI1_EXPECTED_SELECTS),
             spi1_select_cnt == SPI1_EXPECTED_SELECTS);
    tb_check($sformatf("SPI CS0 (flash) not selected at runtime (%0d)", cs0_runtime_sel_cnt),
             cs0_runtime_sel_cnt == 0);

    $display("[TB] ------------------------------------------------------------------");
    $display("[TB]  Monitor fires  : APB %0d %0d %0d %0d %0d %0d | AXI wr %0d, rd %0d",
             mon_total[0], mon_total[1], mon_total[2], mon_total[3],
             mon_total[4], mon_total[5], mon_total[6], mon_total[7]);
