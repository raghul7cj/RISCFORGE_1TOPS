// =============================================================================
// RISCFORGE 1TOPS — Peripheral Register Access Testbench
// =============================================================================
// Boots the full riscforge_soc_subsystem from the Infineon S25FS512S flash
// model, then runs the register-test firmware (ips/RTL_SOC/mem/regtest/regtest.c)
// on the real RV32 core. Every register of I2C, Timer 0, UART, GPIO, SPI and
// Timer 1 is accessed through the real path:
//     core LSU -> hybrid_mem_interface -> axi_lite_xbar -> axi_lite_to_apb -> IP
//
// Firmware -> TB result words (DSRAM 0x0002_0000, 7 words)
//   +0 CMD   written last; the TB acts on this store
//   +4 IP    pointer to IP name string  (strings live in DSRAM .rodata)
//   +8 NAME  pointer to register name string
//  +12 SUB   pointer to check description string
//  +16 ADDR / +20 EXP / +24 GOT
//   CMD 1 PASS, 2 FAIL, 3 SECTION, 4 BUSRESP, 5 UART_TXMON, 6 UART_TXCHK,
//       7 UART_RXSEND, 0xD0 DONE
//
// Checks done by the TB itself (independent of the firmware)
//   - Flash preload and image placement in ISRAM / DSRAM after boot
//   - BUSRESP: for every access the firmware expects to fault, the AXI response
//     seen on the core's crossbar port must be at that address and of the
//     expected type (SLVERR from the peripheral vs DECERR from the APB bridge).
//     The core cannot tell these apart; it traps on both.
//   - Every bus error was expected (count of errors == count of BUSRESP checks)
//   - Timer guard (Issue 4 fix): no timer IRQ while that channel's CTRL.EN = 0
//   - SPI: CS0 and CS1 never low together; CS1 selected exactly once; the
//     flash (CS0) is not selected by the firmware
//   - Firmware's own PASS/FAIL totals match what the TB received
//   - UART pins: bytes the firmware sends are decoded on uart_sout_o (value,
//     start and stop bit), and every decoded byte is checked; bytes the
//     firmware asks for are driven on uart_sin_i
//
// Board model around the DUT
//   - SPI CS0: S25FS512S flash holding the image (boot)
//   - SPI CS1: simple slave model that shifts out SPI1_PATTERN, MSB first,
//              changing on SCK falling edges (mode 0, like the flash)
//   - GPIO:    pads looped back, gpio_in_i = gpio_out_o
//   - I2C:     open-drain SCL/SDA with pull-ups, no slave
//   - UART:    RX idle high; an 8N1 receiver on the TX pin and transmitter on
//              the RX pin, driven by mailbox commands 5/6/7 (the firmware also
//              uses the internal MCR loopback)
//
// -----------------------------------------------------------------------------
// Build the firmware + flash image first (needs the RISC-V GCC toolchain):
//     cd ips/RTL_SOC/mem/regtest && python build.py
// This also writes fw_params.svh (word counts + image paths), included below.
//
// Test filelist: ips/RTL_SOC/tests/regtest.f.
// Run from ips/RTL_SOC/sim/ (all relative paths assume it):
//     xrun -f ../tests/regtest.f -l logs/regtest.log            # normal run
//     xrun -f ../tests/regtest.f -l logs/regtest.log +VERBOSE   # also print every PASS
// Waveforms are written every run to soc_regtest_tb.shm; no flag needed.
// =============================================================================
`timescale 1ns/1ps

module soc_regtest_tb;

  import gpio_reg_pkg::GPIOCount;

  // Generated by build.py: FW_NUM_INSTR_WORDS, FW_NUM_DATA_WORDS, FW_RESULT_ADDR,
  // FW_FLASH_IMAGE / FW_IMEM_HEX / FW_DMEM_HEX. Resolved through the
  // +incdir+../mem/regtest line in tests/regtest.f.
  `include "fw_params.svh"

  // ───────────────────────────────────────────────────────────────────────
  //  Configuration
  // ───────────────────────────────────────────────────────────────────────
  localparam int unsigned TIMER0_CNT           = 2;
  localparam int unsigned TIMER1_CNT           = 2;
  localparam int unsigned FLASH_POWERUP_CYCLES = 30_000;   // S25FS512S tPU = 300 us
  localparam time         CLK_PERIOD           = 10ns;     // 100 MHz

  localparam int unsigned IMAGE_WORDS = FW_NUM_INSTR_WORDS + FW_NUM_DATA_WORDS;

  // Boot = 16384-word SRAM clear (~5 cycles/word) + 30k flash power-up
  //        + ~320 cycles per image word over SPI (CLKDIV = 4).
  localparam longint unsigned BOOT_TIMEOUT_CYCLES = 200_000 + 400 * IMAGE_WORDS;
  localparam longint unsigned RUN_TIMEOUT_CYCLES  = 3_000_000;

  localparam logic [31:0] ISRAM_BASE  = 32'h0001_0000;
  localparam logic [31:0] DSRAM_BASE  = 32'h0002_0000;
  localparam int unsigned DSRAM_WORDS = 8192;
  localparam int unsigned RES_WORD   = (FW_RESULT_ADDR - DSRAM_BASE) >> 2;
  localparam int unsigned RES_WORDS  = 16;   // .result words is 64 B (link.ld)

  // Image paths come from fw_params.svh (firmware selected in tests/regtest.f)
  localparam string FLASH_IMAGE = FW_FLASH_IMAGE;
  localparam string IMEM_HEX    = FW_IMEM_HEX;
  localparam string DMEM_HEX    = FW_DMEM_HEX;
  localparam string OTP_FILE    = "../../spi_slave_infinion/S25fs512s/model/s25fs512sOTP.mem";

  // Must match spi_special() in regtest.c
  localparam logic [63:0] SPI1_PATTERN = 64'hC3A5_5A3C_0F1E_2D4B;

  // Result-word commands (regtest.c)
  localparam logic [31:0] CMD_PASS    = 32'h01;
  localparam logic [31:0] CMD_FAIL    = 32'h02;
  localparam logic [31:0] CMD_SECTION = 32'h03;
  localparam logic [31:0] CMD_BUSRESP = 32'h04;
  localparam logic [31:0] CMD_UART_TXMON  = 32'h05;  // arm TX-pin receiver, EXP = clocks/bit
  localparam logic [31:0] CMD_UART_TXCHK  = 32'h06;  // byte ADDR on the TX pin must be EXP
  localparam logic [31:0] CMD_UART_RXSEND = 32'h07;  // drive byte EXP on RX pin, GOT = clocks/bit
  localparam logic [31:0] CMD_DONE    = 32'hD0;

  // ───────────────────────────────────────────────────────────────────────
  //  Clock & reset
  // ───────────────────────────────────────────────────────────────────────
  logic clk;
  logic hard_rst_ni;
  logic soft_rst_ni;

  initial clk = 1'b0;
  always #(CLK_PERIOD/2) clk = ~clk;

  // 2-state, starts at 0 (no initial assignment: single-driver rule, see
  // soc_timer0_boot_run_tb.sv)
  longint unsigned cyc_cnt;
  always_ff @(posedge clk) cyc_cnt <= cyc_cnt + 1;

  // ───────────────────────────────────────────────────────────────────────
  //  DUT pins
  // ───────────────────────────────────────────────────────────────────────
  localparam int unsigned NR_GPIOS = GPIOCount;

  logic                        boot_done;

  wire                         i2c_scl_i, i2c_sda_i;
  logic                        i2c_scl_o, i2c_scl_oen_o;
  logic                        i2c_sda_o, i2c_sda_oen_o;
  logic                        i2c_interrupt_o;

  logic [(TIMER0_CNT*2)-1:0]   timer0_irq;
  logic [(TIMER1_CNT*2)-1:0]   timer1_irq;

  logic                        uart_sin_i;
  logic                        uart_sout_o, uart_int_o;

  wire  [NR_GPIOS-1:0]         gpio_in_i;
  logic [NR_GPIOS-1:0]         gpio_out_o, gpio_tx_en_o, gpio_in_sync_o;
  logic                        gpio_global_interrupt_o;
  logic [NR_GPIOS-1:0]         gpio_pin_level_interrupts_o;

  logic                        spi_clk_o, spi_csn0_o, spi_csn1_o, spi_sdo0_o;
  wire                         spi_sdi1_i;
  logic [1:0]                  spi_events_o;

  // Bus timeout monitor status. Nothing here should ever stall, so these must
  // stay at zero for the whole run: this test doubles as the no-false-timeout
  // check for the monitors across every register access.
  logic [5:0]                  apb_timeout_sticky;
  logic                        axi_wr_timeout_sticky, axi_rd_timeout_sticky;

  initial uart_sin_i = 1'b1;           // UART RX idle

  // ───────────────────────────────────────────────────────────────────────
  //  UART pin models (8N1, LSB first), armed by the firmware mailbox:
  //   - receiver on uart_sout_o: decodes every frame after CMD_UART_TXMON
  //   - transmitter on uart_sin_i: sends one byte per CMD_UART_RXSEND
  // ───────────────────────────────────────────────────────────────────────
  bit          uart_mon_armed;
  int unsigned uart_bit_cyc;
  logic [7:0]  uart_tx_q [$];          // bytes seen on the TX pin
  bit          uart_tx_frame_ok [$];   // start bit low and stop bit high
  int unsigned uart_tx_checked;

  always @(negedge uart_sout_o) begin
    if (uart_mon_armed && uart_bit_cyc != 0) begin : tx_frame
      logic [7:0] d;
      bit         ok;
      repeat (uart_bit_cyc / 2) @(posedge clk);     // middle of the start bit
      ok = (uart_sout_o === 1'b0);
      for (int i = 0; i < 8; i++) begin
        repeat (uart_bit_cyc) @(posedge clk);
        d[i] = uart_sout_o;
      end
      repeat (uart_bit_cyc) @(posedge clk);         // middle of the stop bit
      ok = ok && (uart_sout_o === 1'b1);
      uart_tx_q.push_back(d);
      uart_tx_frame_ok.push_back(ok);
    end
  end

  task automatic uart_drive_byte(input logic [7:0] d, input int unsigned bit_cyc);
    uart_sin_i = 1'b0;                              // start bit
    repeat (bit_cyc) @(posedge clk);
    for (int i = 0; i < 8; i++) begin
      uart_sin_i = d[i];
      repeat (bit_cyc) @(posedge clk);
    end
    uart_sin_i = 1'b1;                              // stop bit, then idle
    repeat (bit_cyc) @(posedge clk);
  endtask

  // I2C: open-drain bus, pull-ups, no slave. The DUT drives a line only when
  // its output enable (active low) is 0.
  tri1 i2c_scl_bus, i2c_sda_bus;
  assign i2c_scl_bus = (i2c_scl_oen_o === 1'b0) ? i2c_scl_o : 1'bz;
  assign i2c_sda_bus = (i2c_sda_oen_o === 1'b0) ? i2c_sda_o : 1'bz;
  assign i2c_scl_i   = i2c_scl_bus;
  assign i2c_sda_i   = i2c_sda_bus;

  // GPIO: pads looped back so the firmware can drive its own inputs
  assign gpio_in_i = gpio_out_o;

  // ───────────────────────────────────────────────────────────────────────
  //  SPI: flash on CS0, slave model on CS1, MISO selected by chip select
  // ───────────────────────────────────────────────────────────────────────
  wire flash_si, flash_so, flash_wpn, flash_resetn;
  assign flash_si     = spi_sdo0_o;
  assign flash_wpn    = 1'b1;
  assign flash_resetn = 1'b1;

  s25fs512s #(
    .UserPreload   ( 1           ),
    .mem_file_name ( FLASH_IMAGE ),
    .otp_file_name ( OTP_FILE    )
  ) u_flash (
    .SI       ( flash_si     ),
    .SO       ( flash_so     ),
    .SCK      ( spi_clk_o    ),
    .CSNeg    ( spi_csn0_o   ),
    .WPNeg    ( flash_wpn    ),
    .RESETNeg ( flash_resetn )
  );

  // CS1 slave: loads SPI1_PATTERN when selected, presents the MSB on MISO,
  // shifts on every SCK falling edge; the master samples on the rising edge.
  logic [63:0] spi1_shreg;
  int unsigned spi1_select_cnt;
  always @(negedge spi_csn1_o) begin
    spi1_shreg <= SPI1_PATTERN;
    spi1_select_cnt++;
  end
  always @(negedge spi_clk_o)
    if (spi_csn1_o === 1'b0) spi1_shreg <= {spi1_shreg[62:0], 1'b0};

  assign spi_sdi1_i = (spi_csn1_o === 1'b0) ? spi1_shreg[63] : flash_so;

  // ───────────────────────────────────────────────────────────────────────
  //  DUT
  // ───────────────────────────────────────────────────────────────────────
  riscforge_soc_subsystem #(
    .TIMER0_CNT           ( TIMER0_CNT           ),
    .TIMER1_CNT           ( TIMER1_CNT           ),
    .SPI_BUFFER_DEPTH     ( 10                   ),
    .NUM_INSTR_WORDS      ( FW_NUM_INSTR_WORDS   ),
    .NUM_DATA_WORDS       ( FW_NUM_DATA_WORDS    ),
    .FLASH_POWERUP_CYCLES ( FLASH_POWERUP_CYCLES )
  ) dut (
    .clk_i                       ( clk                         ),
    .hard_rst_ni                 ( hard_rst_ni                 ),
    .soft_rst_ni                 ( soft_rst_ni                 ),
    .test_mode_i                 ( 1'b0                        ),
    .fetch_enable_i              ( 1'b1                        ),   // unused by the DUT
    .boot_addr_i                 ( 32'h0000_0000               ),   // unused by the DUT
    .boot_done_o                 ( boot_done                   ),

    .i2c_scl_i                   ( i2c_scl_i                   ),
    .i2c_scl_o                   ( i2c_scl_o                   ),
    .i2c_scl_oen_o               ( i2c_scl_oen_o               ),
    .i2c_sda_i                   ( i2c_sda_i                   ),
    .i2c_sda_o                   ( i2c_sda_o                   ),
    .i2c_sda_oen_o               ( i2c_sda_oen_o               ),
    .i2c_interrupt_o             ( i2c_interrupt_o             ),

    .timer0_irq_o                ( timer0_irq                  ),
    .timer1_irq_o                ( timer1_irq                  ),

    .uart_sin_i                  ( uart_sin_i                  ),
    .uart_sout_o                 ( uart_sout_o                 ),
    .uart_int_o                  ( uart_int_o                  ),

    .gpio_in_i                   ( gpio_in_i                   ),
    .gpio_out_o                  ( gpio_out_o                  ),
    .gpio_tx_en_o                ( gpio_tx_en_o                ),
    .gpio_in_sync_o              ( gpio_in_sync_o              ),
    .gpio_global_interrupt_o     ( gpio_global_interrupt_o     ),
    .gpio_pin_level_interrupts_o ( gpio_pin_level_interrupts_o ),

    .spi_clk_o                   ( spi_clk_o                   ),
    .spi_csn0_o                  ( spi_csn0_o                  ),
    .spi_csn1_o                  ( spi_csn1_o                  ),
    .spi_sdo0_o                  ( spi_sdo0_o                  ),
    .spi_sdi1_i                  ( spi_sdi1_i                  ),
    .spi_events_o                ( spi_events_o                ),

    .apb_timeout_sticky_o        ( apb_timeout_sticky          ),
    .axi_wr_timeout_sticky_o     ( axi_wr_timeout_sticky       ),
    .axi_rd_timeout_sticky_o     ( axi_rd_timeout_sticky       )
  );

  // ───────────────────────────────────────────────────────────────────────
  //  Hierarchical probes
  // ───────────────────────────────────────────────────────────────────────
  `define ISRAM_W(i)    dut.i_isram.u_imem.mem_array[i]
  `define DSRAM_W(i)    dut.i_dsram.mem[i]
  `define CORE_PC       dut.i_riscv_core.Fetch.PCF
  `define TMR(inst, ch) dut.inst.TIMER_GEN[ch].timer_i

  wire core_running = (dut.core_rst_n === 1'b1);

  // ───────────────────────────────────────────────────────────────────────
  //  Scoreboard state
  // ───────────────────────────────────────────────────────────────────────
  bit          verbose;
  bit          fw_running, fw_done;
  int unsigned fw_pass, fw_fail;                 // tallied from the result words
  int unsigned tb_pass, tb_fail;                 // TB's own checks
  int unsigned busresp_checks;
  logic [31:0] done_pass, done_fail, done_traps; // firmware's own totals
  string       last_section;
  longint unsigned run_start_cyc;

  task automatic tb_check(input string label, input bit cond);
    if (cond) begin
      tb_pass++;
      if (verbose) $display("[TB]   PASS  %s", label);
    end else begin
      tb_fail++;
      $display("[TB]   FAIL  %s", label);
    end
  endtask

  function automatic string resp_name(input logic [1:0] r);
    case (r)
      2'b00:   return "OKAY";
      2'b01:   return "EXOKAY";
      2'b10:   return "SLVERR";
      default: return "DECERR";
    endcase
  endfunction

  // Read a NUL-terminated string the firmware placed in DSRAM (.rodata).
  function automatic string fw_str(input logic [31:0] ptr);
    string       s;
    logic [31:0] a;
    logic [31:0] w;
    logic [7:0]  c;
    s = "";
    if (ptr == 32'h0) return s;
    if (ptr < DSRAM_BASE || ptr >= DSRAM_BASE + 4 * DSRAM_WORDS)
      return $sformatf("<ptr 0x%08h outside DSRAM>", ptr);
    for (int i = 0; i < 160; i++) begin
      a = ptr + i;
      if (a >= DSRAM_BASE + 4 * DSRAM_WORDS) break;
      w = `DSRAM_W((a - DSRAM_BASE) >> 2);
      c = w[8 * a[1:0] +: 8];
      if (c == 8'h00) break;
      s = $sformatf("%s%c", s, c);
    end
    return s;
  endfunction

  // ───────────────────────────────────────────────────────────────────────
  //  Per-register scoreboard
  // ───────────────────────────────────────────────────────────────────────
  // The golden register map lives HERE, not in the firmware. Every check the
  // firmware posts carries its IP and register name, so each one is filed
  // against its row; a register the firmware never touches then prints as
  // NOT EXERCISED instead of silently vanishing from the totals.
  //
  // Checks that are not a single register — address holes, aliases, deliberate
  // faults, multi-register sequences — go to a second table so they do not
  // dilute the register verdicts.
  string       rm_key  [$];      // "IP.NAME", in address order
  logic [31:0] rm_addr [$];
  string       rm_kind [$];

  int unsigned r_pass   [string];
  int unsigned r_fail   [string];
  string       r_detail [string];
  bit          r_known  [string];

  string       o_key    [$];
  int unsigned o_pass   [string];
  int unsigned o_fail   [string];
  string       o_detail [string];

  task automatic regdef(input string ip, input string name,
                        input logic [31:0] addr, input string kind);
    string k;
    k = $sformatf("%s.%s", ip, name);
    rm_key.push_back(k);
    rm_addr.push_back(addr);
    rm_kind.push_back(kind);
    r_known[k]  = 1'b1;
    r_pass[k]   = 0;
    r_fail[k]   = 0;
    r_detail[k] = "";
  endtask

  // Names must match the strings regtest.c posts (its reg_t tables, plus DLL /
  // DLM from uart_special and RXFIFO from spi_special).
  task automatic build_regmap();
    // apb_i2c.sv
    regdef("I2C", "PRE", 32'h4000_0000, "RW");
    regdef("I2C", "CTR", 32'h4000_0004, "RW");
    regdef("I2C", "RXR", 32'h4000_0008, "RO");
    regdef("I2C", "SR",  32'h4000_000C, "RO");
    regdef("I2C", "TXR", 32'h4000_0010, "RW");
    regdef("I2C", "CR",  32'h4000_0014, "CMD");

    // apb_timer.sv / timer.sv, two channels
    regdef("TIMER0", "CH0 VAL",  32'h4000_1000, "RW");
    regdef("TIMER0", "CH0 CTRL", 32'h4000_1004, "RW");
    regdef("TIMER0", "CH0 CMP",  32'h4000_1008, "RW");
    regdef("TIMER0", "CH1 VAL",  32'h4000_1010, "RW");
    regdef("TIMER0", "CH1 CTRL", 32'h4000_1014, "RW");
    regdef("TIMER0", "CH1 CMP",  32'h4000_1018, "RW");

    // obi_uart, 16550 layout. DLL / DLM alias RBR / IER when LCR.DLAB = 1.
    regdef("UART", "RBR", 32'h4000_2000, "RO");
    regdef("UART", "DLL", 32'h4000_2000, "RW");
    regdef("UART", "IER", 32'h4000_2004, "RW");
    regdef("UART", "DLM", 32'h4000_2004, "RW");
    regdef("UART", "IIR", 32'h4000_2008, "RO");
    regdef("UART", "LCR", 32'h4000_200C, "RW");
    regdef("UART", "MCR", 32'h4000_2010, "RW");
    regdef("UART", "LSR", 32'h4000_2014, "RO");
    // MSR (0x4000_2018) is not mapped here: the UART is used as a plain TX/RX
    // UART and the modem interface is unused, so regtest.c does not test it.
    // Known RTL issue (not fixed, unused feature): MSR reads 0x0F after reset
    // instead of 0x00. In obi_uart_modem.sv the sync instances i_sync_cts/dsr/
    // ri/cd use sync's default ResetValue = 0, while sync_*_n_q reset to 1, so
    // the delta bits d_cts/d_dsr/te_ri/d_cd latch into MSR right after reset.
    regdef("UART", "SCR", 32'h4000_201C, "RO");

    // gpio_reg_top.sv (reggen)
    regdef("GPIO", "INFO",                   32'h4000_3000, "RO");
    regdef("GPIO", "CFG",                    32'h4000_3004, "RW");
    regdef("GPIO", "GPIO_MODE_0",            32'h4000_3008, "RW");
    regdef("GPIO", "GPIO_MODE_1",            32'h4000_300C, "RW");
    regdef("GPIO", "GPIO_EN",                32'h4000_3080, "RW");
    regdef("GPIO", "GPIO_IN",                32'h4000_3100, "RO");
    regdef("GPIO", "GPIO_OUT",               32'h4000_3180, "RW");
    regdef("GPIO", "GPIO_SET",               32'h4000_3200, "CMD");
    regdef("GPIO", "GPIO_CLEAR",             32'h4000_3280, "CMD");
    regdef("GPIO", "GPIO_TOGGLE",            32'h4000_3300, "CMD");
    regdef("GPIO", "INTRPT_RISE_EN",         32'h4000_3380, "RW");
    regdef("GPIO", "INTRPT_FALL_EN",         32'h4000_3400, "RW");
    regdef("GPIO", "INTRPT_LVL_HIGH_EN",     32'h4000_3480, "RW");
    regdef("GPIO", "INTRPT_LVL_LOW_EN",      32'h4000_3500, "RW");
    regdef("GPIO", "INTRPT_STATUS",          32'h4000_3580, "W1C");
    regdef("GPIO", "INTRPT_RISE_STATUS",     32'h4000_3600, "W1C");
    regdef("GPIO", "INTRPT_FALL_STATUS",     32'h4000_3680, "W1C");
    regdef("GPIO", "INTRPT_LVL_HIGH_STATUS", 32'h4000_3700, "W1C");
    regdef("GPIO", "INTRPT_LVL_LOW_STATUS",  32'h4000_3780, "W1C");

    // apb_spi_master.sv, through the bootloader APB passthrough
    regdef("SPI", "STATUS", 32'h4000_4000, "CMD");
    regdef("SPI", "CLKDIV", 32'h4000_4004, "RW");
    regdef("SPI", "SPICMD", 32'h4000_4008, "RW");
    regdef("SPI", "SPIADR", 32'h4000_400C, "RW");
    regdef("SPI", "SPILEN", 32'h4000_4010, "RW");
    regdef("SPI", "SPIDUM", 32'h4000_4014, "RW");
    regdef("SPI", "TXFIFO", 32'h4000_4018, "WO");
    regdef("SPI", "RXFIFO", 32'h4000_4020, "RO");
    regdef("SPI", "INTCFG", 32'h4000_4024, "RW");
    regdef("SPI", "INTSTA", 32'h4000_4028, "RO");

    regdef("TIMER1", "CH0 VAL",  32'h4000_5000, "RW");
    regdef("TIMER1", "CH0 CTRL", 32'h4000_5004, "RW");
    regdef("TIMER1", "CH0 CMP",  32'h4000_5008, "RW");
    regdef("TIMER1", "CH1 VAL",  32'h4000_5010, "RW");
    regdef("TIMER1", "CH1 CTRL", 32'h4000_5014, "RW");
    regdef("TIMER1", "CH1 CMP",  32'h4000_5018, "RW");
  endtask

  task automatic score(input string key, input string sub, input bit ok,
                       input logic [31:0] exp, input logic [31:0] got);
    if (r_known.exists(key)) begin
      if (ok) r_pass[key]++;
      else begin
        r_fail[key]++;
        r_detail[key] = $sformatf("%s\n[TB]           %s : exp 0x%08h  got 0x%08h",
                                  r_detail[key], sub, exp, got);
      end
    end else begin
      if (!o_pass.exists(key)) begin
        o_key.push_back(key);
        o_pass[key]   = 0;
        o_fail[key]   = 0;
        o_detail[key] = "";
      end
      if (ok) o_pass[key]++;
      else begin
        o_fail[key]++;
        o_detail[key] = $sformatf("%s\n[TB]           %s : exp 0x%08h  got 0x%08h",
                                  o_detail[key], sub, exp, got);
      end
    end
  endtask

  // Printed on every run, not only with +VERBOSE: this table IS the statement
  // that every register was exercised and what its verdict was.
  task automatic print_coverage();
    string       k;
    int unsigned n_ex, n_ok, n_bad, n_miss, n_chk;

    n_ex = 0; n_ok = 0; n_bad = 0; n_miss = 0; n_chk = 0;

    $display("[TB] ------------------------------------------------------------------");
    $display("[TB]  REGISTER COVERAGE");
    $display("[TB] ------------------------------------------------------------------");
    $display("[TB]   ADDRESS      REGISTER                       KIND  CHECKS  RESULT");
    foreach (rm_key[i]) begin
      k     = rm_key[i];
      n_chk = r_pass[k] + r_fail[k];
      if (n_chk == 0) begin
        n_miss++;
        $display("[TB]   0x%08h   %-29s %-4s %6d  NOT EXERCISED",
                 rm_addr[i], k, rm_kind[i], 0);
      end else begin
        n_ex++;
        if (r_fail[k] == 0) begin
          n_ok++;
          $display("[TB]   0x%08h   %-29s %-4s %6d  PASS",
                   rm_addr[i], k, rm_kind[i], n_chk);
        end else begin
          n_bad++;
          $display("[TB]   0x%08h   %-29s %-4s %6d  FAIL (%0d)",
                   rm_addr[i], k, rm_kind[i], n_chk, r_fail[k]);
          $display("%s", r_detail[k]);
        end
      end
    end
    $display("[TB] ------------------------------------------------------------------");
    $display("[TB]   %0d registers mapped: %0d exercised, %0d PASS, %0d FAIL, %0d NOT EXERCISED",
             rm_key.size(), n_ex, n_ok, n_bad, n_miss);

    tb_check($sformatf("every mapped register was exercised (%0d of %0d)", n_ex, rm_key.size()),
             n_miss == 0);
    tb_check($sformatf("no register failed (%0d of %0d failed)", n_bad, rm_key.size()),
             n_bad == 0);

    $display("[TB] ------------------------------------------------------------------");
    $display("[TB]  OTHER CHECKS (holes, aliases, deliberate faults, sequences)");
    foreach (o_key[i]) begin
      k     = o_key[i];
      n_chk = o_pass[k] + o_fail[k];
      if (o_fail[k] == 0)
        $display("[TB]   %-42s %6d  PASS", k, n_chk);
      else begin
        $display("[TB]   %-42s %6d  FAIL (%0d)", k, n_chk, o_fail[k]);
        $display("%s", o_detail[k]);
      end
    end
    $display("[TB] ------------------------------------------------------------------");
  endtask

  // ───────────────────────────────────────────────────────────────────────
  //  Bus monitor on the core's crossbar port (SLV[0])
  // ───────────────────────────────────────────────────────────────────────
  logic [31:0]  bus_last_aw, bus_last_ar;
  logic [31:0]  bus_err_addr;
  logic [1:0]   bus_err_resp;
  bit           bus_err_is_wr, bus_err_pending;
  int unsigned  bus_rd_cnt, bus_wr_cnt, bus_err_cnt, bus_unexpected_err;

  // Registers by ABI name, for the diagnostic below.
  `define RF(n) dut.i_riscv_core.Decode.rf.Register[n]

  int unsigned rogue_dumps;

  task automatic note_bus_error(input logic [31:0] addr, input logic [1:0] resp, input bit is_wr);
    bus_err_cnt++;
    if (bus_err_pending) begin
      // previous error was never claimed by a BUSRESP check
      bus_unexpected_err++;
      $display("[BUS]  unexpected %s on %s @0x%08h (not checked by firmware)",
               resp_name(bus_err_resp), bus_err_is_wr ? "write" : "read", bus_err_addr);
      // An unexpected error means the core issued an address the firmware
      // never intended. Dump the machine state for the first few so the
      // faulting instruction can be identified without a waveform.
      if (rogue_dumps < 8) begin
        rogue_dumps++;
        $display("[BUS]    PC 0x%08h  ra 0x%08h  sp 0x%08h", `CORE_PC, `RF(1), `RF(2));
        $display("[BUS]    a0 0x%08h  a1 0x%08h  a2 0x%08h  a3 0x%08h",
                 `RF(10), `RF(11), `RF(12), `RF(13));
        $display("[BUS]    a4 0x%08h  a5 0x%08h  a6 0x%08h  a7 0x%08h",
                 `RF(14), `RF(15), `RF(16), `RF(17));
        $display("[BUS]    s2 0x%08h  s3 0x%08h  s4 0x%08h  t3 0x%08h",
                 `RF(18), `RF(19), `RF(20), `RF(28));
      end
    end
    bus_err_addr    = addr;
    bus_err_resp    = resp;
    bus_err_is_wr   = is_wr;
    bus_err_pending = 1'b1;
    if (verbose)
      $display("[BUS]  %s on %s @0x%08h (cyc %0d)", resp_name(resp),
               is_wr ? "write" : "read", addr, cyc_cnt);
  endtask

  always @(posedge clk) begin
    if (fw_running) begin
      if (dut.xbar_slv_req[0].aw_valid === 1'b1 && dut.xbar_slv_resp[0].aw_ready === 1'b1)
        bus_last_aw = dut.xbar_slv_req[0].aw.addr;
      if (dut.xbar_slv_req[0].ar_valid === 1'b1 && dut.xbar_slv_resp[0].ar_ready === 1'b1)
        bus_last_ar = dut.xbar_slv_req[0].ar.addr;

      if (dut.xbar_slv_resp[0].b_valid === 1'b1 && dut.xbar_slv_req[0].b_ready === 1'b1) begin
        bus_wr_cnt++;
        if (dut.xbar_slv_resp[0].b.resp !== 2'b00)
          note_bus_error(bus_last_aw, dut.xbar_slv_resp[0].b.resp, 1'b1);
      end
      if (dut.xbar_slv_resp[0].r_valid === 1'b1 && dut.xbar_slv_req[0].r_ready === 1'b1) begin
        bus_rd_cnt++;
        if (dut.xbar_slv_resp[0].r.resp !== 2'b00)
          note_bus_error(bus_last_ar, dut.xbar_slv_resp[0].r.resp, 1'b0);
      end
    end
  end

  // ───────────────────────────────────────────────────────────────────────
  //  Result words
  // ───────────────────────────────────────────────────────────────────────
  task automatic handle_report(input logic [31:0] cmd);
    string       ip, nm, sub, full;
    logic [31:0] addr, exp, got;

    ip   = fw_str(`DSRAM_W(RES_WORD + 1));
    nm   = fw_str(`DSRAM_W(RES_WORD + 2));
    sub  = fw_str(`DSRAM_W(RES_WORD + 3));
    addr = `DSRAM_W(RES_WORD + 4);
    exp  = `DSRAM_W(RES_WORD + 5);
    got  = `DSRAM_W(RES_WORD + 6);
    full = (ip == "") ? nm : $sformatf("%s.%s", ip, nm);

    case (cmd)
      CMD_PASS: begin
        fw_pass++;
        if (ip != "") score(full, sub, 1'b1, exp, got);
        if (verbose)
          $display("[FW]   PASS  %s : %s @0x%08h = 0x%08h", full, sub, addr, got);
      end
      CMD_FAIL: begin
        fw_fail++;
        if (ip != "") score(full, sub, 1'b0, exp, got);
        $display("[FW]   FAIL  %s : %s @0x%08h  exp 0x%08h  got 0x%08h",
                 full, sub, addr, exp, got);
      end
      CMD_SECTION: begin
        last_section = nm;
        $display("[FW] ---- %s   (cyc %0d)", nm, cyc_cnt);
      end
      CMD_BUSRESP: begin
        busresp_checks++;
        if (bus_err_pending && bus_err_addr == addr && bus_err_resp == exp[1:0]) begin
          tb_pass++;
          if (verbose)
            $display("[TB]   PASS  %s : bus response %s @0x%08h", full, resp_name(exp[1:0]), addr);
        end else begin
          tb_fail++;
          if (!bus_err_pending)
            $display("[TB]   FAIL  %s : expected %s @0x%08h, saw no bus error",
                     full, resp_name(exp[1:0]), addr);
          else
            $display("[TB]   FAIL  %s : expected %s @0x%08h, saw %s @0x%08h",
                     full, resp_name(exp[1:0]), addr, resp_name(bus_err_resp), bus_err_addr);
        end
        bus_err_pending = 1'b0;
      end
      CMD_UART_TXMON: begin
        uart_tx_q.delete();
        uart_tx_frame_ok.delete();
        uart_tx_checked = 0;
        uart_bit_cyc    = exp;
        uart_mon_armed  = 1'b1;
        if (verbose)
          $display("[TB]   UART TX pin receiver armed, %0d clocks per bit", exp);
      end
      CMD_UART_TXCHK: begin
        uart_tx_checked++;
        if (addr < uart_tx_q.size())
          tb_check($sformatf("%s : TX pin byte %0d = 0x%02h (expected 0x%02h), framing %s",
                             full, addr, uart_tx_q[addr], exp[7:0],
                             uart_tx_frame_ok[addr] ? "ok" : "BAD"),
                   uart_tx_q[addr] === exp[7:0] && uart_tx_frame_ok[addr]);
        else
          tb_check($sformatf("%s : TX pin byte %0d received (only %0d bytes seen)",
                             full, addr, uart_tx_q.size()), 1'b0);
      end
      CMD_UART_RXSEND: begin
        if (verbose)
          $display("[TB]   UART RX pin: sending 0x%02h, %0d clocks per bit", exp[7:0], got);
        fork
          uart_drive_byte(exp[7:0], got);
        join_none
      end
      CMD_DONE: begin
        done_pass  = addr;
        done_fail  = exp;
        done_traps = got;
        fw_done    = 1'b1;
      end
      default: begin
        tb_fail++;
        $display("[TB]   FAIL  unknown result command 0x%08h", cmd);
      end
    endcase
  endtask

  // The firmware writes CMD last; the arguments are already in the array.
  always @(posedge clk) begin
    if (fw_running && !fw_done &&
        dut.dsram_cs === 1'b1 && dut.dsram_we === 1'b1 &&
        dut.dsram_addr == RES_WORD)
      handle_report(dut.dsram_wdata);
  end

  // ───────────────────────────────────────────────────────────────────────
  //  Timer guard (Issue 4): a channel with CTRL.EN = 0 must never raise IRQ
  // ───────────────────────────────────────────────────────────────────────
  int unsigned timer_irq_violations, timer_irq_pulses;

  task automatic timer_guard(input string name, input logic [1:0] irq, input logic en);
    if (irq !== 2'b00) begin
      timer_irq_pulses++;
      if (en !== 1'b1) begin
        timer_irq_violations++;
        if (timer_irq_violations <= 5)
          $display("[TB]   FAIL  %s raised irq=2'b%02b while CTRL.EN=0 (cyc %0d)",
                   name, irq, cyc_cnt);
      end
    end
  endtask

  always @(posedge clk) begin
    if (core_running) begin
      timer_guard("TIMER0 CH0", `TMR(i_apb_timer0, 0).irq_o, `TMR(i_apb_timer0, 0).regs_q[1][0]);
      timer_guard("TIMER0 CH1", `TMR(i_apb_timer0, 1).irq_o, `TMR(i_apb_timer0, 1).regs_q[1][0]);
      timer_guard("TIMER1 CH0", `TMR(i_apb_timer1, 0).irq_o, `TMR(i_apb_timer1, 0).regs_q[1][0]);
      timer_guard("TIMER1 CH1", `TMR(i_apb_timer1, 1).irq_o, `TMR(i_apb_timer1, 1).regs_q[1][0]);
    end
  end

  // ───────────────────────────────────────────────────────────────────────
  //  SPI chip-select checks
  // ───────────────────────────────────────────────────────────────────────
  int unsigned cs_both_low_cnt, cs0_runtime_sel_cnt;
  always @(posedge clk)
    if (spi_csn0_o === 1'b0 && spi_csn1_o === 1'b0) cs_both_low_cnt++;
  always @(negedge spi_csn0_o)
    if (fw_running) cs0_runtime_sel_cnt++;

  // ───────────────────────────────────────────────────────────────────────
  //  Flash backdoor readback (little-endian word from the byte model)
  // ───────────────────────────────────────────────────────────────────────
  task automatic flash_read_word(input int unsigned word_addr, output logic [31:0] data);
    integer b0, b1, b2, b3;
    u_flash.memory_features_i0.read_mem_w(b0, word_addr * 4 + 0);
    u_flash.memory_features_i0.read_mem_w(b1, word_addr * 4 + 1);
    u_flash.memory_features_i0.read_mem_w(b2, word_addr * 4 + 2);
    u_flash.memory_features_i0.read_mem_w(b3, word_addr * 4 + 3);
    data = {b3[7:0], b2[7:0], b1[7:0], b0[7:0]};
  endtask

  // ───────────────────────────────────────────────────────────────────────
  //  Main sequence
  // ───────────────────────────────────────────────────────────────────────
  logic [31:0] golden_i [0:FW_NUM_INSTR_WORDS-1];
  logic [31:0] golden_d [0:FW_NUM_DATA_WORDS-1];

  initial begin
    longint unsigned wcnt;
    logic [31:0]     fw;
    int unsigned     mism;

    verbose      = $test$plusargs("VERBOSE");
    last_section = "(none)";
    build_regmap();

    // Waveform database, written on every run (no command-line flag).
    `ifdef XCELIUM
      $shm_open("soc_regtest_tb.shm");
      $shm_probe(soc_regtest_tb, "ASMC");
      $display("[TB] waveforms -> soc_regtest_tb.shm");
    `else
      $dumpfile("soc_regtest_tb.vcd");
      $dumpvars(0, soc_regtest_tb);
      $display("[TB] waveforms -> soc_regtest_tb.vcd");
    `endif

    $readmemh(IMEM_HEX, golden_i);
    $readmemh(DMEM_HEX, golden_d);

    hard_rst_ni = 1'b0;
    soft_rst_ni = 1'b1;
    repeat (10) @(posedge clk);

    $display("[TB] --- RISCFORGE SoC — peripheral register access test");
    $display("[TB]  Flash image : %s", FLASH_IMAGE);
    $display("[TB]  Image       : %0d ISRAM words + %0d DSRAM words", FW_NUM_INSTR_WORDS, FW_NUM_DATA_WORDS);

    // ── Phase A: flash preload ────────────────────────────────────────
    $display("[TB] --- A: flash image preload");
    flash_read_word(0, fw);
    tb_check($sformatf("flash word 0 = 0x%08h (expected 0x%08h)", fw, golden_i[0]), fw === golden_i[0]);
    flash_read_word(IMAGE_WORDS - 1, fw);
    tb_check($sformatf("flash last word = 0x%08h (expected 0x%08h)", fw, golden_d[FW_NUM_DATA_WORDS-1]),
             fw === golden_d[FW_NUM_DATA_WORDS-1]);
    if (fw_fail + tb_fail != 0) begin
      $display("[TB]   Flash preload failed: check that build.py ran and that the working");
      $display("[TB]   directory is RTL_SOC/sim/ (image path %s).", FLASH_IMAGE);
    end

    // ── Phase B: cold boot ────────────────────────────────────────────
    $display("[TB] --- B: cold boot from SPI flash");
    hard_rst_ni = 1'b1;
    wcnt = 0;
    while (!boot_done && wcnt < BOOT_TIMEOUT_CYCLES) begin
      @(posedge clk);
      wcnt++;
      if (wcnt % 200_000 == 0)
        $display("[TB]   ... booting, cyc %0d, bootloader %s, word %0d of %0d",
                 cyc_cnt, dut.i_bootloader.state_q.name(),
                 dut.i_bootloader.word_cnt_q, IMAGE_WORDS);
    end
    if (!boot_done) begin
      $display("[TB]   FAIL  boot_done not asserted after %0d cycles (bootloader %s, word %0d)",
               BOOT_TIMEOUT_CYCLES, dut.i_bootloader.state_q.name(), dut.i_bootloader.word_cnt_q);
      tb_fail++;
      summary();
    end
    $display("[TB]   boot_done @cyc %0d", cyc_cnt);

    // ── Phase C: image placement (ISRAM never written at runtime; DSRAM
    //    compared past the result words, which the firmware starts using at once)
    $display("[TB] --- C: image placement in ISRAM / DSRAM");
    mism = 0;
    for (int i = 0; i < FW_NUM_INSTR_WORDS; i++)
      if (`ISRAM_W(i) !== golden_i[i]) begin
        if (mism < 5) $display("[TB]   ISRAM[%0d] = 0x%08h, expected 0x%08h", i, `ISRAM_W(i), golden_i[i]);
        mism++;
      end
    tb_check($sformatf("ISRAM holds all %0d instruction words (%0d mismatches)", FW_NUM_INSTR_WORDS, mism),
             mism == 0);
    mism = 0;
    for (int i = RES_WORDS; i < FW_NUM_DATA_WORDS; i++)
      if (`DSRAM_W(i) !== golden_d[i]) begin
        if (mism < 5) $display("[TB]   DSRAM[%0d] = 0x%08h, expected 0x%08h", i, `DSRAM_W(i), golden_d[i]);
        mism++;
      end
    tb_check($sformatf("DSRAM holds data words %0d..%0d (%0d mismatches)",
                       RES_WORDS, FW_NUM_DATA_WORDS - 1, mism), mism == 0);

    // ── Phase D: firmware run ─────────────────────────────────────────
    $display("[TB] --- D: register test firmware");
    run_start_cyc = cyc_cnt;
    fw_running    = 1'b1;
    wcnt = 0;
    while (!fw_done && wcnt < RUN_TIMEOUT_CYCLES) begin
      @(posedge clk);
      wcnt++;
    end
    if (!fw_done) begin
      tb_fail++;
      $display("[TB]   FAIL  firmware did not finish within %0d cycles", RUN_TIMEOUT_CYCLES);
      $display("[TB]         last section : %s", last_section);
      $display("[TB]         PC           : 0x%08h", `CORE_PC);
      $display("[TB]         bus          : %0d reads, %0d writes, %0d errors",
               bus_rd_cnt, bus_wr_cnt, bus_err_cnt);
    end

    summary();
  end

  // ───────────────────────────────────────────────────────────────────────
  //  Summary
  // ───────────────────────────────────────────────────────────────────────
  task automatic summary();
    repeat (5) @(posedge clk);

    print_coverage();

    $display("[TB] --- E: TB-side checks");
    if (fw_done) begin
      tb_check($sformatf("firmware PASS total matches (fw %0d, tb %0d)", done_pass, fw_pass),
               done_pass == fw_pass);
      tb_check($sformatf("firmware FAIL total matches (fw %0d, tb %0d)", done_fail, fw_fail),
               done_fail == fw_fail);
      tb_check($sformatf("every bus error was expected (%0d errors, %0d BUSRESP checks)",
                         bus_err_cnt, busresp_checks),
               bus_err_cnt == busresp_checks && !bus_err_pending && bus_unexpected_err == 0);
    end
    if (fw_done)
      tb_check($sformatf("UART TX pin: every byte received was checked (%0d received, %0d checked)",
                         uart_tx_q.size(), uart_tx_checked),
               uart_mon_armed && uart_tx_q.size() == uart_tx_checked);
    tb_check($sformatf("no timer IRQ while CTRL.EN=0 (%0d violations, %0d IRQ cycles)",
                       timer_irq_violations, timer_irq_pulses), timer_irq_violations == 0);
    tb_check($sformatf("SPI CS0 and CS1 never low together (%0d cycles)", cs_both_low_cnt),
             cs_both_low_cnt == 0);
    tb_check($sformatf("SPI CS1 selected once by the firmware (%0d)", spi1_select_cnt),
             spi1_select_cnt == 1);
    tb_check($sformatf("SPI CS0 (flash) not selected at runtime (%0d)", cs0_runtime_sel_cnt),
             cs0_runtime_sel_cnt == 0);
    tb_check($sformatf("no bus timeout monitor fired during the whole run (sticky 0x%02h)",
                       {axi_rd_timeout_sticky, axi_wr_timeout_sticky, apb_timeout_sticky}),
             {axi_rd_timeout_sticky, axi_wr_timeout_sticky, apb_timeout_sticky} === 8'h00);

    $display("[TB] ------------------------------------------------------------------");
    $display("[TB]  Firmware checks : %0d passed, %0d failed", fw_pass, fw_fail);
    $display("[TB]  TB checks       : %0d passed, %0d failed", tb_pass, tb_fail);
    if (fw_done)
      $display("[TB]  Runtime         : %0d cycles, %0d MMIO reads, %0d MMIO writes, %0d traps",
               cyc_cnt - run_start_cyc, bus_rd_cnt, bus_wr_cnt, done_traps);
    if (fw_done && fw_fail == 0 && tb_fail == 0)
      $display("[TB]  *** REGISTER TEST PASSED ***");
    else
      $display("[TB]  *** REGISTER TEST FAILED ***");
    $display("[TB] ------------------------------------------------------------------");
    $finish;
  endtask

  // ───────────────────────────────────────────────────────────────────────
  //  Global timeout
  // ───────────────────────────────────────────────────────────────────────
  initial begin
    #80ms;
    $display("[TB] GLOBAL TIMEOUT (80 ms simulated), last section: %s", last_section);
    $finish;
  end

endmodule : soc_regtest_tb
