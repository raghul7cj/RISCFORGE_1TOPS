// =============================================================================
// RISCFORGE 1TOPS — I2C Register Access Testbench
// =============================================================================
// Dedicated to ONE firmware: ips/RTL_SOC/mem/i2c_regtest/i2c_regtest.c.
// Boots the full riscforge_soc_subsystem from the Infineon S25FS512S flash
// model, then runs the I2C register test on the real RV32 core. Every access
// goes through the real path:
//     core LSU -> hybrid_mem_interface -> axi_lite_xbar -> axi_lite_to_apb -> apb_i2c
//
// One testbench per firmware, by design: soc_regtest_tb.sv (all six
// peripherals) and soc_montest_tb.sv (bus timeout monitors) are left alone.
// The next per-peripheral benches follow this file as soc_<ip>_regtest_tb.sv.
//
// -----------------------------------------------------------------------------
// Firmware -> TB mailbox (DSRAM 0x0002_0000, words 0-6) — same protocol as
// regtest.c, so the two benches read the same way:
//   +0 CMD   written last; the TB acts on this store
//   +4 IP    pointer to the IP name string  (strings live in DSRAM .rodata)
//   +8 NAME  pointer to the register name string
//  +12 SUB   pointer to the check description string
//  +16 ADDR / +20 EXP / +24 GOT
//   CMD 1 PASS, 2 FAIL, 3 SECTION, 4 BUSRESP (unused here), 0xD0 DONE
//
// Firmware summary block (DSRAM 0x0002_0020, words 8-15) is cross-checked
// against the mailbox totals in phase F, so the block a memory-dump grading
// flow relies on is itself verified.
//
// -----------------------------------------------------------------------------
// What this TB checks BY ITSELF, independently of anything the firmware claims
//
//  1. Flash preload, and the image landing correctly in ISRAM / DSRAM after boot
//
//  2. APB slot 0 protocol monitor. Every I2C access on apb_req[0] is observed:
//       - PREADY must be high in the ACCESS phase (apb_i2c.sv ties it to 1, so
//         the slot can never stall the bridge)
//       - PSLVERR must never assert (tied to 0), i.e. nothing may fault
//       - PADDR must stay inside 0x4000_0000-0x4000_0FFF
//
//  3. Read-mux shadow check. On EVERY read the TB recomputes PRDATA from the
//     I2C block's own registers through a backdoor probe and compares it with
//     the PRDATA the slave actually drove. This re-derives the whole
//     PADDR[5:2] decode independently of the firmware: ~1500 accesses, the
//     1024-address window sweep included.
//
//  4. Address coverage. A 1024-entry bitmap of every word address in the 4 KB
//     window, plus per-slot read/write counts, so "the whole window was
//     exercised" is the TB's own statement, not the firmware's.
//
//  5. I2C bus idle. This is a register test, not a protocol test: the firmware
//     never writes CR[7:4]. The TB proves it held:
//       - scl_padoen_o / sda_padoen_o stay 1 (lines released) for the whole run
//       - CR[7:4] (STA/STO/RD/WR) is 0 at every clock
//       - SR stays 0x00 at every clock (no TIP, BUSY, AL, RXACK, IF)
//       - i2c_interrupt_o stays low, although phase 5 sets CTR.IEN
//
//  6. Fabric: no bus error on the core's crossbar port, no bus timeout monitor
//     firing on any slot, no OTHER APB slot selected while the firmware runs,
//     and the AXI read/write counts equal the APB slot 0 counts one for one
//     (nothing lost or duplicated in axi_lite_to_apb).
//
//  7. Per-register scoreboard. The golden I2C map lives HERE, not in the
//     firmware, so a register the firmware forgets to touch prints as
//     NOT EXERCISED instead of quietly leaving the totals.
//
// -----------------------------------------------------------------------------
// Board model around the DUT
//   - SPI CS0: S25FS512S flash holding the image (boot only)
//   - SPI CS1: never selected; MISO follows the flash
//   - I2C:     open-drain SCL/SDA with pull-ups, no slave (none is needed —
//              the firmware never starts a transfer)
//   - GPIO:    pads looped back, gpio_in_i = gpio_out_o
//   - UART:    RX idle high
//
// -----------------------------------------------------------------------------
// Build the firmware + flash image first (needs the RISC-V GCC toolchain):
//     cd ips/RTL_SOC/mem/i2c_regtest && python build.py
// That also writes fw_params.svh (word counts + image paths), included below.
//
// Test filelist: ips/RTL_SOC/tests/i2c_regtest.f.
// Run from ips/RTL_SOC/sim/ (all relative paths assume it):
//     xrun -f ../tests/i2c_regtest.f -l logs/i2c_regtest.log            # normal run
//     xrun -f ../tests/i2c_regtest.f -l logs/i2c_regtest.log +VERBOSE   # also print every PASS
// Waveforms are written every run to soc_i2c_regtest_tb.shm; no flag needed.
// =============================================================================
`timescale 1ns/1ps

module soc_i2c_regtest_tb;

  import gpio_reg_pkg::GPIOCount;

  // Generated by build.py: FW_NUM_INSTR_WORDS, FW_NUM_DATA_WORDS, FW_RESULT_ADDR,
  // FW_FLASH_IMAGE / FW_IMEM_HEX / FW_DMEM_HEX. Resolved through the
  // +incdir+../mem/i2c_regtest line in tests/i2c_regtest.f.
  `include "fw_params.svh"

  // ───────────────────────────────────────────────────────────────────────
  //  Configuration
  // ───────────────────────────────────────────────────────────────────────
  localparam int unsigned TIMER0_CNT           = 2;
  localparam int unsigned TIMER1_CNT           = 2;
  localparam int unsigned FLASH_POWERUP_CYCLES = 30_000;   // S25FS512S tPU = 300 us
  localparam time         CLK_PERIOD           = 10ns;     // 100 MHz

  localparam int unsigned IMAGE_WORDS = FW_NUM_INSTR_WORDS + FW_NUM_DATA_WORDS;

  // Boot = 16384-word SRAM clear (~5 cycles/word) + 30k flash power-up
  //        + ~320 cycles per image word over SPI (CLKDIV = 4).
  localparam longint unsigned BOOT_TIMEOUT_CYCLES = 200_000 + 400 * IMAGE_WORDS;
  // The firmware makes ~1600 MMIO accesses (1024 of them the window sweep).
  localparam longint unsigned RUN_TIMEOUT_CYCLES  = 1_000_000;

  localparam logic [31:0] ISRAM_BASE  = 32'h0001_0000;
  localparam logic [31:0] DSRAM_BASE  = 32'h0002_0000;
  localparam int unsigned DSRAM_WORDS = 8192;
  localparam int unsigned RES_WORD    = (FW_RESULT_ADDR - DSRAM_BASE) >> 2;
  localparam int unsigned RES_WORDS   = 16;   // .results is 64 B (link.ld)

  // I2C window under test: apb_addr_map[0], full 4 KB
  localparam logic [31:0] I2C_BASE  = 32'h4000_0000;
  localparam logic [31:0] I2C_LIMIT = 32'h4000_1000;
  localparam int unsigned I2C_WORDS = 1024;   // word addresses in the window

  // Image paths come from fw_params.svh (firmware selected in tests/i2c_regtest.f)
  localparam string FLASH_IMAGE = FW_FLASH_IMAGE;
  localparam string IMEM_HEX    = FW_IMEM_HEX;
  localparam string DMEM_HEX    = FW_DMEM_HEX;
  localparam string OTP_FILE    = "../../spi_slave_infinion/S25fs512s/model/s25fs512sOTP.mem";

  // Mailbox commands (i2c_regtest.c)
  localparam logic [31:0] CMD_PASS    = 32'h01;
  localparam logic [31:0] CMD_FAIL    = 32'h02;
  localparam logic [31:0] CMD_SECTION = 32'h03;
  localparam logic [31:0] CMD_BUSRESP = 32'h04;
  localparam logic [31:0] CMD_DONE    = 32'hD0;

  // Summary block (i2c_regtest.c), DSRAM words 8-15
  localparam int unsigned SUM_W         = 8;
  localparam logic [31:0] SUM_MAGIC_VAL = 32'h4932_4352;   // "I2CR"
  localparam logic [31:0] SUM_DONE_VAL  = 32'hD09E_D09E;

  // ───────────────────────────────────────────────────────────────────────
  //  Clock & reset
  // ───────────────────────────────────────────────────────────────────────
  logic clk;
  logic hard_rst_ni;
  logic soft_rst_ni;

  initial clk = 1'b0;
  always #(CLK_PERIOD/2) clk = ~clk;

  // 2-state, starts at 0 (no initial assignment: single-driver rule)
  longint unsigned cyc_cnt;
  always_ff @(posedge clk) cyc_cnt <= cyc_cnt + 1;

  // ───────────────────────────────────────────────────────────────────────
  //  DUT pins
  // ───────────────────────────────────────────────────────────────────────
  localparam int unsigned NR_GPIOS = GPIOCount;

  logic                        boot_done;

  wire                         i2c_scl_i, i2c_sda_i;
  logic                        i2c_scl_o, i2c_scl_oen_o;
  logic                        i2c_sda_o, i2c_sda_oen_o;
  logic                        i2c_interrupt_o;

  logic [(TIMER0_CNT*2)-1:0]   timer0_irq;
  logic [(TIMER1_CNT*2)-1:0]   timer1_irq;

  logic                        uart_sin_i;
  logic                        uart_sout_o, uart_int_o;

  wire  [NR_GPIOS-1:0]         gpio_in_i;
  logic [NR_GPIOS-1:0]         gpio_out_o, gpio_tx_en_o, gpio_in_sync_o;
  logic                        gpio_global_interrupt_o;
  logic [NR_GPIOS-1:0]         gpio_pin_level_interrupts_o;

  logic                        spi_clk_o, spi_csn0_o, spi_csn1_o, spi_sdo0_o;
  wire                         spi_sdi1_i;
  logic [1:0]                  spi_events_o;

  // Nothing in this run may stall, so these must stay at zero throughout.
  logic [5:0]                  apb_timeout_sticky;
  logic                        axi_wr_timeout_sticky, axi_rd_timeout_sticky;

  initial uart_sin_i = 1'b1;           // UART RX idle

  // I2C: open-drain bus with pull-ups, no slave. The DUT drives a line only
  // when its output enable (active low) is 0 — which, for this firmware, is
  // never: see the bus-idle monitor below.
  tri1 i2c_scl_bus, i2c_sda_bus;
  assign i2c_scl_bus = (i2c_scl_oen_o === 1'b0) ? i2c_scl_o : 1'bz;
  assign i2c_sda_bus = (i2c_sda_oen_o === 1'b0) ? i2c_sda_o : 1'bz;
  assign i2c_scl_i   = i2c_scl_bus;
  assign i2c_sda_i   = i2c_sda_bus;

  // GPIO pads looped back (untouched by this firmware, kept for a clean tie-off)
  assign gpio_in_i = gpio_out_o;

  // ───────────────────────────────────────────────────────────────────────
  //  SPI: flash on CS0 for the boot. CS1 is never selected.
  // ───────────────────────────────────────────────────────────────────────
  wire flash_si, flash_so, flash_wpn, flash_resetn;
  assign flash_si     = spi_sdo0_o;
  assign flash_wpn    = 1'b1;
  assign flash_resetn = 1'b1;
  assign spi_sdi1_i   = flash_so;

  s25fs512s #(
    .UserPreload   ( 1           ),
    .mem_file_name ( FLASH_IMAGE ),
    .otp_file_name ( OTP_FILE    )
  ) u_flash (
    .SI       ( flash_si     ),
    .SO       ( flash_so     ),
    .SCK      ( spi_clk_o    ),
    .CSNeg    ( spi_csn0_o   ),
    .WPNeg    ( flash_wpn    ),
    .RESETNeg ( flash_resetn )
  );

  // ───────────────────────────────────────────────────────────────────────
  //  DUT
  // ───────────────────────────────────────────────────────────────────────
  riscforge_soc_subsystem #(
    .TIMER0_CNT           ( TIMER0_CNT           ),
    .TIMER1_CNT           ( TIMER1_CNT           ),
    .SPI_BUFFER_DEPTH     ( 10                   ),
    .NUM_INSTR_WORDS      ( FW_NUM_INSTR_WORDS   ),
    .NUM_DATA_WORDS       ( FW_NUM_DATA_WORDS    ),
    .FLASH_POWERUP_CYCLES ( FLASH_POWERUP_CYCLES )
  ) dut (
    .clk_i                       ( clk                         ),
    .hard_rst_ni                 ( hard_rst_ni                 ),
    .soft_rst_ni                 ( soft_rst_ni                 ),
    .test_mode_i                 ( 1'b0                        ),
    .fetch_enable_i              ( 1'b1                        ),   // unused by the DUT
    .boot_addr_i                 ( 32'h0000_0000               ),   // unused by the DUT
    .boot_done_o                 ( boot_done                   ),

    .i2c_scl_i                   ( i2c_scl_i                   ),
    .i2c_scl_o                   ( i2c_scl_o                   ),
    .i2c_scl_oen_o               ( i2c_scl_oen_o               ),
    .i2c_sda_i                   ( i2c_sda_i                   ),
    .i2c_sda_o                   ( i2c_sda_o                   ),
    .i2c_sda_oen_o               ( i2c_sda_oen_o               ),
    .i2c_interrupt_o             ( i2c_interrupt_o             ),

    .timer0_irq_o                ( timer0_irq                  ),
    .timer1_irq_o                ( timer1_irq                  ),

    .uart_sin_i                  ( uart_sin_i                  ),
    .uart_sout_o                 ( uart_sout_o                 ),
    .uart_int_o                  ( uart_int_o                  ),

    .gpio_in_i                   ( gpio_in_i                   ),
    .gpio_out_o                  ( gpio_out_o                  ),
    .gpio_tx_en_o                ( gpio_tx_en_o                ),
    .gpio_in_sync_o              ( gpio_in_sync_o              ),
    .gpio_global_interrupt_o     ( gpio_global_interrupt_o     ),
    .gpio_pin_level_interrupts_o ( gpio_pin_level_interrupts_o ),

    .spi_clk_o                   ( spi_clk_o                   ),
    .spi_csn0_o                  ( spi_csn0_o                  ),
    .spi_csn1_o                  ( spi_csn1_o                  ),
    .spi_sdo0_o                  ( spi_sdo0_o                  ),
    .spi_sdi1_i                  ( spi_sdi1_i                  ),
    .spi_events_o                ( spi_events_o                ),

    .apb_timeout_sticky_o        ( apb_timeout_sticky          ),
    .axi_wr_timeout_sticky_o     ( axi_wr_timeout_sticky       ),
    .axi_rd_timeout_sticky_o     ( axi_rd_timeout_sticky       )
  );

  // ───────────────────────────────────────────────────────────────────────
  //  Hierarchical probes (macro names are prefixed so this file can never
  //  collide with soc_regtest_tb.sv / soc_montest_tb.sv)
  // ───────────────────────────────────────────────────────────────────────
  `define I2CTB_ISRAM_W(i) dut.i_isram.u_imem.mem_array[i]
  `define I2CTB_DSRAM_W(i) dut.i_dsram.mem[i]
  `define I2CTB_PC         dut.i_riscv_core.Fetch.PCF

  // APB slot 0 (I2C). apb_req goes straight to the slave; the timeout monitor
  // is interposed on the RESPONSE path only, so apb_resp_slv[0] is the I2C
  // block's own answer, before any monitor override.
  `define I2CTB_PSEL    dut.apb_req[0].psel
  `define I2CTB_PENABLE dut.apb_req[0].penable
  `define I2CTB_PWRITE  dut.apb_req[0].pwrite
  `define I2CTB_PADDR   dut.apb_req[0].paddr
  `define I2CTB_PWDATA  dut.apb_req[0].pwdata
  `define I2CTB_PRDATA  dut.apb_resp_slv[0].prdata
  `define I2CTB_PREADY  dut.apb_resp_slv[0].pready
  `define I2CTB_PSLVERR dut.apb_resp_slv[0].pslverr

  // apb_i2c.sv internal state, for the read-mux shadow check
  `define I2CTB_R_PRE   dut.i_apb_i2c.r_pre
  `define I2CTB_R_CTR   dut.i_apb_i2c.r_ctrl
  `define I2CTB_R_TXR   dut.i_apb_i2c.r_tx
  `define I2CTB_R_CMD   dut.i_apb_i2c.r_cmd
  `define I2CTB_S_SR    dut.i_apb_i2c.s_status
  `define I2CTB_S_RXR   dut.i_apb_i2c.s_rx

  wire core_running = (dut.core_rst_n === 1'b1);

  // ───────────────────────────────────────────────────────────────────────
  //  Scoreboard state
  // ───────────────────────────────────────────────────────────────────────
  bit          verbose;
  bit          fw_running, fw_done;
  int unsigned fw_pass, fw_fail;                  // tallied from the mailbox
  int unsigned tb_pass, tb_fail;                  // the TB's own checks
  logic [31:0] done_pass, done_fail, done_traps;  // firmware totals from DONE
  string       last_section;
  int unsigned last_phase;
  longint unsigned run_start_cyc;

  task automatic tb_check(input string label, input bit cond);
    if (cond) begin
      tb_pass++;
      if (verbose) $display("[TB]   PASS  %s", label);
    end else begin
      tb_fail++;
      $display("[TB]   FAIL  %s", label);
    end
  endtask

  function automatic string resp_name(input logic [1:0] r);
    case (r)
      2'b00:   return "OKAY";
      2'b01:   return "EXOKAY";
      2'b10:   return "SLVERR";
      default: return "DECERR";
    endcase
  endfunction

  function automatic string slot_name(input int unsigned s);
    case (s)
      0:       return "PRE";
      1:       return "CTR";
      2:       return "RXR";
      3:       return "SR";
      4:       return "TXR";
      5:       return "CR";
      default: return $sformatf("hole@0x%02h", 8'(s * 4));
    endcase
  endfunction

  // Read a NUL-terminated string the firmware placed in DSRAM (.rodata).
  function automatic string fw_str(input logic [31:0] ptr);
    string       s;
    logic [31:0] a;
    logic [31:0] w;
    logic [7:0]  c;
    s = "";
    if (ptr == 32'h0) return s;
    if (ptr < DSRAM_BASE || ptr >= DSRAM_BASE + 4 * DSRAM_WORDS)
      return $sformatf("<ptr 0x%08h outside DSRAM>", ptr);
    for (int i = 0; i < 160; i++) begin
      a = ptr + i;
      if (a >= DSRAM_BASE + 4 * DSRAM_WORDS) break;
      w = `I2CTB_DSRAM_W((a - DSRAM_BASE) >> 2);
      c = w[8 * a[1:0] +: 8];
      if (c == 8'h00) break;
      s = $sformatf("%s%c", s, c);
    end
    return s;
  endfunction

  // ───────────────────────────────────────────────────────────────────────
  //  Golden I2C register map — held HERE, not in the firmware
  // ───────────────────────────────────────────────────────────────────────
  string       rm_key  [$];
  logic [31:0] rm_addr [$];
  string       rm_kind [$];

  int unsigned r_pass   [string];
  int unsigned r_fail   [string];
  string       r_detail [string];
  bit          r_known  [string];

  string       o_key    [$];
  int unsigned o_pass   [string];
  int unsigned o_fail   [string];
  string       o_detail [string];

  task automatic regdef(input string ip, input string name,
                        input logic [31:0] addr, input string kind);
    string k;
    k = $sformatf("%s.%s", ip, name);
    rm_key.push_back(k);
    rm_addr.push_back(addr);
    rm_kind.push_back(kind);
    r_known[k]  = 1'b1;
    r_pass[k]   = 0;
    r_fail[k]   = 0;
    r_detail[k] = "";
  endtask

  // Names must match the strings i2c_regtest.c posts.
  task automatic build_regmap();
    regdef("I2C", "PRE", 32'h4000_0000, "RW");
    regdef("I2C", "CTR", 32'h4000_0004, "RW");
    regdef("I2C", "RXR", 32'h4000_0008, "RO");
    regdef("I2C", "SR",  32'h4000_000C, "RO");
    regdef("I2C", "TXR", 32'h4000_0010, "RW");
    regdef("I2C", "CR",  32'h4000_0014, "CMD");
  endtask

  task automatic score(input string key, input string sub, input bit ok,
                       input logic [31:0] exp, input logic [31:0] got);
    if (r_known.exists(key)) begin
      if (ok) r_pass[key]++;
      else begin
        r_fail[key]++;
        r_detail[key] = $sformatf("%s\n[TB]           %s : exp 0x%08h  got 0x%08h",
                                  r_detail[key], sub, exp, got);
      end
    end else begin
      if (!o_pass.exists(key)) begin
        o_key.push_back(key);
        o_pass[key]   = 0;
        o_fail[key]   = 0;
        o_detail[key] = "";
      end
      if (ok) o_pass[key]++;
      else begin
        o_fail[key]++;
        o_detail[key] = $sformatf("%s\n[TB]           %s : exp 0x%08h  got 0x%08h",
                                  o_detail[key], sub, exp, got);
      end
    end
  endtask

  // ───────────────────────────────────────────────────────────────────────
  //  APB slot 0 monitor + read-mux shadow model
  // ───────────────────────────────────────────────────────────────────────
  int unsigned apb_rd_cnt, apb_wr_cnt;
  int unsigned apb_pready_low, apb_pslverr_cnt, apb_out_of_window;
  int unsigned prdata_checks, prdata_errs;
  int unsigned slot_rd [16];
  int unsigned slot_wr [16];
  bit          win_seen [I2C_WORDS];
  int unsigned prdata_err_dumps;

  // What PRDATA must be, recomputed from the I2C block's own registers.
  // Transcribed from the read mux in apb_i2c.sv.
  function automatic logic [31:0] i2c_shadow_prdata(input int unsigned s);
    case (s)
      0:       return {16'h0, `I2CTB_R_PRE};
      1:       return {24'h0, `I2CTB_R_CTR};
      2:       return {24'h0, `I2CTB_S_RXR};
      3:       return {24'h0, `I2CTB_S_SR};
      4:       return {24'h0, `I2CTB_R_TXR};
      5:       return {24'h0, `I2CTB_R_CMD};
      default: return 32'h0;
    endcase
  endfunction

  always @(posedge clk) begin : apb_slot0_monitor
    int unsigned s;
    int unsigned widx;
    logic [31:0] shadow;
    logic [11:0] off;

    if (fw_running && `I2CTB_PSEL === 1'b1 && `I2CTB_PENABLE === 1'b1) begin
      s    = int'(`I2CTB_PADDR[5:2]);
      widx = int'(`I2CTB_PADDR[11:2]);
      off  = `I2CTB_PADDR[11:0];

      // PREADY is tied high in apb_i2c.sv: the slot must never stall.
      if (`I2CTB_PREADY !== 1'b1) begin
        apb_pready_low++;
        if (apb_pready_low <= 5)
          $display("[APB]  FAIL  PREADY low in ACCESS phase @0x%08h (cyc %0d)",
                   `I2CTB_PADDR, cyc_cnt);
      end

      // PSLVERR is tied 0: no I2C access may fault.
      if (`I2CTB_PSLVERR !== 1'b0) begin
        apb_pslverr_cnt++;
        if (apb_pslverr_cnt <= 5)
          $display("[APB]  FAIL  PSLVERR asserted @0x%08h (cyc %0d)",
                   `I2CTB_PADDR, cyc_cnt);
      end

      // paddr is the full 32-bit address, so the decode can be checked here:
      // the bridge must only ever select slot 0 inside apb_addr_map[0].
      if (`I2CTB_PADDR < I2C_BASE || `I2CTB_PADDR >= I2C_LIMIT) begin
        apb_out_of_window++;
        if (apb_out_of_window <= 5)
          $display("[APB]  FAIL  slot 0 selected for 0x%08h, outside 0x%08h-0x%08h (cyc %0d)",
                   `I2CTB_PADDR, I2C_BASE, I2C_LIMIT - 1, cyc_cnt);
      end else begin
        win_seen[widx] = 1'b1;
      end

      if (`I2CTB_PWRITE === 1'b1) begin
        apb_wr_cnt++;
        slot_wr[s]++;
        if (verbose)
          $display("[APB]  WR  %-12s @+0x%03h = 0x%08h (cyc %0d)",
                   slot_name(s), off, `I2CTB_PWDATA, cyc_cnt);
      end else begin
        apb_rd_cnt++;
        slot_rd[s]++;
        // Independent read-mux check: PRDATA must equal the mux output
        // recomputed from the block's own registers.
        shadow = i2c_shadow_prdata(s);
        prdata_checks++;
        if (`I2CTB_PRDATA !== shadow) begin
          prdata_errs++;
          if (prdata_err_dumps < 10) begin
            prdata_err_dumps++;
            $display("[APB]  FAIL  PRDATA mismatch @+0x%03h (%s): slave 0x%08h, shadow 0x%08h (cyc %0d)",
                     off, slot_name(s), `I2CTB_PRDATA, shadow, cyc_cnt);
          end
        end
        if (verbose)
          $display("[APB]  RD  %-12s @+0x%03h = 0x%08h (cyc %0d)",
                   slot_name(s), off, `I2CTB_PRDATA, cyc_cnt);
      end
    end
  end

  // ───────────────────────────────────────────────────────────────────────
  //  I2C bus-idle monitor
  //  This is a register test: the firmware never writes CR[7:4], so the I2C
  //  pads must stay released and the status register must stay at 0 for the
  //  entire run. Any violation means a transfer was started by accident.
  // ───────────────────────────────────────────────────────────────────────
  int unsigned scl_driven_cyc, sda_driven_cyc;
  int unsigned cmd_bits_cyc, sr_nonzero_cyc, irq_high_cyc;
  bit   [7:0]  sr_worst, cmd_worst;      // 2-state: start at 0, OR-accumulated

  always @(posedge clk) begin : i2c_bus_idle_monitor
    if (core_running) begin
      if (i2c_scl_oen_o === 1'b0) scl_driven_cyc++;
      if (i2c_sda_oen_o === 1'b0) sda_driven_cyc++;

      if ((`I2CTB_R_CMD & 8'hF0) !== 8'h00) begin
        cmd_bits_cyc++;
        cmd_worst = cmd_worst | (`I2CTB_R_CMD & 8'hF0);
        if (cmd_bits_cyc == 1)
          $display("[I2C]  FAIL  CR[7:4] = 0x%02h at cyc %0d: a bus command was issued",
                   `I2CTB_R_CMD & 8'hF0, cyc_cnt);
      end

      if (`I2CTB_S_SR !== 8'h00) begin
        sr_nonzero_cyc++;
        sr_worst = sr_worst | `I2CTB_S_SR;
        if (sr_nonzero_cyc == 1)
          $display("[I2C]  FAIL  SR = 0x%02h at cyc %0d: the bus left the idle state",
                   `I2CTB_S_SR, cyc_cnt);
      end

      if (i2c_interrupt_o === 1'b1) begin
        irq_high_cyc++;
        if (irq_high_cyc == 1)
          $display("[I2C]  FAIL  i2c_interrupt_o high at cyc %0d with SR.IF = %0b",
                   cyc_cnt, `I2CTB_S_SR[0]);
      end
    end
  end

  // ───────────────────────────────────────────────────────────────────────
  //  Decode isolation: the firmware touches only the I2C window, so no other
  //  APB slot may be selected while it runs. Unrolled rather than indexed
  //  with a variable, to keep the hierarchical references constant.
  // ───────────────────────────────────────────────────────────────────────
  int unsigned other_slot_sel;

  always @(posedge clk) begin : other_slot_monitor
    if (fw_running) begin
      if (dut.apb_req[1].psel === 1'b1 && dut.apb_req[1].penable === 1'b1) other_slot_sel++;
      if (dut.apb_req[2].psel === 1'b1 && dut.apb_req[2].penable === 1'b1) other_slot_sel++;
      if (dut.apb_req[3].psel === 1'b1 && dut.apb_req[3].penable === 1'b1) other_slot_sel++;
      if (dut.apb_req[4].psel === 1'b1 && dut.apb_req[4].penable === 1'b1) other_slot_sel++;
      if (dut.apb_req[5].psel === 1'b1 && dut.apb_req[5].penable === 1'b1) other_slot_sel++;
    end
  end

  // ───────────────────────────────────────────────────────────────────────
  //  Bus monitor on the core's crossbar port (SLV[0]) — nothing may error.
  //  hybrid_mem_interface serves DSRAM directly and sends only MMIO over AXI,
  //  so for this firmware every transaction here is an I2C access, and the
  //  AXI counts must equal the APB slot 0 counts one for one.
  // ───────────────────────────────────────────────────────────────────────
  logic [31:0] bus_last_aw, bus_last_ar;
  int unsigned bus_rd_cnt, bus_wr_cnt, bus_err_cnt;

  always @(posedge clk) begin : core_bus_monitor
    if (fw_running) begin
      if (dut.xbar_slv_req[0].aw_valid === 1'b1 && dut.xbar_slv_resp[0].aw_ready === 1'b1)
        bus_last_aw = dut.xbar_slv_req[0].aw.addr;
      if (dut.xbar_slv_req[0].ar_valid === 1'b1 && dut.xbar_slv_resp[0].ar_ready === 1'b1)
        bus_last_ar = dut.xbar_slv_req[0].ar.addr;

      if (dut.xbar_slv_resp[0].b_valid === 1'b1 && dut.xbar_slv_req[0].b_ready === 1'b1) begin
        bus_wr_cnt++;
        if (dut.xbar_slv_resp[0].b.resp !== 2'b00) begin
          bus_err_cnt++;
          if (bus_err_cnt <= 8)
            $display("[BUS]  FAIL  %s on write @0x%08h (cyc %0d), PC 0x%08h",
                     resp_name(dut.xbar_slv_resp[0].b.resp), bus_last_aw, cyc_cnt, `I2CTB_PC);
        end
      end
      if (dut.xbar_slv_resp[0].r_valid === 1'b1 && dut.xbar_slv_req[0].r_ready === 1'b1) begin
        bus_rd_cnt++;
        if (dut.xbar_slv_resp[0].r.resp !== 2'b00) begin
          bus_err_cnt++;
          if (bus_err_cnt <= 8)
            $display("[BUS]  FAIL  %s on read @0x%08h (cyc %0d), PC 0x%08h",
                     resp_name(dut.xbar_slv_resp[0].r.resp), bus_last_ar, cyc_cnt, `I2CTB_PC);
        end
      end
    end
  end

  // ───────────────────────────────────────────────────────────────────────
  //  Mailbox watcher
  // ───────────────────────────────────────────────────────────────────────
  task automatic handle_report(input logic [31:0] cmd);
    string       ip, nm, sub, full;
    logic [31:0] addr, exp, got;

    ip   = fw_str(`I2CTB_DSRAM_W(RES_WORD + 1));
    nm   = fw_str(`I2CTB_DSRAM_W(RES_WORD + 2));
    sub  = fw_str(`I2CTB_DSRAM_W(RES_WORD + 3));
    addr = `I2CTB_DSRAM_W(RES_WORD + 4);
    exp  = `I2CTB_DSRAM_W(RES_WORD + 5);
    got  = `I2CTB_DSRAM_W(RES_WORD + 6);
    full = (ip == "") ? nm : $sformatf("%s.%s", ip, nm);

    case (cmd)
      CMD_PASS: begin
        fw_pass++;
        if (ip != "") score(full, sub, 1'b1, exp, got);
        if (verbose)
          $display("[FW]   PASS  %s : %s @0x%08h = 0x%08h", full, sub, addr, got);
      end
      CMD_FAIL: begin
        fw_fail++;
        if (ip != "") score(full, sub, 1'b0, exp, got);
        $display("[FW]   FAIL  %s : %s @0x%08h  exp 0x%08h  got 0x%08h",
                 full, sub, addr, exp, got);
      end
      CMD_SECTION: begin
        last_section = nm;
        last_phase   = addr;
        $display("[FW] ---- %s   (cyc %0d)", nm, cyc_cnt);
      end
      CMD_BUSRESP: begin
        // i2c_regtest.c never posts this: no I2C access can fault.
        tb_fail++;
        $display("[TB]   FAIL  unexpected BUSRESP post from the firmware @0x%08h", addr);
      end
      CMD_DONE: begin
        done_pass  = addr;
        done_fail  = exp;
        done_traps = got;
        fw_done    = 1'b1;
      end
      default: begin
        tb_fail++;
        $display("[TB]   FAIL  unknown mailbox command 0x%08h", cmd);
      end
    endcase
  endtask

  // The firmware writes CMD last; the other words are already in place.
  always @(posedge clk) begin : mailbox_watcher
    if (fw_running && !fw_done &&
        dut.dsram_cs === 1'b1 && dut.dsram_we === 1'b1 &&
        dut.dsram_addr == RES_WORD)
      handle_report(dut.dsram_wdata);
  end

  // ───────────────────────────────────────────────────────────────────────
  //  Flash backdoor readback (little-endian word from the byte model)
  // ───────────────────────────────────────────────────────────────────────
  task automatic flash_read_word(input int unsigned word_addr, output logic [31:0] data);
    integer b0, b1, b2, b3;
    u_flash.memory_features_i0.read_mem_w(b0, word_addr * 4 + 0);
    u_flash.memory_features_i0.read_mem_w(b1, word_addr * 4 + 1);
    u_flash.memory_features_i0.read_mem_w(b2, word_addr * 4 + 2);
    u_flash.memory_features_i0.read_mem_w(b3, word_addr * 4 + 3);
    data = {b3[7:0], b2[7:0], b1[7:0], b0[7:0]};
  endtask

  // ───────────────────────────────────────────────────────────────────────
  //  Reports
  // ───────────────────────────────────────────────────────────────────────
  task automatic print_coverage();
    string       k;
    int unsigned n_ex, n_ok, n_bad, n_miss, n_chk;

    n_ex = 0; n_ok = 0; n_bad = 0; n_miss = 0;

    $display("[TB] ------------------------------------------------------------------");
    $display("[TB]  I2C REGISTER COVERAGE");
    $display("[TB] ------------------------------------------------------------------");
    $display("[TB]   ADDRESS      REGISTER        KIND  CHECKS  RESULT");
    foreach (rm_key[i]) begin
      k     = rm_key[i];
      n_chk = r_pass[k] + r_fail[k];
      if (n_chk == 0) begin
        n_miss++;
        $display("[TB]   0x%08h   %-15s %-4s %6d  NOT EXERCISED",
                 rm_addr[i], k, rm_kind[i], 0);
      end else begin
        n_ex++;
        if (r_fail[k] == 0) begin
          n_ok++;
          $display("[TB]   0x%08h   %-15s %-4s %6d  PASS",
                   rm_addr[i], k, rm_kind[i], n_chk);
        end else begin
          n_bad++;
          $display("[TB]   0x%08h   %-15s %-4s %6d  FAIL (%0d)",
                   rm_addr[i], k, rm_kind[i], n_chk, r_fail[k]);
          $display("%s", r_detail[k]);
        end
      end
    end
    $display("[TB] ------------------------------------------------------------------");
    $display("[TB]   %0d registers mapped: %0d exercised, %0d PASS, %0d FAIL, %0d NOT EXERCISED",
             rm_key.size(), n_ex, n_ok, n_bad, n_miss);

    tb_check($sformatf("every I2C register was exercised (%0d of %0d)", n_ex, rm_key.size()),
             n_miss == 0);
    tb_check($sformatf("no I2C register failed (%0d of %0d failed)", n_bad, rm_key.size()),
             n_bad == 0);

    $display("[TB] ------------------------------------------------------------------");
    $display("[TB]  OTHER FIRMWARE CHECKS (holes, aliases, window sweep, bus)");
    foreach (o_key[i]) begin
      k     = o_key[i];
      n_chk = o_pass[k] + o_fail[k];
      if (o_fail[k] == 0)
        $display("[TB]   %-30s %6d  PASS", k, n_chk);
      else begin
        $display("[TB]   %-30s %6d  FAIL (%0d)", k, n_chk, o_fail[k]);
        $display("%s", o_detail[k]);
      end
    end
    $display("[TB] ------------------------------------------------------------------");
  endtask

  task automatic print_apb_coverage();
    int unsigned seen;
    seen = 0;
    for (int i = 0; i < I2C_WORDS; i++)
      if (win_seen[i]) seen++;

    $display("[TB] ------------------------------------------------------------------");
    $display("[TB]  APB SLOT 0 ACCESS COVERAGE (observed by the TB, not reported)");
    $display("[TB] ------------------------------------------------------------------");
    $display("[TB]   SLOT  OFFSET  REGISTER        READS  WRITES");
    for (int s = 0; s < 16; s++)
      $display("[TB]   %4d  0x%03h   %-15s %6d  %6d",
               s, 12'(s * 4), slot_name(s), slot_rd[s], slot_wr[s]);
    $display("[TB] ------------------------------------------------------------------");
    $display("[TB]   APB accesses : %0d reads, %0d writes", apb_rd_cnt, apb_wr_cnt);
    $display("[TB]   window words : %0d of %0d word addresses touched", seen, I2C_WORDS);
    $display("[TB]   PRDATA shadow: %0d checks, %0d mismatches", prdata_checks, prdata_errs);

    // Every one of the 16 decode slots must have been read at least once.
    begin : slot_coverage
      int unsigned missed;
      missed = 0;
      for (int s = 0; s < 16; s++)
        if (slot_rd[s] == 0) begin
          missed++;
          $display("[TB]   slot %0d (%s) was never read", s, slot_name(s));
        end
      tb_check($sformatf("all 16 decode slots were read (%0d missed)", missed), missed == 0);
    end

    tb_check($sformatf("all %0d word addresses in the 4 KB window were accessed (%0d seen)",
                       I2C_WORDS, seen), seen == I2C_WORDS);
    tb_check($sformatf("every PRDATA matched the shadow read mux (%0d checks, %0d bad)",
                       prdata_checks, prdata_errs), prdata_errs == 0);
    tb_check($sformatf("PREADY never low in an ACCESS phase (%0d violations)", apb_pready_low),
             apb_pready_low == 0);
    tb_check($sformatf("PSLVERR never asserted (%0d cycles)", apb_pslverr_cnt),
             apb_pslverr_cnt == 0);
    tb_check($sformatf("no APB access outside the 4 KB window (%0d)", apb_out_of_window),
             apb_out_of_window == 0);
    $display("[TB] ------------------------------------------------------------------");
  endtask

  // Cross-check the standalone summary block the firmware maintains, so the
  // memory-dump grading path is verified too.
  task automatic check_summary_block();
    logic [31:0] magic, s_pass, s_fail, s_checks, s_traps, s_first, s_phase, s_done;

    magic    = `I2CTB_DSRAM_W(SUM_W + 0);
    s_pass   = `I2CTB_DSRAM_W(SUM_W + 1);
    s_fail   = `I2CTB_DSRAM_W(SUM_W + 2);
    s_checks = `I2CTB_DSRAM_W(SUM_W + 3);
    s_traps  = `I2CTB_DSRAM_W(SUM_W + 4);
    s_first  = `I2CTB_DSRAM_W(SUM_W + 5);
    s_phase  = `I2CTB_DSRAM_W(SUM_W + 6);
    s_done   = `I2CTB_DSRAM_W(SUM_W + 7);

    $display("[TB]   summary block @0x%08h: magic 0x%08h  pass %0d  fail %0d  checks %0d",
             DSRAM_BASE + 4 * SUM_W, magic, s_pass, s_fail, s_checks);
    $display("[TB]                          traps %0d  first_fail 0x%08h  phase %0d  done 0x%08h",
             s_traps, s_first, s_phase, s_done);

    tb_check($sformatf("summary magic is 0x%08h (got 0x%08h)", SUM_MAGIC_VAL, magic),
             magic === SUM_MAGIC_VAL);
    tb_check($sformatf("summary DONE is 0x%08h (got 0x%08h)", SUM_DONE_VAL, s_done),
             s_done === SUM_DONE_VAL);
    tb_check($sformatf("summary pass count matches the mailbox (%0d vs %0d)", s_pass, fw_pass),
             s_pass == fw_pass);
    tb_check($sformatf("summary fail count matches the mailbox (%0d vs %0d)", s_fail, fw_fail),
             s_fail == fw_fail);
    tb_check($sformatf("summary check count is consistent (%0d = %0d + %0d)",
                       s_checks, s_pass, s_fail), s_checks == s_pass + s_fail);
    tb_check($sformatf("summary reports no trap (%0d)", s_traps), s_traps == 32'h0);
    tb_check($sformatf("summary reached the last phase (phase %0d of 9)", s_phase),
             s_phase == 32'd9);
  endtask

  // ───────────────────────────────────────────────────────────────────────
  //  Main sequence
  // ───────────────────────────────────────────────────────────────────────
  logic [31:0] golden_i [0:FW_NUM_INSTR_WORDS-1];
  logic [31:0] golden_d [0:FW_NUM_DATA_WORDS-1];

  initial begin
    longint unsigned wcnt;
    logic [31:0]     fw;
    int unsigned     mism;

    verbose      = $test$plusargs("VERBOSE");
    last_section = "(none)";
    build_regmap();

    // Waveform database, written on every run (no command-line flag).
    `ifdef XCELIUM
      $shm_open("soc_i2c_regtest_tb.shm");
      $shm_probe(soc_i2c_regtest_tb, "ASMC");
      $display("[TB] waveforms -> soc_i2c_regtest_tb.shm");
    `else
      $dumpfile("soc_i2c_regtest_tb.vcd");
      $dumpvars(0, soc_i2c_regtest_tb);
      $display("[TB] waveforms -> soc_i2c_regtest_tb.vcd");
    `endif

    $readmemh(IMEM_HEX, golden_i);
    $readmemh(DMEM_HEX, golden_d);

    hard_rst_ni = 1'b0;
    soft_rst_ni = 1'b1;
    repeat (10) @(posedge clk);

    $display("[TB] ==================================================================");
    $display("[TB]  RISCFORGE SoC — I2C register access test");
    $display("[TB] ==================================================================");
    $display("[TB]  Firmware    : ../mem/i2c_regtest/i2c_regtest.c");
    $display("[TB]  Flash image : %s", FLASH_IMAGE);
    $display("[TB]  Image       : %0d ISRAM words + %0d DSRAM words",
             FW_NUM_INSTR_WORDS, FW_NUM_DATA_WORDS);
    $display("[TB]  Under test  : apb_i2c.sv, APB slot 0, 0x%08h-0x%08h",
             I2C_BASE, I2C_LIMIT - 1);

    // ── Phase A: flash preload ────────────────────────────────────────
    $display("[TB] --- A: flash image preload");
    flash_read_word(0, fw);
    tb_check($sformatf("flash word 0 = 0x%08h (expected 0x%08h)", fw, golden_i[0]),
             fw === golden_i[0]);
    flash_read_word(IMAGE_WORDS - 1, fw);
    tb_check($sformatf("flash last word = 0x%08h (expected 0x%08h)",
                       fw, golden_d[FW_NUM_DATA_WORDS-1]),
             fw === golden_d[FW_NUM_DATA_WORDS-1]);
    if (tb_fail != 0) begin
      $display("[TB]   Flash preload failed: check that build.py ran in");
      $display("[TB]   ips/RTL_SOC/mem/i2c_regtest/ and that the working directory is");
      $display("[TB]   RTL_SOC/sim/ (image path %s).", FLASH_IMAGE);
    end

    // ── Phase B: cold boot ────────────────────────────────────────────
    $display("[TB] --- B: cold boot from SPI flash");
    hard_rst_ni = 1'b1;
    wcnt = 0;
    while (!boot_done && wcnt < BOOT_TIMEOUT_CYCLES) begin
      @(posedge clk);
      wcnt++;
      if (wcnt % 200_000 == 0)
        $display("[TB]   ... booting, cyc %0d, bootloader %s, word %0d of %0d",
                 cyc_cnt, dut.i_bootloader.state_q.name(),
                 dut.i_bootloader.word_cnt_q, IMAGE_WORDS);
    end
    if (!boot_done) begin
      $display("[TB]   FAIL  boot_done not asserted after %0d cycles (bootloader %s, word %0d)",
               BOOT_TIMEOUT_CYCLES, dut.i_bootloader.state_q.name(),
               dut.i_bootloader.word_cnt_q);
      tb_fail++;
      summary();
    end
    $display("[TB]   boot_done @cyc %0d", cyc_cnt);

    // ── Phase C: image placement ──────────────────────────────────────
    $display("[TB] --- C: image placement in ISRAM / DSRAM");
    mism = 0;
    for (int i = 0; i < FW_NUM_INSTR_WORDS; i++)
      if (`I2CTB_ISRAM_W(i) !== golden_i[i]) begin
        if (mism < 5)
          $display("[TB]   ISRAM[%0d] = 0x%08h, expected 0x%08h",
                   i, `I2CTB_ISRAM_W(i), golden_i[i]);
        mism++;
      end
    tb_check($sformatf("ISRAM holds all %0d instruction words (%0d mismatches)",
                       FW_NUM_INSTR_WORDS, mism), mism == 0);
    // DSRAM compared past the .results words: the firmware starts using the
    // mailbox immediately, so those words legitimately differ from the image.
    mism = 0;
    for (int i = RES_WORDS; i < FW_NUM_DATA_WORDS; i++)
      if (`I2CTB_DSRAM_W(i) !== golden_d[i]) begin
        if (mism < 5)
          $display("[TB]   DSRAM[%0d] = 0x%08h, expected 0x%08h",
                   i, `I2CTB_DSRAM_W(i), golden_d[i]);
        mism++;
      end
    tb_check($sformatf("DSRAM holds data words %0d..%0d (%0d mismatches)",
                       RES_WORDS, FW_NUM_DATA_WORDS - 1, mism), mism == 0);

    // ── Phase D: I2C registers at reset, before the core runs ─────────
    // The core is released by the bootloader, so this is the last chance to
    // read the block's power-on state without the firmware having touched it.
    $display("[TB] --- D: I2C block reset state (backdoor, before any access)");
    tb_check($sformatf("PRE  = 0x%04h at reset", `I2CTB_R_PRE), `I2CTB_R_PRE === 16'h0000);
    tb_check($sformatf("CTR  = 0x%02h at reset", `I2CTB_R_CTR), `I2CTB_R_CTR === 8'h00);
    tb_check($sformatf("TXR  = 0x%02h at reset", `I2CTB_R_TXR), `I2CTB_R_TXR === 8'h00);
    tb_check($sformatf("CR   = 0x%02h at reset", `I2CTB_R_CMD), `I2CTB_R_CMD === 8'h00);
    tb_check($sformatf("SR   = 0x%02h at reset", `I2CTB_S_SR),  `I2CTB_S_SR  === 8'h00);
    tb_check("SCL released at reset (scl_oen = 1)", i2c_scl_oen_o === 1'b1);
    tb_check("SDA released at reset (sda_oen = 1)", i2c_sda_oen_o === 1'b1);

    // ── Phase E: firmware run ─────────────────────────────────────────
    $display("[TB] --- E: I2C register test firmware");
    run_start_cyc = cyc_cnt;
    fw_running    = 1'b1;
    wcnt = 0;
    while (!fw_done && wcnt < RUN_TIMEOUT_CYCLES) begin
      @(posedge clk);
      wcnt++;
    end
    if (!fw_done) begin
      tb_fail++;
      $display("[TB]   FAIL  firmware did not finish within %0d cycles", RUN_TIMEOUT_CYCLES);
      $display("[TB]         last section : %s (phase %0d)", last_section, last_phase);
      $display("[TB]         PC           : 0x%08h", `I2CTB_PC);
      $display("[TB]         APB slot 0   : %0d reads, %0d writes", apb_rd_cnt, apb_wr_cnt);
      $display("[TB]         core bus     : %0d reads, %0d writes, %0d errors",
               bus_rd_cnt, bus_wr_cnt, bus_err_cnt);
    end

    summary();
  end

  // ───────────────────────────────────────────────────────────────────────
  //  Summary
  // ───────────────────────────────────────────────────────────────────────
  task automatic summary();
    repeat (5) @(posedge clk);

    print_coverage();
    print_apb_coverage();

    $display("[TB] --- F: TB-side checks");

    if (fw_done) begin
      tb_check($sformatf("firmware PASS total matches the mailbox (fw %0d, tb %0d)",
                         done_pass, fw_pass), done_pass == fw_pass);
      tb_check($sformatf("firmware FAIL total matches the mailbox (fw %0d, tb %0d)",
                         done_fail, fw_fail), done_fail == fw_fail);
      tb_check($sformatf("firmware took no trap (%0d)", done_traps), done_traps == 32'h0);
      check_summary_block();
    end

    // The I2C bus must have stayed idle for the whole run.
    tb_check($sformatf("SCL never driven low by the DUT (%0d cycles)", scl_driven_cyc),
             scl_driven_cyc == 0);
    tb_check($sformatf("SDA never driven low by the DUT (%0d cycles)", sda_driven_cyc),
             sda_driven_cyc == 0);
    tb_check($sformatf("CR[7:4] never set, no bus command issued (%0d cycles, worst 0x%02h)",
                       cmd_bits_cyc, cmd_worst), cmd_bits_cyc == 0);
    tb_check($sformatf("SR stayed 0x00 for the whole run (%0d cycles, worst 0x%02h)",
                       sr_nonzero_cyc, sr_worst), sr_nonzero_cyc == 0);
    tb_check($sformatf("i2c_interrupt_o never asserted (%0d cycles)", irq_high_cyc),
             irq_high_cyc == 0);

    // Final register state must be the reset state again.
    tb_check($sformatf("PRE back to 0x0000 (0x%04h)", `I2CTB_R_PRE), `I2CTB_R_PRE === 16'h0000);
    tb_check($sformatf("CTR back to 0x00 (0x%02h)",   `I2CTB_R_CTR), `I2CTB_R_CTR === 8'h00);
    tb_check($sformatf("TXR back to 0x00 (0x%02h)",   `I2CTB_R_TXR), `I2CTB_R_TXR === 8'h00);
    tb_check($sformatf("CR  back to 0x00 (0x%02h)",   `I2CTB_R_CMD), `I2CTB_R_CMD === 8'h00);

    // Fabric health.
    tb_check($sformatf("no bus error on the core's AXI port (%0d)", bus_err_cnt),
             bus_err_cnt == 0);
    tb_check($sformatf("every AXI read reached I2C as exactly one APB read (axi %0d, apb %0d)",
                       bus_rd_cnt, apb_rd_cnt), bus_rd_cnt == apb_rd_cnt);
    tb_check($sformatf("every AXI write reached I2C as exactly one APB write (axi %0d, apb %0d)",
                       bus_wr_cnt, apb_wr_cnt), bus_wr_cnt == apb_wr_cnt);
    tb_check($sformatf("no other APB slot selected during the run (%0d accesses)",
                       other_slot_sel), other_slot_sel == 0);
    tb_check($sformatf("no bus timeout monitor fired (sticky 0x%02h)",
                       {axi_rd_timeout_sticky, axi_wr_timeout_sticky, apb_timeout_sticky}),
             {axi_rd_timeout_sticky, axi_wr_timeout_sticky, apb_timeout_sticky} === 8'h00);

    $display("[TB] ==================================================================");
    $display("[TB]  Firmware checks : %0d passed, %0d failed", fw_pass, fw_fail);
    $display("[TB]  TB checks       : %0d passed, %0d failed", tb_pass, tb_fail);
    if (fw_done)
      $display("[TB]  Runtime         : %0d cycles, %0d APB reads, %0d APB writes, %0d traps",
               cyc_cnt - run_start_cyc, apb_rd_cnt, apb_wr_cnt, done_traps);
    if (fw_done && fw_fail == 0 && tb_fail == 0)
      $display("[TB]  *** I2C REGISTER TEST PASSED ***");
    else
      $display("[TB]  *** I2C REGISTER TEST FAILED ***");
