// =============================================================================
// RISCFORGE 1TOPS — System Test Testbench (signoff item 6.12)
// =============================================================================
// Boots the full riscforge_soc_subsystem from the Infineon S25FS512S flash
// model, then runs the system-test firmware (ips/RTL_SOC/mem/systest/systest.c)
// on the real RV32 core.
//
// Together with soc_regtest_tb (mem/regtest), this is the bare-metal C test
// suite for 6.12. Split:
//
//   Covered here (systest)
//     A  DSRAM memory test: walking 1s/0s, power-of-two address offsets,
//        March C- over all DSRAM the program does not use, program data intact
//     B  interrupts taken by the core: MSIP (3), MTIP via Timer 0 ch0 compare
//        (7), Timer 1 ch0 compare (24), GPIO rising edge (16), UART receive
//        (19); masking by mie and mstatus.MIE; MEIP (11) tied off, reads 0
//     C  SPI 32-bit write on CS1, MOSI captured and checked by this TB
//
//   Signoff item 4.12 (reset and interrupt entry), checked here
//     - after every core reset release the first decoded instruction is at
//       RESET_PC 0x0000_0000 and is boot ROM word 0 (cold boot, then a warm
//       reset through soft_rst_ni after which the firmware runs a second time)
//     - for every interrupt: the trap target and the first handler fetch equal
//       mtvec (direct mode), mepc is written with the interrupted instruction's
//       PC, and that instruction is the first to retire after mret
//     - firmware B8 / B9: clean boundary (512-addi block) and mtvec direct mode
//
//   Already covered by soc_regtest_tb, not repeated here
//     register reset/RW/alias checks of every peripheral, UART TX/RX on the
//     pins and MCR loopback, GPIO pad loopback, SPI read on CS1, timer period,
//     bus-error and out-of-region access faults
//
// Firmware -> TB result words (DSRAM 0x0002_0000, 7 words, same as regtest)
//   +0 CMD   written last; the TB acts on this store
//   +4 IP / +8 NAME / +12 SUB   pointers to strings in DSRAM .rodata
//  +16 ADDR / +20 EXP / +24 GOT
//   CMD 1 PASS, 2 FAIL, 3 SECTION, 7 UART_RXSEND, 8 SPI_TXCHK, 0xD0 DONE
//
// Checks done by the TB itself
//   - Flash preload, image placement in ISRAM / DSRAM after boot
//   - SPI MOSI word on CS1 equals what the firmware wrote (CMD 8)
//   - No bus error at all (systest makes no faulting access)
//   - No timer IRQ while that channel's CTRL.EN = 0
//   - SPI: CS0/CS1 never low together, CS1 selected exactly once, flash (CS0)
//     not selected at runtime; no bus-timeout monitor fired
//   - Firmware's own PASS/FAIL totals match what the TB received
//
// Board model around the DUT
//   - SPI CS0: S25FS512S flash holding the image (boot)
//   - SPI CS1: MOSI captured on SCK rising edges (mode 0, MSB first)
//   - GPIO:    pads looped back, gpio_in_i = gpio_out_o
//   - I2C:     open-drain SCL/SDA with pull-ups, no slave
//   - UART:    RX idle high; 8N1 transmitter on uart_sin_i (CMD 7)
//
// -----------------------------------------------------------------------------
// Build the firmware + flash image first:
//     cd ips/RTL_SOC/mem/systest && python build.py
// Test filelist: ips/RTL_SOC/tests/systest.f. Run from ips/RTL_SOC/sim/:
//     xrun -f ../tests/systest.f -l logs/systest.log            # normal run
//     xrun -f ../tests/systest.f -l logs/systest.log +VERBOSE   # also print every PASS
// =============================================================================
`timescale 1ns/1ps

module soc_systest_tb;

  import gpio_reg_pkg::GPIOCount;

  // Generated by build.py (+incdir+../mem/systest in tests/systest.f)
  `include "fw_params.svh"

  // ───────────────────────────────────────────────────────────────────────
  //  Configuration
  // ───────────────────────────────────────────────────────────────────────
  localparam int unsigned TIMER0_CNT           = 2;
  localparam int unsigned TIMER1_CNT           = 2;
  localparam int unsigned FLASH_POWERUP_CYCLES = 30_000;   // S25FS512S tPU = 300 us
  localparam time         CLK_PERIOD           = 10ns;     // 100 MHz

  localparam int unsigned IMAGE_WORDS = FW_NUM_INSTR_WORDS + FW_NUM_DATA_WORDS;

  localparam longint unsigned BOOT_TIMEOUT_CYCLES = 200_000 + 400 * IMAGE_WORDS;
  localparam longint unsigned RUN_TIMEOUT_CYCLES  = 4_000_000;

  localparam logic [31:0] DSRAM_BASE  = 32'h0002_0000;
  localparam int unsigned DSRAM_WORDS = 8192;
  localparam int unsigned RES_WORD    = (FW_RESULT_ADDR - DSRAM_BASE) >> 2;
  localparam int unsigned RES_WORDS   = 16;   // .results is 64 B (link.ld)

  localparam string FLASH_IMAGE = FW_FLASH_IMAGE;
  localparam string IMEM_HEX    = FW_IMEM_HEX;
  localparam string DMEM_HEX    = FW_DMEM_HEX;
  localparam string OTP_FILE    = "../../spi_slave_infinion/S25fs512s/model/s25fs512sOTP.mem";

  // Result-word commands (systest.c)
  localparam logic [31:0] CMD_PASS        = 32'h01;
  localparam logic [31:0] CMD_FAIL        = 32'h02;
  localparam logic [31:0] CMD_SECTION     = 32'h03;
  localparam logic [31:0] CMD_UART_RXSEND = 32'h07;  // drive byte EXP on RX pin, GOT = clocks/bit
  localparam logic [31:0] CMD_SPI_TXCHK   = 32'h08;  // last CS1 MOSI word must be EXP, GOT = bits
  localparam logic [31:0] CMD_DONE        = 32'hD0;

  // ───────────────────────────────────────────────────────────────────────
  //  Clock & reset
  // ───────────────────────────────────────────────────────────────────────
  logic clk;
  logic hard_rst_ni;
  logic soft_rst_ni;

  initial clk = 1'b0;
  always #(CLK_PERIOD/2) clk = ~clk;

  longint unsigned cyc_cnt;
  always_ff @(posedge clk) cyc_cnt <= cyc_cnt + 1;

  // ───────────────────────────────────────────────────────────────────────
  //  DUT pins
  // ───────────────────────────────────────────────────────────────────────
  localparam int unsigned NR_GPIOS = GPIOCount;

  logic                        boot_done;

  wire                         i2c_scl_i, i2c_sda_i;
  logic                        i2c_scl_o, i2c_scl_oen_o;
  logic                        i2c_sda_o, i2c_sda_oen_o;
  logic                        i2c_interrupt_o;

  logic [(TIMER0_CNT*2)-1:0]   timer0_irq;
  logic [(TIMER1_CNT*2)-1:0]   timer1_irq;

  logic                        uart_sin_i;
  logic                        uart_sout_o, uart_int_o;

  wire  [NR_GPIOS-1:0]         gpio_in_i;
  logic [NR_GPIOS-1:0]         gpio_out_o, gpio_tx_en_o, gpio_in_sync_o;
  logic                        gpio_global_interrupt_o;
  logic [NR_GPIOS-1:0]         gpio_pin_level_interrupts_o;

  logic                        spi_clk_o, spi_csn0_o, spi_csn1_o, spi_sdo0_o;
  wire                         spi_sdi1_i;
  logic [1:0]                  spi_events_o;

  logic [5:0]                  apb_timeout_sticky;
  logic                        axi_wr_timeout_sticky, axi_rd_timeout_sticky;

  // UART RX pin: idle high, 8N1 transmitter driven by CMD_UART_RXSEND
  initial uart_sin_i = 1'b1;

  task automatic uart_drive_byte(input logic [7:0] d, input int unsigned bit_cyc);
    uart_sin_i = 1'b0;                              // start bit
    repeat (bit_cyc) @(posedge clk);
    for (int i = 0; i < 8; i++) begin
      uart_sin_i = d[i];
      repeat (bit_cyc) @(posedge clk);
    end
    uart_sin_i = 1'b1;                              // stop bit, then idle
    repeat (bit_cyc) @(posedge clk);
  endtask

  // I2C: open-drain bus, pull-ups, no slave
  tri1 i2c_scl_bus, i2c_sda_bus;
  assign i2c_scl_bus = (i2c_scl_oen_o === 1'b0) ? i2c_scl_o : 1'bz;
  assign i2c_sda_bus = (i2c_sda_oen_o === 1'b0) ? i2c_sda_o : 1'bz;
  assign i2c_scl_i   = i2c_scl_bus;
  assign i2c_sda_i   = i2c_sda_bus;

  // GPIO: pads looped back (B5 drives its own rising edge on pin 0)
  assign gpio_in_i = gpio_out_o;

  // ───────────────────────────────────────────────────────────────────────
  //  SPI: flash on CS0, MOSI capture on CS1
  // ───────────────────────────────────────────────────────────────────────
  wire flash_si, flash_so, flash_wpn, flash_resetn;
  assign flash_si     = spi_sdo0_o;
  assign flash_wpn    = 1'b1;
  assign flash_resetn = 1'b1;

  s25fs512s #(
    .UserPreload   ( 1           ),
    .mem_file_name ( FLASH_IMAGE ),
    .otp_file_name ( OTP_FILE    )
  ) u_flash (
    .SI       ( flash_si     ),
    .SO       ( flash_so     ),
    .SCK      ( spi_clk_o    ),
    .CSNeg    ( spi_csn0_o   ),
    .WPNeg    ( flash_wpn    ),
    .RESETNeg ( flash_resetn )
  );

  // CS1 device: samples MOSI on every SCK rising edge while selected (mode 0,
  // MSB first). Drives MISO low (the write test reads nothing back).
  logic [63:0] cs1_mosi;
  int unsigned cs1_bits, spi1_select_cnt;
  always @(negedge spi_csn1_o) begin
    cs1_mosi = '0;
    cs1_bits = 0;
    spi1_select_cnt++;
  end
  always @(posedge spi_clk_o)
    if (spi_csn1_o === 1'b0) begin
      cs1_mosi = {cs1_mosi[62:0], spi_sdo0_o};
      cs1_bits++;
    end

  assign spi_sdi1_i = (spi_csn1_o === 1'b0) ? 1'b0 : flash_so;

  // ───────────────────────────────────────────────────────────────────────
  //  DUT
  // ───────────────────────────────────────────────────────────────────────
  riscforge_soc_subsystem #(
    .TIMER0_CNT           ( TIMER0_CNT           ),
    .TIMER1_CNT           ( TIMER1_CNT           ),
    .SPI_BUFFER_DEPTH     ( 10                   ),
    .NUM_INSTR_WORDS      ( FW_NUM_INSTR_WORDS   ),
    .NUM_DATA_WORDS       ( FW_NUM_DATA_WORDS    ),
    .FLASH_POWERUP_CYCLES ( FLASH_POWERUP_CYCLES )
  ) dut (
    .clk_i                       ( clk                         ),
    .hard_rst_ni                 ( hard_rst_ni                 ),
    .soft_rst_ni                 ( soft_rst_ni                 ),
    .test_mode_i                 ( 1'b0                        ),
    .fetch_enable_i              ( 1'b1                        ),
    .boot_addr_i                 ( 32'h0000_0000               ),
    .boot_done_o                 ( boot_done                   ),

    .i2c_scl_i                   ( i2c_scl_i                   ),
    .i2c_scl_o                   ( i2c_scl_o                   ),
    .i2c_scl_oen_o               ( i2c_scl_oen_o               ),
    .i2c_sda_i                   ( i2c_sda_i                   ),
    .i2c_sda_o                   ( i2c_sda_o                   ),
    .i2c_sda_oen_o               ( i2c_sda_oen_o               ),
    .i2c_interrupt_o             ( i2c_interrupt_o             ),

    .timer0_irq_o                ( timer0_irq                  ),
    .timer1_irq_o                ( timer1_irq                  ),

    .uart_sin_i                  ( uart_sin_i                  ),
    .uart_sout_o                 ( uart_sout_o                 ),
    .uart_int_o                  ( uart_int_o                  ),

    .gpio_in_i                   ( gpio_in_i                   ),
    .gpio_out_o                  ( gpio_out_o                  ),
    .gpio_tx_en_o                ( gpio_tx_en_o                ),
    .gpio_in_sync_o              ( gpio_in_sync_o              ),
    .gpio_global_interrupt_o     ( gpio_global_interrupt_o     ),
    .gpio_pin_level_interrupts_o ( gpio_pin_level_interrupts_o ),

    .spi_clk_o                   ( spi_clk_o                   ),
    .spi_csn0_o                  ( spi_csn0_o                  ),
    .spi_csn1_o                  ( spi_csn1_o                  ),
    .spi_sdo0_o                  ( spi_sdo0_o                  ),
    .spi_sdi1_i                  ( spi_sdi1_i                  ),
    .spi_events_o                ( spi_events_o                ),

    .apb_timeout_sticky_o        ( apb_timeout_sticky          ),
    .axi_wr_timeout_sticky_o     ( axi_wr_timeout_sticky       ),
    .axi_rd_timeout_sticky_o     ( axi_rd_timeout_sticky       )
  );

  // ───────────────────────────────────────────────────────────────────────
  //  Hierarchical probes
  // ───────────────────────────────────────────────────────────────────────
  `define ISRAM_W(i)    dut.i_isram.u_imem.mem_array[i]
  `define DSRAM_W(i)    dut.i_dsram.mem[i]
  `define CORE_PC       dut.i_riscv_core.Fetch.PCF
  `define TMR(inst, ch) dut.inst.TIMER_GEN[ch].timer_i

  wire core_running = (dut.core_rst_n === 1'b1);

  // ───────────────────────────────────────────────────────────────────────
  //  Scoreboard
  // ───────────────────────────────────────────────────────────────────────
  bit          verbose;
  bit          fw_running, fw_done;
  int unsigned fw_pass, fw_fail;
  int unsigned tb_pass, tb_fail;
  logic [31:0] done_pass, done_fail, done_irqs;
  int unsigned done_pass_tot, done_fail_tot, done_irqs_tot, runs_done;   // over both runs
  string       last_section;
  longint unsigned run_start_cyc;

  // Per-group verdicts ("IP.NAME"), printed as a table at the end
  string       g_key  [$];
  int unsigned g_pass [string];
  int unsigned g_fail [string];
  string       g_detail [string];

  task automatic tb_check(input string label, input bit cond);
    if (cond) begin
      tb_pass++;
      if (verbose) $display("[TB]   PASS  %s", label);
    end else begin
      tb_fail++;
      $display("[TB]   FAIL  %s", label);
    end
  endtask

  task automatic score(input string key, input string sub, input bit ok,
                       input logic [31:0] exp, input logic [31:0] got);
    if (!g_pass.exists(key)) begin
      g_key.push_back(key);
      g_pass[key]   = 0;
      g_fail[key]   = 0;
      g_detail[key] = "";
    end
    if (ok) g_pass[key]++;
    else begin
      g_fail[key]++;
      g_detail[key] = $sformatf("%s\n[TB]           %s : exp 0x%08h  got 0x%08h",
                                g_detail[key], sub, exp, got);
    end
  endtask

  function automatic string fw_str(input logic [31:0] ptr);
    string       s;
    logic [31:0] a, w;
    logic [7:0]  c;
    s = "";
    if (ptr == 32'h0) return s;
    if (ptr < DSRAM_BASE || ptr >= DSRAM_BASE + 4 * DSRAM_WORDS)
      return $sformatf("<ptr 0x%08h outside DSRAM>", ptr);
    for (int i = 0; i < 160; i++) begin
      a = ptr + i;
      if (a >= DSRAM_BASE + 4 * DSRAM_WORDS) break;
      w = `DSRAM_W((a - DSRAM_BASE) >> 2);
      c = w[8 * a[1:0] +: 8];
      if (c == 8'h00) break;
      s = $sformatf("%s%c", s, c);
    end
    return s;
  endfunction

  // ───────────────────────────────────────────────────────────────────────
  //  Bus monitor on the core's crossbar port: systest expects no bus error
  // ───────────────────────────────────────────────────────────────────────
  logic [31:0] bus_last_aw, bus_last_ar;
  int unsigned bus_rd_cnt, bus_wr_cnt, bus_err_cnt;

  always @(posedge clk) begin
    if (fw_running) begin
      if (dut.xbar_slv_req[0].aw_valid === 1'b1 && dut.xbar_slv_resp[0].aw_ready === 1'b1)
        bus_last_aw = dut.xbar_slv_req[0].aw.addr;
      if (dut.xbar_slv_req[0].ar_valid === 1'b1 && dut.xbar_slv_resp[0].ar_ready === 1'b1)
        bus_last_ar = dut.xbar_slv_req[0].ar.addr;
      if (dut.xbar_slv_resp[0].b_valid === 1'b1 && dut.xbar_slv_req[0].b_ready === 1'b1) begin
        bus_wr_cnt++;
        if (dut.xbar_slv_resp[0].b.resp !== 2'b00) begin
          bus_err_cnt++;
          $display("[BUS]  unexpected write error @0x%08h (cyc %0d)", bus_last_aw, cyc_cnt);
        end
      end
      if (dut.xbar_slv_resp[0].r_valid === 1'b1 && dut.xbar_slv_req[0].r_ready === 1'b1) begin
        bus_rd_cnt++;
        if (dut.xbar_slv_resp[0].r.resp !== 2'b00) begin
          bus_err_cnt++;
          $display("[BUS]  unexpected read error @0x%08h (cyc %0d)", bus_last_ar, cyc_cnt);
        end
      end
    end
  end

  // ───────────────────────────────────────────────────────────────────────
  //  Result words
  // ───────────────────────────────────────────────────────────────────────
  task automatic handle_report(input logic [31:0] cmd);
    string       ip, nm, sub, full;
    logic [31:0] addr, exp, got;

    ip   = fw_str(`DSRAM_W(RES_WORD + 1));
    nm   = fw_str(`DSRAM_W(RES_WORD + 2));
    sub  = fw_str(`DSRAM_W(RES_WORD + 3));
    addr = `DSRAM_W(RES_WORD + 4);
    exp  = `DSRAM_W(RES_WORD + 5);
    got  = `DSRAM_W(RES_WORD + 6);
    full = (ip == "") ? nm : $sformatf("%s.%s", ip, nm);

    case (cmd)
      CMD_PASS: begin
        fw_pass++;
        if (ip != "") score(full, sub, 1'b1, exp, got);
        if (verbose)
          $display("[FW]   PASS  %s : %s @0x%08h = 0x%08h", full, sub, addr, got);
      end
      CMD_FAIL: begin
        fw_fail++;
        if (ip != "") score(full, sub, 1'b0, exp, got);
        $display("[FW]   FAIL  %s : %s @0x%08h  exp 0x%08h  got 0x%08h",
                 full, sub, addr, exp, got);
      end
      CMD_SECTION: begin
        last_section = nm;
        $display("[FW] ---- %s   (cyc %0d)", nm, cyc_cnt);
      end
      CMD_UART_RXSEND: begin
        if (verbose)
          $display("[TB]   UART RX pin: sending 0x%02h, %0d clocks per bit", exp[7:0], got);
        fork
          uart_drive_byte(exp[7:0], got);
        join_none
      end
      CMD_SPI_TXCHK: begin
        tb_check($sformatf("%s : CS1 MOSI = 0x%08h, %0d bits (expected 0x%08h, %0d bits)",
                           full, cs1_mosi[31:0], cs1_bits, exp, got),
                 cs1_mosi[31:0] === exp && cs1_bits == got);
      end
      CMD_DONE: begin
        done_pass = addr;
        done_fail = exp;
        done_irqs = got;
        done_pass_tot += addr;
        done_fail_tot += exp;
        done_irqs_tot += got;
        runs_done++;
        fw_done   = 1'b1;
      end
      default: begin
        tb_fail++;
        $display("[TB]   FAIL  unknown result command 0x%08h", cmd);
      end
    endcase
  endtask

  // The firmware writes CMD last; the arguments are already in the array.
  always @(posedge clk) begin
    if (fw_running && !fw_done &&
        dut.dsram_cs === 1'b1 && dut.dsram_we === 1'b1 &&
        dut.dsram_addr == RES_WORD)
      handle_report(dut.dsram_wdata);
  end

  // ───────────────────────────────────────────────────────────────────────
  //  Timer guard: a channel with CTRL.EN = 0 must never raise IRQ
  // ───────────────────────────────────────────────────────────────────────
  int unsigned timer_irq_violations;

  task automatic timer_guard(input string name, input logic [1:0] irq, input logic en);
    if (irq !== 2'b00 && en !== 1'b1) begin
      timer_irq_violations++;
      if (timer_irq_violations <= 5)
        $display("[TB]   FAIL  %s raised irq=2'b%02b while CTRL.EN=0 (cyc %0d)", name, irq, cyc_cnt);
    end
  endtask

  always @(posedge clk) begin
    if (core_running) begin
      timer_guard("TIMER0 CH0", `TMR(i_apb_timer0, 0).irq_o, `TMR(i_apb_timer0, 0).regs_q[1][0]);
      timer_guard("TIMER0 CH1", `TMR(i_apb_timer0, 1).irq_o, `TMR(i_apb_timer0, 1).regs_q[1][0]);
      timer_guard("TIMER1 CH0", `TMR(i_apb_timer1, 0).irq_o, `TMR(i_apb_timer1, 0).regs_q[1][0]);
      timer_guard("TIMER1 CH1", `TMR(i_apb_timer1, 1).irq_o, `TMR(i_apb_timer1, 1).regs_q[1][0]);
    end
  end

  // ───────────────────────────────────────────────────────────────────────
  //  4.12: reset and interrupt entry
  // ───────────────────────────────────────────────────────────────────────
  `define CORE dut.i_riscv_core

  // (1) Fetch starts at RESET_PC: the first instruction that reaches decode
  //     after each core_rst_n release must be boot ROM word 0 at 0x0000_0000.
  localparam logic [31:0] RESET_PC      = 32'h0000_0000;
  localparam logic [31:0] BOOTROM_WORD0 = 32'h0002_8137;   // lui x2, 0x28

  bit          wait_first_decode;
  int unsigned core_resets_seen;

  always @(posedge clk) begin
    if (dut.core_rst_n !== 1'b1)
      wait_first_decode <= 1'b1;
    else if (wait_first_decode && `CORE.valid_D === 1'b1) begin
      wait_first_decode <= 1'b0;
      core_resets_seen++;
      tb_check($sformatf("4.12 reset %0d: first decoded instruction PC 0x%08h = 0x%08h (expected RESET_PC 0x%08h, boot ROM word 0x%08h)",
                         core_resets_seen, `CORE.PCD, `CORE.InstrD, RESET_PC, BOOTROM_WORD0),
               `CORE.PCD === RESET_PC && `CORE.InstrD === BOOTROM_WORD0);
    end
  end

  // (2) Interrupt entry: at each interrupt commit (WB stage) the trap target
  //     must be the mtvec base (direct mode), mepc must be written with the
  //     interrupted instruction's PC, the first handler instruction must come
  //     from mtvec, and after mret the interrupted instruction must be the
  //     first to retire.
  int unsigned irq_entries;
  logic [31:0] irq_pc, irq_mtvec;
  bit          irq_commit_q, chk_mepc, chk_target, in_handler, chk_resume;

  always @(posedge clk) begin
    if (core_running) begin
      if (`CORE.trap_commit_valid === 1'b1 && `CORE.trap_commit_is_interrupt === 1'b1
          && !irq_commit_q) begin
        irq_entries++;
        irq_pc     = `CORE.exc_pc_W;
        irq_mtvec  = {`CORE.csr_file.mtvec_r[31:2], 2'b00};
        tb_check($sformatf("4.12 irq %0d: trap target 0x%08h = mtvec 0x%08h",
                           irq_entries, `CORE.trap_target, irq_mtvec),
                 `CORE.trap_target === irq_mtvec);
        chk_mepc   = 1'b1;
        chk_target = 1'b1;
        in_handler = 1'b1;
      end else begin
        if (chk_mepc) begin                      // mepc_r updated on the commit edge
          chk_mepc = 1'b0;
          tb_check($sformatf("4.12 irq %0d: mepc 0x%08h = interrupted instruction PC 0x%08h",
                             irq_entries, `CORE.csr_file.mepc_r, irq_pc),
                   `CORE.csr_file.mepc_r === irq_pc);
        end
        if (chk_target && `CORE.valid_D === 1'b1) begin
          chk_target = 1'b0;
          tb_check($sformatf("4.12 irq %0d: first handler instruction at 0x%08h = mtvec 0x%08h",
                             irq_entries, `CORE.PCD, irq_mtvec),
                   `CORE.PCD === irq_mtvec);
        end
        if (in_handler && `CORE.mret_commit === 1'b1) begin
          in_handler = 1'b0;
          chk_resume = 1'b1;
        end else if (chk_resume && `CORE.valid_W === 1'b1 && `CORE.exc_valid_W !== 1'b1) begin
          chk_resume = 1'b0;
          tb_check($sformatf("4.12 irq %0d: first instruction retired after mret at 0x%08h = mepc 0x%08h",
                             irq_entries, `CORE.PC_W, irq_pc),
                   `CORE.PC_W === irq_pc);
        end
      end
      irq_commit_q = (`CORE.trap_commit_valid === 1'b1);
    end
  end

  // ───────────────────────────────────────────────────────────────────────
  //  SPI chip-select checks
  // ───────────────────────────────────────────────────────────────────────
  int unsigned cs_both_low_cnt, cs0_runtime_sel_cnt;
  always @(posedge clk)
    if (spi_csn0_o === 1'b0 && spi_csn1_o === 1'b0) cs_both_low_cnt++;
  always @(negedge spi_csn0_o)
    if (fw_running) cs0_runtime_sel_cnt++;

  // ───────────────────────────────────────────────────────────────────────
  //  Flash backdoor readback (little-endian word from the byte model)
  // ───────────────────────────────────────────────────────────────────────
  task automatic flash_read_word(input int unsigned word_addr, output logic [31:0] data);
    integer b0, b1, b2, b3;
    u_flash.memory_features_i0.read_mem_w(b0, word_addr * 4 + 0);
    u_flash.memory_features_i0.read_mem_w(b1, word_addr * 4 + 1);
    u_flash.memory_features_i0.read_mem_w(b2, word_addr * 4 + 2);
    u_flash.memory_features_i0.read_mem_w(b3, word_addr * 4 + 3);
    data = {b3[7:0], b2[7:0], b1[7:0], b0[7:0]};
  endtask

  // ───────────────────────────────────────────────────────────────────────
  //  Main sequence
  // ───────────────────────────────────────────────────────────────────────
  logic [31:0] golden_i [0:FW_NUM_INSTR_WORDS-1];
  logic [31:0] golden_d [0:FW_NUM_DATA_WORDS-1];

  initial begin
    longint unsigned wcnt;
    logic [31:0]     fw;
    int unsigned     mism;

    verbose      = $test$plusargs("VERBOSE");
    last_section = "(none)";

    `ifdef XCELIUM
      if ($test$plusargs("WAVES")) begin
        $shm_open("soc_systest_tb.shm");
        $shm_probe(soc_systest_tb, "ASMC");
        $display("[TB] waveforms -> soc_systest_tb.shm");
      end
    `endif

    $readmemh(IMEM_HEX, golden_i);
    $readmemh(DMEM_HEX, golden_d);

    hard_rst_ni = 1'b0;
    soft_rst_ni = 1'b1;
    repeat (10) @(posedge clk);

    $display("[TB] --- RISCFORGE SoC — system test (memory, interrupts, SPI write)");
    $display("[TB]  Flash image : %s", FLASH_IMAGE);
    $display("[TB]  Image       : %0d ISRAM words + %0d DSRAM words", FW_NUM_INSTR_WORDS, FW_NUM_DATA_WORDS);

    // ── A: flash preload ─────────────────────────────────────────────
    $display("[TB] --- A: flash image preload");
    flash_read_word(0, fw);
    tb_check($sformatf("flash word 0 = 0x%08h (expected 0x%08h)", fw, golden_i[0]), fw === golden_i[0]);
    flash_read_word(IMAGE_WORDS - 1, fw);
    tb_check($sformatf("flash last word = 0x%08h (expected 0x%08h)", fw, golden_d[FW_NUM_DATA_WORDS-1]),
             fw === golden_d[FW_NUM_DATA_WORDS-1]);

    // ── B: cold boot ─────────────────────────────────────────────────
    $display("[TB] --- B: cold boot from SPI flash");
    hard_rst_ni = 1'b1;
    wcnt = 0;
    while (!boot_done && wcnt < BOOT_TIMEOUT_CYCLES) begin
      @(posedge clk);
      wcnt++;
    end
    if (!boot_done) begin
      $display("[TB]   FAIL  boot_done not asserted after %0d cycles (bootloader %s)",
               BOOT_TIMEOUT_CYCLES, dut.i_bootloader.state_q.name());
      tb_fail++;
      summary();
    end
    $display("[TB]   boot_done @cyc %0d", cyc_cnt);

    // ── C: image placement ───────────────────────────────────────────
    $display("[TB] --- C: image placement in ISRAM / DSRAM");
    mism = 0;
    for (int i = 0; i < FW_NUM_INSTR_WORDS; i++)
      if (`ISRAM_W(i) !== golden_i[i]) mism++;
    tb_check($sformatf("ISRAM holds all %0d instruction words (%0d mismatches)", FW_NUM_INSTR_WORDS, mism),
             mism == 0);
    mism = 0;
    for (int i = RES_WORDS; i < FW_NUM_DATA_WORDS; i++)
      if (`DSRAM_W(i) !== golden_d[i]) mism++;
    tb_check($sformatf("DSRAM holds data words %0d..%0d (%0d mismatches)",
                       RES_WORDS, FW_NUM_DATA_WORDS - 1, mism), mism == 0);

    // ── D: firmware run ──────────────────────────────────────────────
    $display("[TB] --- D: system test firmware");
    run_start_cyc = cyc_cnt;
    fw_running    = 1'b1;
    wcnt = 0;
    while (!fw_done && wcnt < RUN_TIMEOUT_CYCLES) begin
      @(posedge clk);
      wcnt++;
    end
    if (!fw_done) begin
      tb_fail++;
      $display("[TB]   FAIL  firmware did not finish within %0d cycles", RUN_TIMEOUT_CYCLES);
      $display("[TB]         last section : %s", last_section);
      $display("[TB]         PC           : 0x%08h", `CORE_PC);
    end

    // ── F: warm reset and second run (4.12: fetch at RESET_PC after a warm
    //    reset). The bootloader skips the flash fetch and keeps the SRAMs, the
    //    core restarts at the boot ROM and the firmware runs again.
    if (fw_done) begin
      $display("[TB] --- F: warm reset (soft_rst_ni) and second firmware run");
      fw_done     = 1'b0;
      soft_rst_ni = 1'b0;
      repeat (100) @(posedge clk);                  // > SoftRstFiltCycles (16)
      tb_check("warm reset: core held in reset while soft_rst_ni is low",
               dut.core_rst_n === 1'b0);
      soft_rst_ni = 1'b1;
      repeat (20) @(posedge clk);
      wcnt = 0;
      while (!(boot_done === 1'b1 && dut.core_rst_n === 1'b1) && wcnt < 10_000) begin
        @(posedge clk);
        wcnt++;
      end
      tb_check($sformatf("warm reset: boot_done and core released (%0d cycles)", wcnt),
               boot_done === 1'b1 && dut.core_rst_n === 1'b1);
      mism = 0;
      for (int i = 0; i < FW_NUM_INSTR_WORDS; i++)
        if (`ISRAM_W(i) !== golden_i[i]) mism++;
      tb_check($sformatf("warm reset: ISRAM image kept (%0d mismatches)", mism), mism == 0);

      wcnt = 0;
      while (!fw_done && wcnt < RUN_TIMEOUT_CYCLES) begin
        @(posedge clk);
        wcnt++;
      end
      if (!fw_done) begin
        tb_fail++;
        $display("[TB]   FAIL  second run did not finish within %0d cycles (last section: %s)",
                 RUN_TIMEOUT_CYCLES, last_section);
      end
    end

    summary();
  end

  // ───────────────────────────────────────────────────────────────────────
  //  Summary
  // ───────────────────────────────────────────────────────────────────────
  task automatic summary();
    repeat (5) @(posedge clk);

    $display("[TB] ------------------------------------------------------------------");
    $display("[TB]  RESULTS BY GROUP");
    foreach (g_key[i]) begin
      if (g_fail[g_key[i]] == 0)
        $display("[TB]   %-42s %6d  PASS", g_key[i], g_pass[g_key[i]]);
      else begin
        $display("[TB]   %-42s %6d  FAIL (%0d)", g_key[i],
                 g_pass[g_key[i]] + g_fail[g_key[i]], g_fail[g_key[i]]);
        $display("%s", g_detail[g_key[i]]);
      end
    end

    $display("[TB] --- E: TB-side checks");
    tb_check($sformatf("firmware ran to completion twice: cold boot + warm reset (%0d runs)", runs_done),
             runs_done == 2);
    tb_check($sformatf("firmware PASS total matches over both runs (fw %0d, tb %0d)", done_pass_tot, fw_pass),
             done_pass_tot == fw_pass);
    tb_check($sformatf("firmware FAIL total matches over both runs (fw %0d, tb %0d)", done_fail_tot, fw_fail),
             done_fail_tot == fw_fail);
    tb_check($sformatf("4.12: RESET_PC checked after every core reset (%0d of 2)", core_resets_seen),
             core_resets_seen == 2);
    tb_check($sformatf("4.12: every interrupt checked (%0d seen by TB, %0d counted by firmware)",
                       irq_entries, done_irqs_tot),
             irq_entries == done_irqs_tot && irq_entries != 0 && !chk_resume && !in_handler);
    tb_check($sformatf("no bus error during the run (%0d)", bus_err_cnt), bus_err_cnt == 0);
    tb_check($sformatf("no timer IRQ while CTRL.EN=0 (%0d violations)", timer_irq_violations),
             timer_irq_violations == 0);
    tb_check($sformatf("SPI CS0 and CS1 never low together (%0d cycles)", cs_both_low_cnt),
             cs_both_low_cnt == 0);
    tb_check($sformatf("SPI CS1 selected once per firmware run (%0d for %0d runs)", spi1_select_cnt, runs_done),
             spi1_select_cnt == runs_done);
    tb_check($sformatf("SPI CS0 (flash) not selected at runtime (%0d)", cs0_runtime_sel_cnt),
             cs0_runtime_sel_cnt == 0);
    tb_check($sformatf("no bus timeout monitor fired (sticky 0x%02h)",
                       {axi_rd_timeout_sticky, axi_wr_timeout_sticky, apb_timeout_sticky}),
             {axi_rd_timeout_sticky, axi_wr_timeout_sticky, apb_timeout_sticky} === 8'h00);

    $display("[TB] ------------------------------------------------------------------");
    $display("[TB]  Firmware checks : %0d passed, %0d failed", fw_pass, fw_fail);
    $display("[TB]  TB checks       : %0d passed, %0d failed", tb_pass, tb_fail);
    if (fw_done)
      $display("[TB]  Runtime         : %0d cycles (2 runs), %0d MMIO reads, %0d MMIO writes, %0d interrupts",
               cyc_cnt - run_start_cyc, bus_rd_cnt, bus_wr_cnt, done_irqs_tot);
    if (fw_done && runs_done == 2 && fw_fail == 0 && tb_fail == 0)
      $display("[TB]  *** SYSTEM TEST PASSED ***");
    else
      $display("[TB]  *** SYSTEM TEST FAILED ***");
    $display("[TB] ------------------------------------------------------------------");
    $finish;
  endtask

  // ───────────────────────────────────────────────────────────────────────
  //  Global timeout
  // ───────────────────────────────────────────────────────────────────────
  initial begin
    #80ms;
    $display("[TB] GLOBAL TIMEOUT (80 ms simulated), last section: %s", last_section);
    $finish;
  end

endmodule : soc_systest_tb
