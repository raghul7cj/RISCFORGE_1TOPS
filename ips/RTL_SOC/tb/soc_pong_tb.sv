// =============================================================================
// RISCFORGE 1TOPS — Pong demo testbench
// =============================================================================
// Boots the full riscforge_soc_subsystem from the Infineon S25FS512S flash
// model, then runs the Pong firmware (ips/RTL_SOC/mem/pong/pong.c) on the real
// RV32 core and plays it through the UART pins, the way the PC does on the board.
//
// The firmware must be the SIMULATION build (python build.py --sim): UART
// divisor 2 (32 clocks per bit) and a frame every 40 000 cycles. The board
// build (115200 baud, 30 fps) would need ~100x more cycles per frame.
//
// Board model around the DUT
//   - SPI CS0: S25FS512S flash holding the image (boot); CS1 unused
//   - UART TX: decoded by the TB at 16 * FW_UART_DIV clocks per bit and fed to
//              (a) a small ANSI terminal emulator (cursor position, clear
//                  screen / line, colours ignored) holding an 80-column screen,
//              (b) the binary packet parser (after the TB sends 0x02)
//   - UART RX: driven by the TB to inject key presses
//   - I2C pulled up, GPIO looped back, no other stimulus
//
// Sequence
//   A  flash preload             B  cold boot            C  image placement
//   D1 first screen: title, walls, both paddles, ball centred, serve prompt
//   D2 frame tick = TIMER0 CH0 compare every FW_FRAME_CYC + 1 cycles
//   D3 keys w w w s move the left paddle (top row 9 -> 6 -> 7)
//   D4 SPACE serves: the ball leaves the centre and travels
//   D5 0x02: binary packets — sync, checksum, field ranges, ball moving,
//          paddle position agrees with D3
//   D6 0x01: back to terminal mode, full redraw
//   E  no bus error, no bus-timeout monitor, no UART framing error
//
// The screen is printed at each step, so the log shows the game.
// -----------------------------------------------------------------------------
// Build the firmware first:  cd ips/RTL_SOC/mem/pong && python build.py --sim
// Test filelist: ips/RTL_SOC/tests/pong.f. Run from ips/RTL_SOC/sim/:
//     xrun -f ../tests/pong.f -l logs/pong.log            # normal run
//     xrun -f ../tests/pong.f -l logs/pong.log +VERBOSE   # also print every packet
//     xrun -f ../tests/pong.f -l logs/pong.log +WAVES     # write soc_pong_tb.shm
// =============================================================================
`timescale 1ns/1ps

module soc_pong_tb;

  import gpio_reg_pkg::GPIOCount;

  // Generated by build.py --sim: word counts, image paths, FW_UART_DIV,
  // FW_FRAME_CYC. Resolved through +incdir+../mem/pong/sim_build in tests/pong.f.
  `include "fw_params.svh"

  // ───────────────────────────────────────────────────────────────────────
  //  Configuration
  // ───────────────────────────────────────────────────────────────────────
  localparam int unsigned TIMER0_CNT           = 2;
  localparam int unsigned TIMER1_CNT           = 2;
  localparam int unsigned FLASH_POWERUP_CYCLES = 30_000;   // S25FS512S tPU = 300 us
  localparam time         CLK_PERIOD           = 10ns;     // 100 MHz

  localparam int unsigned IMAGE_WORDS = FW_NUM_INSTR_WORDS + FW_NUM_DATA_WORDS;
  localparam longint unsigned BOOT_TIMEOUT_CYCLES = 200_000 + 400 * IMAGE_WORDS;

  localparam int unsigned UART_BIT_CYC = 16 * FW_UART_DIV;

  localparam int unsigned DSRAM_WORDS = 8192;
  localparam int unsigned RES_WORDS   = 16;   // .results words (link.ld), not in the image compare

  localparam string FLASH_IMAGE = FW_FLASH_IMAGE;
  localparam string IMEM_HEX    = FW_IMEM_HEX;
  localparam string DMEM_HEX    = FW_DMEM_HEX;
  localparam string OTP_FILE    = "../../spi_slave_infinion/S25fs512s/model/s25fs512sOTP.mem";

  // Must match pong.c
  localparam int FW   = 80;
  localparam int FH   = 22;
  localparam int PH   = 4;
  localparam int P1X  = 2;
  localparam int P2X  = 77;
  localparam int MIDX = 40;

  // Terminal layout (pong.c): row 1 scores, row 2 top wall, field row y at
  // terminal row y + 3, bottom wall FH + 3, status FH + 4; column x at x + 1.
  localparam int SCR_ROWS = 32;
  localparam int SCR_COLS = 100;
  localparam int ROW_TOP_WALL = 2;
  localparam int ROW_BOT_WALL = FH + 3;
  localparam int ROW_STATUS   = FH + 4;

  // ───────────────────────────────────────────────────────────────────────
  //  Clock & reset
  // ───────────────────────────────────────────────────────────────────────
  logic clk;
  logic hard_rst_ni;
  logic soft_rst_ni;

  initial clk = 1'b0;
  always #(CLK_PERIOD/2) clk = ~clk;

  longint unsigned cyc_cnt;
  always_ff @(posedge clk) cyc_cnt <= cyc_cnt + 1;

  // ───────────────────────────────────────────────────────────────────────
  //  DUT pins
  // ───────────────────────────────────────────────────────────────────────
  localparam int unsigned NR_GPIOS = GPIOCount;

  logic                        boot_done;

  wire                         i2c_scl_i, i2c_sda_i;
  logic                        i2c_scl_o, i2c_scl_oen_o;
  logic                        i2c_sda_o, i2c_sda_oen_o;
  logic                        i2c_interrupt_o;

  logic [(TIMER0_CNT*2)-1:0]   timer0_irq;
  logic [(TIMER1_CNT*2)-1:0]   timer1_irq;

  logic                        uart_sin_i;
  logic                        uart_sout_o, uart_int_o;

  wire  [NR_GPIOS-1:0]         gpio_in_i;
  logic [NR_GPIOS-1:0]         gpio_out_o, gpio_tx_en_o, gpio_in_sync_o;
  logic                        gpio_global_interrupt_o;
  logic [NR_GPIOS-1:0]         gpio_pin_level_interrupts_o;

  logic                        spi_clk_o, spi_csn0_o, spi_csn1_o, spi_sdo0_o;
  wire                         spi_sdi1_i;
  logic [1:0]                  spi_events_o;

  logic [5:0]                  apb_timeout_sticky;
  logic                        axi_wr_timeout_sticky, axi_rd_timeout_sticky;

  initial uart_sin_i = 1'b1;           // UART RX idle

  tri1 i2c_scl_bus, i2c_sda_bus;
  assign i2c_scl_bus = (i2c_scl_oen_o === 1'b0) ? i2c_scl_o : 1'bz;
  assign i2c_sda_bus = (i2c_sda_oen_o === 1'b0) ? i2c_sda_o : 1'bz;
  assign i2c_scl_i   = i2c_scl_bus;
  assign i2c_sda_i   = i2c_sda_bus;

  assign gpio_in_i = gpio_out_o;

  // ───────────────────────────────────────────────────────────────────────
  //  SPI: flash on CS0, nothing on CS1
  // ───────────────────────────────────────────────────────────────────────
  wire flash_si, flash_so, flash_wpn, flash_resetn;
  assign flash_si     = spi_sdo0_o;
  assign flash_wpn    = 1'b1;
  assign flash_resetn = 1'b1;

  s25fs512s #(
    .UserPreload   ( 1           ),
    .mem_file_name ( FLASH_IMAGE ),
    .otp_file_name ( OTP_FILE    )
  ) u_flash (
    .SI       ( flash_si     ),
    .SO       ( flash_so     ),
    .SCK      ( spi_clk_o    ),
    .CSNeg    ( spi_csn0_o   ),
    .WPNeg    ( flash_wpn    ),
    .RESETNeg ( flash_resetn )
  );

  assign spi_sdi1_i = flash_so;

  // ───────────────────────────────────────────────────────────────────────
  //  DUT
  // ───────────────────────────────────────────────────────────────────────
  riscforge_soc_subsystem #(
    .TIMER0_CNT           ( TIMER0_CNT           ),
    .TIMER1_CNT           ( TIMER1_CNT           ),
    .SPI_BUFFER_DEPTH     ( 10                   ),
    .NUM_INSTR_WORDS      ( FW_NUM_INSTR_WORDS   ),
    .NUM_DATA_WORDS       ( FW_NUM_DATA_WORDS    ),
    .FLASH_POWERUP_CYCLES ( FLASH_POWERUP_CYCLES )
  ) dut (
    .clk_i                       ( clk                         ),
    .hard_rst_ni                 ( hard_rst_ni                 ),
    .soft_rst_ni                 ( soft_rst_ni                 ),
    .test_mode_i                 ( 1'b0                        ),
    .fetch_enable_i              ( 1'b1                        ),
    .boot_addr_i                 ( 32'h0000_0000               ),
    .boot_done_o                 ( boot_done                   ),

    .i2c_scl_i                   ( i2c_scl_i                   ),
    .i2c_scl_o                   ( i2c_scl_o                   ),
    .i2c_scl_oen_o               ( i2c_scl_oen_o               ),
    .i2c_sda_i                   ( i2c_sda_i                   ),
    .i2c_sda_o                   ( i2c_sda_o                   ),
    .i2c_sda_oen_o               ( i2c_sda_oen_o               ),
    .i2c_interrupt_o             ( i2c_interrupt_o             ),

    .timer0_irq_o                ( timer0_irq                  ),
    .timer1_irq_o                ( timer1_irq                  ),

    .uart_sin_i                  ( uart_sin_i                  ),
    .uart_sout_o                 ( uart_sout_o                 ),
    .uart_int_o                  ( uart_int_o                  ),

    .gpio_in_i                   ( gpio_in_i                   ),
    .gpio_out_o                  ( gpio_out_o                  ),
    .gpio_tx_en_o                ( gpio_tx_en_o                ),
    .gpio_in_sync_o              ( gpio_in_sync_o              ),
    .gpio_global_interrupt_o     ( gpio_global_interrupt_o     ),
    .gpio_pin_level_interrupts_o ( gpio_pin_level_interrupts_o ),

    .spi_clk_o                   ( spi_clk_o                   ),
    .spi_csn0_o                  ( spi_csn0_o                  ),
    .spi_csn1_o                  ( spi_csn1_o                  ),
    .spi_sdo0_o                  ( spi_sdo0_o                  ),
    .spi_sdi1_i                  ( spi_sdi1_i                  ),
    .spi_events_o                ( spi_events_o                ),

    .apb_timeout_sticky_o        ( apb_timeout_sticky          ),
    .axi_wr_timeout_sticky_o     ( axi_wr_timeout_sticky       ),
    .axi_rd_timeout_sticky_o     ( axi_rd_timeout_sticky       )
  );

  // ───────────────────────────────────────────────────────────────────────
  //  Hierarchical probes
  // ───────────────────────────────────────────────────────────────────────
  `define ISRAM_W(i)    dut.i_isram.u_imem.mem_array[i]
  `define DSRAM_W(i)    dut.i_dsram.mem[i]
  `define CORE_PC       dut.i_riscv_core.Fetch.PCF
  `define TMR(inst, ch) dut.inst.TIMER_GEN[ch].timer_i

  wire core_running = (dut.core_rst_n === 1'b1);

  // ───────────────────────────────────────────────────────────────────────
  //  Checks
  // ───────────────────────────────────────────────────────────────────────
  bit          verbose;
  bit          fw_running;
  int unsigned tb_pass, tb_fail;

  task automatic tb_check(input string label, input bit cond);
    if (cond) begin
      tb_pass++;
      $display("[TB]   PASS  %s", label);
    end else begin
      tb_fail++;
      $display("[TB]   FAIL  %s", label);
    end
  endtask

  // ───────────────────────────────────────────────────────────────────────
  //  Frame tick: TIMER0 CH0 compare match (one-cycle irq pulse)
  // ───────────────────────────────────────────────────────────────────────
  int unsigned     frames, frame_period_bad;
  longint unsigned last_tick_cyc, last_period;

  always @(posedge clk) begin
    if (core_running && `TMR(i_apb_timer0, 0).irq_o[1] === 1'b1) begin
      if (frames >= 1) begin
        last_period = cyc_cnt - last_tick_cyc;
        if (last_period != FW_FRAME_CYC + 1) begin
          frame_period_bad++;
          if (frame_period_bad <= 5)
            $display("[TB]   frame %0d period %0d cycles, expected %0d",
                     frames, last_period, FW_FRAME_CYC + 1);
        end
      end
      last_tick_cyc = cyc_cnt;
      frames++;
    end
  end

  task automatic wait_frames(input int unsigned n);
    int unsigned target;
    target = frames + n;
    while (frames < target) @(posedge clk);
  endtask

  // ───────────────────────────────────────────────────────────────────────
  //  Bus errors on the core's crossbar port (none expected)
  // ───────────────────────────────────────────────────────────────────────
  int unsigned bus_rd_cnt, bus_wr_cnt, bus_err_cnt;

  always @(posedge clk) begin
    if (fw_running) begin
      if (dut.xbar_slv_resp[0].b_valid === 1'b1 && dut.xbar_slv_req[0].b_ready === 1'b1) begin
        bus_wr_cnt++;
        if (dut.xbar_slv_resp[0].b.resp !== 2'b00) begin
          bus_err_cnt++;
          $display("[BUS]  write error resp %0d (cyc %0d, PC 0x%08h)",
                   dut.xbar_slv_resp[0].b.resp, cyc_cnt, `CORE_PC);
        end
      end
      if (dut.xbar_slv_resp[0].r_valid === 1'b1 && dut.xbar_slv_req[0].r_ready === 1'b1) begin
        bus_rd_cnt++;
        if (dut.xbar_slv_resp[0].r.resp !== 2'b00) begin
          bus_err_cnt++;
          $display("[BUS]  read error resp %0d (cyc %0d, PC 0x%08h)",
                   dut.xbar_slv_resp[0].r.resp, cyc_cnt, `CORE_PC);
        end
      end
    end
  end

  // ───────────────────────────────────────────────────────────────────────
  //  UART RX side of the PC: decode uart_sout_o
  // ───────────────────────────────────────────────────────────────────────
  int unsigned uart_rx_bytes, uart_frame_err;
  bit          bin_mode;            // set when the TB sends 0x02, cleared on 0x01

  initial begin
    logic [7:0] b;
    forever begin
      @(negedge uart_sout_o);
      repeat (UART_BIT_CYC / 2) @(posedge clk);
      if (uart_sout_o !== 1'b0) continue;           // glitch / X at reset
      for (int i = 0; i < 8; i++) begin
        repeat (UART_BIT_CYC) @(posedge clk);
        b[i] = uart_sout_o;
      end
      repeat (UART_BIT_CYC) @(posedge clk);
      if (uart_sout_o !== 1'b1) begin
        uart_frame_err++;
        if (uart_frame_err <= 5)
          $display("[UART] framing error after byte 0x%02h (cyc %0d)", b, cyc_cnt);
      end
      uart_rx_bytes++;
      if (bin_mode) pkt_byte(b);
      else          term_byte(b);
    end
  end

  // PC -> SoC key press, 8N1 at the firmware's divisor
  task automatic send_key(input logic [7:0] c);
    uart_sin_i = 1'b0;
    repeat (UART_BIT_CYC) @(posedge clk);
    for (int i = 0; i < 8; i++) begin
      uart_sin_i = c[i];
      repeat (UART_BIT_CYC) @(posedge clk);
    end
    uart_sin_i = 1'b1;
    repeat (2 * UART_BIT_CYC) @(posedge clk);
  endtask

  // ───────────────────────────────────────────────────────────────────────
  //  Terminal emulator: the ANSI subset pong.c uses
  //    ESC[r;cH  cursor   ESC[2J  clear screen   ESC[2K  clear line
  //    ESC[..m   colours (ignored)   ESC[?25l / h  cursor visibility (ignored)
  // ───────────────────────────────────────────────────────────────────────
  logic [7:0]  scr [1:SCR_ROWS][1:SCR_COLS];
  int          cur_r = 1, cur_c = 1;
  int unsigned esc_state;           // 0 text, 1 after ESC, 2 inside CSI
  int          csi_p [4];
  int unsigned csi_n;
  int unsigned n_clear_screen, n_csi;

  task automatic scr_clear();
    for (int r = 1; r <= SCR_ROWS; r++)
      for (int c = 1; c <= SCR_COLS; c++)
        scr[r][c] = 8'h20;
  endtask

  task automatic term_byte(input logic [7:0] b);
    if (b == 8'h1B) begin           // ESC always starts a new sequence
      esc_state = 1;
      return;
    end
    case (esc_state)
      0: begin
        if (b == 8'h0D)
          cur_c = 1;
        else if (b == 8'h0A)
          cur_r++;
        else if (b >= 8'h20 && b <= 8'h7E) begin
          if (cur_r >= 1 && cur_r <= SCR_ROWS && cur_c >= 1 && cur_c <= SCR_COLS)
            scr[cur_r][cur_c] = b;
          cur_c++;
        end
      end
      1: begin
        if (b == "[") begin
          esc_state = 2;
          csi_n     = 0;
          foreach (csi_p[i]) csi_p[i] = -1;
        end else
          esc_state = 0;
      end
      default: begin
        if (b >= "0" && b <= "9") begin
          if (csi_p[csi_n] < 0) csi_p[csi_n] = 0;
          csi_p[csi_n] = csi_p[csi_n] * 10 + (b - "0");
        end else if (b == ";") begin
          if (csi_n < 3) csi_n++;
        end else if (b == "?") begin
          // private mode prefix
        end else begin
          n_csi++;
          esc_state = 0;
          case (b)
            "H": begin
              cur_r = (csi_p[0] < 1) ? 1 : csi_p[0];
              cur_c = (csi_p[1] < 1) ? 1 : csi_p[1];
            end
            "J": if (csi_p[0] == 2) begin
              scr_clear();
              n_clear_screen++;
            end
            "K": if (csi_p[0] == 2 && cur_r >= 1 && cur_r <= SCR_ROWS)
              for (int c = 1; c <= SCR_COLS; c++) scr[cur_r][c] = 8'h20;
            default: ;  // m, h, l
          endcase
        end
      end
    endcase
  endtask

  function automatic string scr_row(input int r, input int c0 = 1, input int c1 = FW);
    string s;
    s = "";
    for (int c = c0; c <= c1; c++)
      s = $sformatf("%s%c", s, scr[r][c]);
    return s;
  endfunction

  function automatic bit row_has(input int r, input string pat);
    string s;
    s = scr_row(r);
    for (int i = 0; i + pat.len() <= s.len(); i++)
      if (s.substr(i, i + pat.len() - 1) == pat) return 1'b1;
    return 1'b0;
  endfunction

  function automatic bit row_all(input int r, input logic [7:0] ch);
    for (int c = 1; c <= FW; c++)
      if (scr[r][c] != ch) return 1'b0;
    return 1'b1;
  endfunction

  // Field coordinates of the 'O' (x = -1 if none on the field)
  task automatic find_ball(output int x, output int y, output int count);
    x = -1; y = -1; count = 0;
    for (int r = ROW_TOP_WALL + 1; r < ROW_BOT_WALL; r++)
      for (int c = 1; c <= FW; c++)
        if (scr[r][c] == "O") begin
          count++;
          x = c - 1;
          y = r - 3;
        end
  endtask

  // Field row of the top '#' in column x, and how many '#' it has
  task automatic find_paddle(input int x, output int top, output int count);
    top = -1; count = 0;
    for (int r = ROW_TOP_WALL + 1; r < ROW_BOT_WALL; r++)
      if (scr[r][x + 1] == "#") begin
        if (top < 0) top = r - 3;
        count++;
      end
  endtask

  task automatic dump_screen(input string title);
    $display("[SCR] ---- %s (frame %0d, cyc %0d)", title, frames, cyc_cnt);
    for (int r = 1; r <= ROW_STATUS; r++)
      $display("[SCR] |%s|", scr_row(r));
  endtask

  // ───────────────────────────────────────────────────────────────────────
  //  Binary packet parser
  //    0xA5 0x5A | bx(2) by(2) | p1 p2 | s1 s2 | state | rsvd(4) | sum
  // ───────────────────────────────────────────────────────────────────────
  logic [7:0]  pkt [16];
  int unsigned pkt_idx;
  int unsigned pkt_ok, pkt_bad, pkt_range_err, pkt_ball_moved;
  int          pk_bx, pk_by, pk_p1, pk_p2, pk_s1, pk_s2, pk_state;
  int          prev_bx, prev_by;
  bit          have_prev;

  task automatic pkt_byte(input logic [7:0] b);
    logic [7:0] sum;
    if (pkt_idx == 0) begin
      if (b == 8'hA5) pkt[pkt_idx++] = b;
      return;
    end
    if (pkt_idx == 1) begin
      if (b == 8'h5A)      pkt[pkt_idx++] = b;
      else if (b != 8'hA5) pkt_idx = 0;
      return;
    end
    pkt[pkt_idx++] = b;
    if (pkt_idx < 16) return;
    pkt_idx = 0;

    sum = 8'h00;
    for (int i = 2; i < 15; i++) sum += pkt[i];
    if (sum != pkt[15]) begin
      pkt_bad++;
      if (pkt_bad <= 5) $display("[PKT]  checksum error: sum 0x%02h, got 0x%02h", sum, pkt[15]);
      return;
    end

    pkt_ok++;
    pk_bx    = $signed({pkt[3], pkt[2]});
    pk_by    = $signed({pkt[5], pkt[4]});
    pk_p1    = pkt[6];
    pk_p2    = pkt[7];
    pk_s1    = pkt[8];
    pk_s2    = pkt[9];
    pk_state = pkt[10] & 8'h0F;

    if (pk_by < 0 || pk_by >= FH * 16 || pk_bx < -32 || pk_bx >= (FW + 2) * 16 ||
        pk_p1 > FH - PH || pk_p2 > FH - PH || pk_state > 4 || pk_s1 > 7 || pk_s2 > 7) begin
      pkt_range_err++;
      if (pkt_range_err <= 5)
        $display("[PKT]  out of range: bx %0d by %0d p1 %0d p2 %0d s %0d:%0d state %0d",
                 pk_bx, pk_by, pk_p1, pk_p2, pk_s1, pk_s2, pk_state);
    end
    if (have_prev && (pk_bx != prev_bx || pk_by != prev_by)) pkt_ball_moved++;
    prev_bx   = pk_bx;
    prev_by   = pk_by;
    have_prev = 1'b1;

    if (verbose || pkt_ok <= 6 || pkt_ok % 10 == 0)
      $display("[PKT]  #%0d  ball (%0d.%02d, %0d.%02d)  paddles %0d / %0d  score %0d:%0d  state %0d",
               pkt_ok, pk_bx >>> 4, ((pk_bx & 15) * 100) >> 4, pk_by >>> 4,
               ((pk_by & 15) * 100) >> 4, pk_p1, pk_p2, pk_s1, pk_s2, pk_state);
  endtask

  // ───────────────────────────────────────────────────────────────────────
  //  Flash backdoor readback
  // ───────────────────────────────────────────────────────────────────────
  task automatic flash_read_word(input int unsigned word_addr, output logic [31:0] data);
    integer b0, b1, b2, b3;
    u_flash.memory_features_i0.read_mem_w(b0, word_addr * 4 + 0);
    u_flash.memory_features_i0.read_mem_w(b1, word_addr * 4 + 1);
    u_flash.memory_features_i0.read_mem_w(b2, word_addr * 4 + 2);
    u_flash.memory_features_i0.read_mem_w(b3, word_addr * 4 + 3);
    data = {b3[7:0], b2[7:0], b1[7:0], b0[7:0]};
  endtask

  // ───────────────────────────────────────────────────────────────────────
  //  Main sequence
  // ───────────────────────────────────────────────────────────────────────
  logic [31:0] golden_i [0:FW_NUM_INSTR_WORDS-1];
  logic [31:0] golden_d [0:FW_NUM_DATA_WORDS-1];

  initial begin
    longint unsigned wcnt;
    logic [31:0]     fw;
    int unsigned     mism;
    int              bx, by, nball, ptop, pcnt, ptop2, pcnt2;
    int              x0, y0;
    int unsigned     clears0, pkt0;

    verbose = $test$plusargs("VERBOSE");
    scr_clear();

    if ($test$plusargs("WAVES")) begin
      `ifdef XCELIUM
        $shm_open("soc_pong_tb.shm");
        $shm_probe(soc_pong_tb, "ASMC");
        $display("[TB] waveforms -> soc_pong_tb.shm");
      `else
        $dumpfile("soc_pong_tb.vcd");
        $dumpvars(0, soc_pong_tb);
        $display("[TB] waveforms -> soc_pong_tb.vcd");
      `endif
    end

    $readmemh(IMEM_HEX, golden_i);
    $readmemh(DMEM_HEX, golden_d);

    hard_rst_ni = 1'b0;
    soft_rst_ni = 1'b1;
    repeat (10) @(posedge clk);

    $display("[TB] --- RISCFORGE SoC — Pong demo");
    $display("[TB]  Flash image : %s", FLASH_IMAGE);
    $display("[TB]  Image       : %0d ISRAM words + %0d DSRAM words", FW_NUM_INSTR_WORDS, FW_NUM_DATA_WORDS);
    $display("[TB]  UART        : divisor %0d, %0d clocks per bit", FW_UART_DIV, UART_BIT_CYC);
    $display("[TB]  Frame       : every %0d cycles", FW_FRAME_CYC + 1);
    if (FW_UART_DIV > 8)
      $display("[TB]  WARNING: this looks like the board image; build with python build.py --sim");

    // ── A: flash preload ─────────────────────────────────────────────
    $display("[TB] --- A: flash image preload");
    flash_read_word(0, fw);
    tb_check($sformatf("flash word 0 = 0x%08h (expected 0x%08h)", fw, golden_i[0]), fw === golden_i[0]);
    flash_read_word(IMAGE_WORDS - 1, fw);
    tb_check($sformatf("flash last word = 0x%08h (expected 0x%08h)", fw, golden_d[FW_NUM_DATA_WORDS-1]),
             fw === golden_d[FW_NUM_DATA_WORDS-1]);

    // ── B: cold boot ─────────────────────────────────────────────────
    $display("[TB] --- B: cold boot from SPI flash");
    hard_rst_ni = 1'b1;
    wcnt = 0;
    while (!boot_done && wcnt < BOOT_TIMEOUT_CYCLES) begin
      @(posedge clk);
      wcnt++;
    end
    tb_check($sformatf("boot_done asserted (cyc %0d)", cyc_cnt), boot_done === 1'b1);
    if (!boot_done) summary();

    // ── C: image placement ───────────────────────────────────────────
    $display("[TB] --- C: image placement in ISRAM / DSRAM");
    mism = 0;
    for (int i = 0; i < FW_NUM_INSTR_WORDS; i++)
      if (`ISRAM_W(i) !== golden_i[i]) mism++;
    tb_check($sformatf("ISRAM holds all %0d instruction words (%0d mismatches)", FW_NUM_INSTR_WORDS, mism),
             mism == 0);
    mism = 0;
    for (int i = RES_WORDS; i < FW_NUM_DATA_WORDS; i++)
      if (`DSRAM_W(i) !== golden_d[i]) mism++;
    tb_check($sformatf("DSRAM holds data words %0d..%0d (%0d mismatches)",
                       RES_WORDS, FW_NUM_DATA_WORDS - 1, mism), mism == 0);

    fw_running = 1'b1;

    // ── D1: first screen ─────────────────────────────────────────────
    $display("[TB] --- D1: first screen after boot");
    wait_frames(12);
    dump_screen("after boot");
    tb_check("score line shows RISCFORGE PONG", row_has(1, "RISCFORGE PONG"));
    tb_check("score line shows LEFT 0 : 0 RIGHT (CPU)", row_has(1, "LEFT (w/s)  0  :  0  RIGHT (CPU)"));
    tb_check("top wall complete", row_all(ROW_TOP_WALL, "="));
    tb_check("bottom wall complete", row_all(ROW_BOT_WALL, "="));
    find_paddle(P1X, ptop, pcnt);
    tb_check($sformatf("left paddle at rows %0d..%0d (got top %0d, %0d cells)",
                       (FH - PH) / 2, (FH - PH) / 2 + PH - 1, ptop, pcnt),
             ptop == (FH - PH) / 2 && pcnt == PH);
    find_paddle(P2X, ptop2, pcnt2);
    tb_check($sformatf("right paddle at rows %0d..%0d (got top %0d, %0d cells)",
                       (FH - PH) / 2, (FH - PH) / 2 + PH - 1, ptop2, pcnt2),
             ptop2 == (FH - PH) / 2 && pcnt2 == PH);
    find_ball(bx, by, nball);
    tb_check($sformatf("one ball, centred at (%0d,%0d) (got (%0d,%0d), %0d balls)",
                       MIDX, FH / 2, bx, by, nball),
             nball == 1 && bx == MIDX && by == FH / 2);
    tb_check("status line shows the serve prompt", row_has(ROW_STATUS, "SPACE serve"));

    // ── D2: frame tick ───────────────────────────────────────────────
    $display("[TB] --- D2: frame tick");
    tb_check($sformatf("%0d frames, every period = %0d cycles (%0d wrong, last %0d)",
                       frames, FW_FRAME_CYC + 1, frame_period_bad, last_period),
             frames >= 12 && frame_period_bad == 0);

    // ── D3: paddle keys ──────────────────────────────────────────────
    $display("[TB] --- D3: keys w w w -> left paddle up 3, then s -> down 1");
    send_key("w"); send_key("w"); send_key("w");
    wait_frames(6);
    find_paddle(P1X, ptop, pcnt);
    tb_check($sformatf("after w w w: left paddle top row %0d (expected %0d), %0d cells",
                       ptop, (FH - PH) / 2 - 3, pcnt),
             ptop == (FH - PH) / 2 - 3 && pcnt == PH);
    send_key("s");
    wait_frames(6);
    find_paddle(P1X, ptop, pcnt);
    tb_check($sformatf("after s: left paddle top row %0d (expected %0d), %0d cells",
                       ptop, (FH - PH) / 2 - 2, pcnt),
             ptop == (FH - PH) / 2 - 2 && pcnt == PH);
    find_paddle(P2X, ptop2, pcnt2);
    tb_check($sformatf("right (CPU) paddle unaffected by w/s (top %0d)", ptop2),
             ptop2 == (FH - PH) / 2 && pcnt2 == PH);

    // ── D4: serve ────────────────────────────────────────────────────
    $display("[TB] --- D4: SPACE serves");
    find_ball(x0, y0, nball);
    send_key(" ");
    for (int k = 0; k < 8; k++) begin
      wait_frames(5);
      find_ball(bx, by, nball);
      $display("[TB]   frame %0d: ball at (%0d,%0d)", frames, bx, by);
    end
    dump_screen("ball in play");
    tb_check("status line left the serve prompt", !row_has(ROW_STATUS, "SPACE serve"));
    tb_check($sformatf("ball travelled from (%0d,%0d) to (%0d,%0d) in 40 frames",
                       x0, y0, bx, by),
             nball == 1 && (bx - x0 >= 10 || x0 - bx >= 10));

    // ── D5: binary mode ──────────────────────────────────────────────
    $display("[TB] --- D5: 0x02 -> binary packets for pong_viewer.py");
    clears0  = n_clear_screen;
    pkt0     = pkt_ok;
    bin_mode = 1'b1;
    send_key(8'h02);
    wait_frames(30);
    tb_check($sformatf("%0d packets received in 30 frames", pkt_ok - pkt0), pkt_ok - pkt0 >= 25);
    tb_check($sformatf("no checksum errors (%0d)", pkt_bad), pkt_bad == 0);
    tb_check($sformatf("all packet fields in range (%0d errors)", pkt_range_err), pkt_range_err == 0);
    tb_check($sformatf("ball position changed in %0d of %0d packets", pkt_ball_moved, pkt_ok - 1),
             pkt_ball_moved * 2 >= pkt_ok);
    tb_check($sformatf("packet left paddle = %0d, same as the screen in D3", pk_p1),
             pk_p1 == (FH - PH) / 2 - 2);

    // ── D6: back to terminal mode ────────────────────────────────────
    $display("[TB] --- D6: 0x01 -> terminal mode, full redraw");
    bin_mode = 1'b0;
    esc_state = 0;
    send_key(8'h01);
    wait_frames(15);
    dump_screen("back in terminal mode");
    tb_check($sformatf("screen cleared and redrawn (%0d clears)", n_clear_screen - clears0),
             n_clear_screen > clears0);
    tb_check("title and walls redrawn",
             row_has(1, "RISCFORGE PONG") && row_all(ROW_TOP_WALL, "=") && row_all(ROW_BOT_WALL, "="));
    find_paddle(P1X, ptop, pcnt);
    tb_check($sformatf("left paddle redrawn at top row %0d", ptop),
             ptop == (FH - PH) / 2 - 2 && pcnt == PH);

    summary();
  end

  // ───────────────────────────────────────────────────────────────────────
  //  Summary
  // ───────────────────────────────────────────────────────────────────────
  task automatic summary();
    repeat (5) @(posedge clk);

    $display("[TB] --- E: whole-run checks");
    tb_check($sformatf("no bus error on the core port (%0d reads, %0d writes, %0d errors)",
                       bus_rd_cnt, bus_wr_cnt, bus_err_cnt), bus_err_cnt == 0);
    tb_check($sformatf("no bus timeout monitor fired (sticky 0x%02h)",
                       {axi_rd_timeout_sticky, axi_wr_timeout_sticky, apb_timeout_sticky}),
             {axi_rd_timeout_sticky, axi_wr_timeout_sticky, apb_timeout_sticky} === 8'h00);
    tb_check($sformatf("no UART framing error (%0d bytes, %0d errors)", uart_rx_bytes, uart_frame_err),
             uart_frame_err == 0 && uart_rx_bytes > 0);
    tb_check($sformatf("frame period constant over %0d frames (%0d wrong)", frames, frame_period_bad),
             frame_period_bad == 0);

    $display("[TB] ------------------------------------------------------------------");
    $display("[TB]  TB checks : %0d passed, %0d failed", tb_pass, tb_fail);
    $display("[TB]  Run       : %0d cycles, %0d frames, %0d UART bytes, %0d packets",
             cyc_cnt, frames, uart_rx_bytes, pkt_ok);
    if (tb_fail == 0)
      $display("[TB]  *** PONG DEMO TEST PASSED ***");
    else
      $display("[TB]  *** PONG DEMO TEST FAILED ***");
    $display("[TB] ------------------------------------------------------------------");
    $finish;
  endtask

  // ───────────────────────────────────────────────────────────────────────
  //  Global timeout
  // ───────────────────────────────────────────────────────────────────────
  initial begin
    #150ms;
    $display("[TB] GLOBAL TIMEOUT (150 ms simulated), frame %0d, PC 0x%08h", frames, `CORE_PC);
    dump_screen("at timeout");
    $finish;
  end

