// =============================================================================
// RISCFORGE 1TOPS — Full Boot-to-Runtime Testbench (Timer 0 test program)
// =============================================================================
// End-to-end test of the complete flow, with the REAL RV32IM core:
//
//   1. COLD BOOT   Bootloader powers up the Infineon S25FS512S flash model,
//                  clears ISRAM+DSRAM, then streams the image over SPI.
//                  Instruction words -> ISRAM (0x0001_0000)
//                  Data words        -> DSRAM (0x0002_0000)
//   2. RESET SEQ   spi_rst_n released before core_rst_n; core and peripherals
//                  released together once the image is in place.
//   3. BOOTROM     Core comes out of reset at 0x0000_0000 and runs the ROM:
//                      lui x2, 0x28      -> sp = 0x0002_8000 (top of DSRAM)
//                      jal x0, +0xFFFC   -> 0x0001_0000 (ISRAM base)
//   4. RUNTIME     The loaded program exercises an MMIO round-trip through
//                  hybrid_mem_interface -> AXI-Lite -> crossbar -> APB bridge
//                  -> Timer 0, then a direct DSRAM store:
//
//                      lui  x1, 0x40001     ; Timer 0 base
//                      addi x2, x0, 9       ; EN=1, PRESCALER=1
//                      sw   x2, 4(x1)       ; TIMER_CTRL = 9      (MMIO write)
//                      lw   x3, 4(x1)       ; readback            (MMIO read)
//                      lui  x4, 0x20        ; DSRAM base
//                      beq  x2, x3, +12     ; readback matches?
//                      addi x5, x0, 0       ;   no  -> FAIL
//                      jal  x0, +8
//                      addi x5, x0, 1       ;   yes -> PASS
//                      sw   x5, 0(x4)       ; DSRAM[0] = result   (direct SRAM)
//                      beq  x0, x0, 0       ; park
//
// So a full pass proves: SPI boot, the ISRAM/DSRAM split, the BootROM reset
// vector, instruction fetch through the demux, the direct DSRAM data path,
// and the MMIO path across the whole AXI+APB fabric.
//
// -----------------------------------------------------------------------------
// Flash image
// -----------------------------------------------------------------------------
// Generated by ips/mem_files/gen_flash_image.py (which reuses the vendor
// converter spi_unified_mem_instr_data.py) from:
//     riscforge_timer0_test.hex   11 instruction words
//     riscforge_timer0_dmem.hex    4 data words
// into ips/mem_files/riscforge_timer0_flash.mem — a little-endian byte stream
// from flash address 0, which is what the bootloader's 0x03 read + RX-FIFO
// byte swap (bootloader.sv:525) reconstructs into 32-bit words.
//
// Regenerate with:   cd ips/mem_files && python gen_flash_image.py
//
// -----------------------------------------------------------------------------
// Run (working directory MUST be RTL_SOC/ — all relative paths assume it)
// -----------------------------------------------------------------------------
//     xrun -f rtl/soc_timer0_boot_run.f            # normal run, no waveforms
//     xrun -f rtl/soc_timer0_boot_run.f +WAVES     # add SHM waveform dump
//
// All relative paths (flash image, boot ROM hex) assume that working directory.
// =============================================================================
`timescale 1ns/1ps

module soc_timer0_boot_run_tb;

  import gpio_reg_pkg::GPIOCount;

  // ───────────────────────────────────────────────────────────────────────
  //  Test configuration — must match gen_flash_image.py output
  // ───────────────────────────────────────────────────────────────────────
  localparam int unsigned NUM_INSTR_WORDS = 11;
  localparam int unsigned NUM_DATA_WORDS  = 4;

  // Must match ISRAM_NUM_WORDS / DSRAM_NUM_WORDS in riscforge_soc_subsystem.sv.
  // Boot writes each SRAM once per word to clear it, then once per image word.
  localparam int unsigned SRAM_WORDS   = 8192;
  localparam int unsigned EXP_ISRAM_WR = SRAM_WORDS + NUM_INSTR_WORDS;
  localparam int unsigned EXP_DSRAM_WR = SRAM_WORDS + NUM_DATA_WORDS;

  // Vendor model tPU = 300 us. At 100 MHz (10 ns) that is 30_000 cycles.
  localparam int unsigned FLASH_POWERUP_CYCLES = 30_000;

  localparam time CLK_PERIOD = 10ns;

  // Boot cost is dominated by the SRAM clear: the bootloader zeroes every
  // ISRAM and DSRAM word (16384 total) with one AXI write each. Add the
  // 300 us flash power-up and 15 SPI word reads on top.
  localparam int unsigned BOOT_TIMEOUT_CYCLES = 500_000;

  // The program is 11 instructions plus the 2-instruction ROM preamble.
  localparam int unsigned RUN_TIMEOUT_CYCLES  = 5_000;

  // Memory map (mirrors riscforge_soc_subsystem.sv)
  localparam logic [31:0] BOOTROM_BASE = 32'h0000_0000;
  localparam logic [31:0] ISRAM_BASE   = 32'h0001_0000;
  localparam logic [31:0] DSRAM_BASE   = 32'h0002_0000;
  localparam logic [31:0] TIMER0_BASE  = 32'h4000_1000;

  localparam logic [31:0] EXPECTED_SP       = 32'h0002_8000;  // ROM: lui x2,0x28
  localparam logic [31:0] EXPECTED_CTRL     = 32'h0000_0009;  // EN=1, PRESCALER=1
  localparam logic [31:0] EXPECTED_RESULT   = 32'h0000_0001;  // PASS code
  localparam logic [31:0] DATA0_PRELOAD     = 32'hDEAD_BEEF;  // overwritten at runtime

  // Data image sentinels — words 1..3 are never touched by the program, so
  // they prove the DSRAM half of the boot load survived into runtime.
  logic [31:0] golden_data [0:NUM_DATA_WORDS-1];
  logic [31:0] golden_instr[0:NUM_INSTR_WORDS-1];

  initial begin
    golden_instr[0]  = 32'h400010B7;  // lui  x1, 0x40001
    golden_instr[1]  = 32'h00900113;  // addi x2, x0, 9
    golden_instr[2]  = 32'h0020A223;  // sw   x2, 4(x1)
    golden_instr[3]  = 32'h0040A183;  // lw   x3, 4(x1)
    golden_instr[4]  = 32'h00020237;  // lui  x4, 0x20
    golden_instr[5]  = 32'h00310663;  // beq  x2, x3, +12
    golden_instr[6]  = 32'h00000293;  // addi x5, x0, 0
    golden_instr[7]  = 32'h0080006F;  // jal  x0, +8
    golden_instr[8]  = 32'h00100293;  // addi x5, x0, 1
    golden_instr[9]  = 32'h00522023;  // sw   x5, 0(x4)
    golden_instr[10] = 32'h00000063;  // beq  x0, x0, 0

    golden_data[0]   = 32'hDEAD_BEEF;
    golden_data[1]   = 32'hCAFE_BABE;
    golden_data[2]   = 32'h1234_5678;
    golden_data[3]   = 32'hA5A5_A5A5;
  end

  // ───────────────────────────────────────────────────────────────────────
  //  Clock & Reset
  // ───────────────────────────────────────────────────────────────────────
  logic clk;
  logic hard_rst_ni;
  logic soft_rst_ni;

  initial clk = 1'b0;
  always #(CLK_PERIOD/2) clk = ~clk;

  // ───────────────────────────────────────────────────────────────────────
  //  SoC external interface
  // ───────────────────────────────────────────────────────────────────────
  logic boot_done;

  logic i2c_scl_i, i2c_scl_o, i2c_scl_oen_o;
  logic i2c_sda_i, i2c_sda_o, i2c_sda_oen_o;
  logic i2c_interrupt_o;

  localparam int unsigned TIMER0_CNT = 2;
  localparam int unsigned TIMER1_CNT = 2;
  logic [(TIMER0_CNT*2)-1:0] timer0_irq;
  logic [(TIMER1_CNT*2)-1:0] timer1_irq;

  logic uart_sin_i, uart_sout_o, uart_int_o;
  logic uart_out1n_o, uart_out2n_o, uart_rtsn_o, uart_dtrn_o;
  logic uart_ctsn_i, uart_dsrn_i, uart_dcdn_i, uart_rin_i;

  localparam int unsigned NR_GPIOS = GPIOCount;
  logic [NR_GPIOS-1:0] gpio_in_i, gpio_out_o, gpio_tx_en_o, gpio_in_sync_o;
  logic gpio_global_interrupt_o;
  logic [NR_GPIOS-1:0] gpio_pin_level_interrupts_o;

  logic spi_clk_o;
  logic spi_csn0_o, spi_csn1_o, spi_csn2_o, spi_csn3_o;
  logic [1:0] spi_mode_o;
  logic spi_sdo0_o, spi_sdo1_o, spi_sdo2_o, spi_sdo3_o;
  logic spi_sdi0_i, spi_sdi1_i, spi_sdi2_i, spi_sdi3_i;
  logic [1:0] spi_events_o;

  initial begin
    i2c_scl_i   = 1'b1;
    i2c_sda_i   = 1'b1;
    uart_sin_i  = 1'b1;
    uart_ctsn_i = 1'b1;
    uart_dsrn_i = 1'b1;
    uart_dcdn_i = 1'b1;
    uart_rin_i  = 1'b1;
    gpio_in_i   = '0;
    spi_sdi0_i  = 1'b0;   // IO0 not sampled in standard-SPI reads
    spi_sdi2_i  = 1'b0;
    spi_sdi3_i  = 1'b0;
  end

  // ───────────────────────────────────────────────────────────────────────
  //  Vendor SPI flash model (Infineon S25FS512S)
  // ───────────────────────────────────────────────────────────────────────
  // SI / SO are inout on the vendor model. In standard SPI mode the SoC
  // drives sdo0 (MOSI) and samples IO1 for MISO (spi_master_rx.sv:84), so
  // route them through explicit wires to avoid direction ambiguity.
  //
  // The image is preloaded via mem_file_name rather than the backdoor
  // write_mem_w task, so the flash contents come from exactly the file the
  // Python converters produced.
  wire flash_si;
  wire flash_so;
  wire flash_wpn;
  wire flash_resetn;

  assign flash_si     = spi_sdo0_o;   // MOSI from master
  assign spi_sdi1_i   = flash_so;     // MISO into master (IO1)
  assign flash_wpn    = 1'b1;         // write protect deasserted
  assign flash_resetn = 1'b1;         // chip not held in reset

  s25fs512s #(
    .UserPreload   ( 1                                                        ),
    .mem_file_name ( "../mem_files/riscforge_timer0_flash.mem"                ),
    .otp_file_name ( "../spi_slave_infinion/S25fs512s/model/s25fs512sOTP.mem" )
  ) u_flash (
    .SI       ( flash_si     ),
    .SO       ( flash_so     ),
    .SCK      ( spi_clk_o    ),
    .CSNeg    ( spi_csn0_o   ),
    .WPNeg    ( flash_wpn    ),
    .RESETNeg ( flash_resetn )
  );

  // ───────────────────────────────────────────────────────────────────────
  //  DUT
  // ───────────────────────────────────────────────────────────────────────
  riscforge_soc_subsystem #(
    .TIMER0_CNT           ( TIMER0_CNT           ),
    .TIMER1_CNT           ( TIMER1_CNT           ),
    .SPI_BUFFER_DEPTH     ( 10                   ),
    .NUM_INSTR_WORDS      ( NUM_INSTR_WORDS      ),
    .NUM_DATA_WORDS       ( NUM_DATA_WORDS       ),
    .FLASH_POWERUP_CYCLES ( FLASH_POWERUP_CYCLES )
  ) dut (
    .clk_i                       ( clk                         ),
    .hard_rst_ni                 ( hard_rst_ni                 ),
    .soft_rst_ni                 ( soft_rst_ni                 ),
    .test_mode_i                 ( 1'b0                        ),

    // Legacy stub-era controls: the reset vector is now the RESET_PC
    // parameter on the core, so these are unused by the DUT.
    .fetch_enable_i              ( 1'b1                        ),
    .boot_addr_i                 ( BOOTROM_BASE                ),

    .boot_done_o                 ( boot_done                   ),

    .i2c_scl_i                   ( i2c_scl_i                   ),
    .i2c_scl_o                   ( i2c_scl_o                   ),
    .i2c_scl_oen_o               ( i2c_scl_oen_o               ),
    .i2c_sda_i                   ( i2c_sda_i                   ),
    .i2c_sda_o                   ( i2c_sda_o                   ),
    .i2c_sda_oen_o               ( i2c_sda_oen_o               ),
    .i2c_interrupt_o             ( i2c_interrupt_o             ),

    .timer0_irq_o                ( timer0_irq                  ),
    .timer1_irq_o                ( timer1_irq                  ),

    .uart_sin_i                  ( uart_sin_i                  ),
    .uart_sout_o                 ( uart_sout_o                 ),
    .uart_int_o                  ( uart_int_o                  ),
    .uart_out1n_o                ( uart_out1n_o                ),
    .uart_out2n_o                ( uart_out2n_o                ),
    .uart_rtsn_o                 ( uart_rtsn_o                 ),
    .uart_dtrn_o                 ( uart_dtrn_o                 ),
    .uart_ctsn_i                 ( uart_ctsn_i                 ),
    .uart_dsrn_i                 ( uart_dsrn_i                 ),
    .uart_dcdn_i                 ( uart_dcdn_i                 ),
    .uart_rin_i                  ( uart_rin_i                  ),

    .gpio_in_i                   ( gpio_in_i                   ),
    .gpio_out_o                  ( gpio_out_o                  ),
    .gpio_tx_en_o                ( gpio_tx_en_o                ),
    .gpio_in_sync_o              ( gpio_in_sync_o              ),
    .gpio_global_interrupt_o     ( gpio_global_interrupt_o     ),
    .gpio_pin_level_interrupts_o ( gpio_pin_level_interrupts_o ),

    .spi_clk_o                   ( spi_clk_o                   ),
    .spi_csn0_o                  ( spi_csn0_o                  ),
    .spi_csn1_o                  ( spi_csn1_o                  ),
    .spi_csn2_o                  ( spi_csn2_o                  ),
    .spi_csn3_o                  ( spi_csn3_o                  ),
    .spi_mode_o                  ( spi_mode_o                  ),
    .spi_sdo0_o                  ( spi_sdo0_o                  ),
    .spi_sdo1_o                  ( spi_sdo1_o                  ),
    .spi_sdo2_o                  ( spi_sdo2_o                  ),
    .spi_sdo3_o                  ( spi_sdo3_o                  ),
    .spi_sdi0_i                  ( spi_sdi0_i                  ),
    .spi_sdi1_i                  ( spi_sdi1_i                  ),
    .spi_sdi2_i                  ( spi_sdi2_i                  ),
    .spi_sdi3_i                  ( spi_sdi3_i                  ),
    .spi_events_o                ( spi_events_o                )
  );

  // ───────────────────────────────────────────────────────────────────────
  //  Hierarchical probes
  // ───────────────────────────────────────────────────────────────────────
  `define ISRAM_W(i)   dut.i_isram.u_imem.mem_array[i]
  `define DSRAM_W(i)   dut.i_dsram.mem[i]
  `define XREG(n)      dut.i_riscv_core.Decode.rf.Register[n]
  `define CORE_PC      dut.i_riscv_core.Fetch.PCF
  `define T0_CTRL      dut.i_apb_timer0.TIMER_GEN[0].timer_i.regs_q[1]
  `define T0_VAL       dut.i_apb_timer0.TIMER_GEN[0].timer_i.regs_q[0]

  wire core_rst_n_obs   = dut.core_rst_n;
  wire periph_rst_n_obs = dut.periph_rst_n;
  wire spi_rst_n_obs    = dut.spi_rst_n;

  // ───────────────────────────────────────────────────────────────────────
  //  Cycle counter, monitors
  // ───────────────────────────────────────────────────────────────────────
  // NOTE: deliberately no `initial cyc_cnt = 0;`. A variable written by an
  // always_ff may have exactly ONE driver, and an initial block assigning to it
  // counts as a second — xmelab rejects that with *E,MULAXX. longint is 2-state
  // so it already starts at 0. This matches soc_imem_boot_vendor_tb.sv:219 and
  // bootloader_tb.sv:382.
  longint unsigned cyc_cnt;
  always_ff @(posedge clk) cyc_cnt <= cyc_cnt + 1;

  always @(dut.i_bootloader.state_q)
    $display("[TB] @%0t (cyc %0d) Bootloader -> %s",
             $time, cyc_cnt, dut.i_bootloader.state_q.name());

  always @(posedge clk) begin
    if (cyc_cnt > 0 && cyc_cnt % 25000 == 0 && !boot_done)
      $display("[TB] ... boot in progress @cyc %0d: state=%s clear_cnt=%0d word_cnt=%0d",
               cyc_cnt, dut.i_bootloader.state_q.name(),
               dut.i_bootloader.clear_cnt_q, dut.i_bootloader.word_cnt_q);
  end

  // Reset-release ordering
  int unsigned spi_release_cyc, core_release_cyc, periph_release_cyc;
  bit          saw_spi_activity;

  always @(posedge clk) begin
    if (spi_rst_n_obs    === 1'b1 && spi_release_cyc    == 0) spi_release_cyc    = cyc_cnt;
    if (core_rst_n_obs   === 1'b1 && core_release_cyc   == 0) core_release_cyc   = cyc_cnt;
    if (periph_rst_n_obs === 1'b1 && periph_release_cyc == 0) periph_release_cyc = cyc_cnt;
  end

  always @(negedge spi_csn0_o) saw_spi_activity = 1'b1;

  // ───────────────────────────────────────────────────────────────────────
  //  ISRAM write-path diagnostics
  // ───────────────────────────────────────────────────────────────────────
  // Regression guard for a bug that was hard to see from the checks alone: the
  // bootloader drove aw.prot = 0, and i_isram_axi_if (PRIV_WRITE_ONLY=1) then
  // rejected every ISRAM write with SLVERR WITHOUT ever asserting sram_req_o.
  // Boot still "succeeded" — DSRAM has no privilege gate, so it filled normally
  // — and the only symptom was ISRAM left at its NOP fill.
  //
  // These counters localise any recurrence immediately:
  //   isram_wr_cnt == EXP_ISRAM_WR, no errors  -> path healthy.
  //   isram_wr_cnt == 0 && isram_slverr_cnt > 0 -> rejected at the bridge.
  //       aw_prot_seen then says whether the privileged marking (3'b001)
  //       survived the crossbar or arrived as 0.
  //   isram_wr_cnt == 0 && isram_aw_cnt == 0    -> nothing reached MST[0] at
  //       all; suspect crossbar routing / address map.
  //   anything in between                       -> partial; counts are printed.
  int unsigned isram_wr_cnt, dsram_wr_cnt, isram_slverr_cnt, isram_aw_cnt;
  logic [2:0]  aw_prot_seen;

  always @(posedge clk) begin
    // Writes actually presented to the ISRAM macro
    if (dut.isram_cs === 1'b1 && dut.isram_we === 1'b1) begin
      isram_wr_cnt++;
      if (isram_wr_cnt <= 3)
        $display("[ISRAM-WR] #%0d @cyc %0d addr=0x%04h data=0x%08h mask=0x%1h",
                 isram_wr_cnt, cyc_cnt, dut.isram_addr, dut.isram_wdata, dut.isram_wmask);
    end
    if (dut.dsram_cs === 1'b1 && dut.dsram_we === 1'b1) dsram_wr_cnt++;

    // AW handshakes arriving at the ISRAM bridge — capture the prot bits the
    // privilege gate actually sees (bootloader drives 3'b001).
    if (dut.xbar_mst_req[0].aw_valid === 1'b1 &&
        dut.xbar_mst_resp[0].aw_ready === 1'b1) begin
      isram_aw_cnt++;
      aw_prot_seen = dut.xbar_mst_req[0].aw.prot;
      if (isram_aw_cnt <= 3)
        $display("[ISRAM-AW] #%0d @cyc %0d addr=0x%08h prot=3'b%03b %s",
                 isram_aw_cnt, cyc_cnt, dut.xbar_mst_req[0].aw.addr,
                 dut.xbar_mst_req[0].aw.prot,
                 dut.xbar_mst_req[0].aw.prot[0] ? "(privileged - passes gate)"
                                                : "(UNPRIVILEGED - WILL BE REJECTED)");
    end

    // SLVERR / DECERR responses coming back from the ISRAM bridge
    if (dut.xbar_mst_resp[0].b_valid === 1'b1 &&
        dut.xbar_mst_req[0].b_ready  === 1'b1 &&
        dut.xbar_mst_resp[0].b.resp  !== 2'b00) begin
      isram_slverr_cnt++;
      if (isram_slverr_cnt <= 3)
        $display("[ISRAM-ERR] error response #%0d @cyc %0d resp=2'b%02b",
                 isram_slverr_cnt, cyc_cnt, dut.xbar_mst_resp[0].b.resp);
    end
  end

  // ───────────────────────────────────────────────────────────────────────
  //  BootROM effect capture (x2 / stack pointer)
  // ───────────────────────────────────────────────────────────────────────
  // The BootROM's `lui x2, 0x28` initialises the stack pointer, but the loaded
  // program's SECOND instruction is `addi x2, x0, 9` — it reuses x2 as a
  // scratch register. So sampling x2 at the end of the run cannot tell whether
  // the ROM executed: it reads 9 either way, and read 0 in the failing runs
  // only because the program never ran at all.
  //
  // Latch the FIRST architectural write to x2 instead. That write is the ROM's
  // lui; every later one belongs to the program. The register file commits on
  // `WE3 && A3 != 0` (Register_File.v:35), so watching WE3/A3/WD3 catches the
  // value at retirement, independent of pipeline depth or branch timing.
  logic [31:0] x2_first_wr_val;
  int unsigned x2_first_wr_cyc, x2_wr_count;
  bit          x2_written;

  always @(posedge clk) begin
    if (dut.i_riscv_core.Decode.rf.WE3 === 1'b1 &&
        dut.i_riscv_core.Decode.rf.A3  === 5'd2) begin
      x2_wr_count++;
      if (!x2_written) begin
        x2_written      = 1'b1;
        x2_first_wr_val = dut.i_riscv_core.Decode.rf.WD3;
        x2_first_wr_cyc = cyc_cnt;
        $display("[TB] First write to x2 @cyc %0d: 0x%08h  (BootROM lui should give 0x%08h)",
                 cyc_cnt, dut.i_riscv_core.Decode.rf.WD3, EXPECTED_SP);
      end
    end
  end

  // ───────────────────────────────────────────────────────────────────────
  //  Scoreboard
  // ───────────────────────────────────────────────────────────────────────
  int unsigned pass_cnt, fail_cnt;

  task automatic check(input string label, input bit cond);
    if (cond) begin
      $display("[TB]   PASS: %s", label);
      pass_cnt++;
    end else begin
      $error  ("[TB]   FAIL: %s", label);
      fail_cnt++;
    end
  endtask

  task automatic check_word(input string label,
                            input logic [31:0] actual,
                            input logic [31:0] expected);
    if (actual === expected) begin
      $display("[TB]   PASS: %s = 0x%08h", label, actual);
      pass_cnt++;
    end else begin
      $error  ("[TB]   FAIL: %s = 0x%08h (expected 0x%08h)", label, actual, expected);
      fail_cnt++;
    end
  endtask

  task automatic banner(input string text);
    $display("[TB] ============================================================");
    $display("[TB]  %s", text);
    $display("[TB] ============================================================");
  endtask

  // ───────────────────────────────────────────────────────────────────────
  //  Flash backdoor readback
  // ───────────────────────────────────────────────────────────────────────
  // Reassembles a 32-bit word from the flash model's byte-addressed sparse
  // memory, undoing the little-endian layout the image was written in.
  // Used only to confirm the preload landed — the boot path itself reads the
  // flash over real SPI.
  task automatic flash_read_word(input  int unsigned  word_addr,
                                 output logic [31:0]  data);
    integer b0, b1, b2, b3;
    int unsigned base;
    begin
      base = word_addr * 4;
      u_flash.memory_features_i0.read_mem_w(b0, base + 0);
      u_flash.memory_features_i0.read_mem_w(b1, base + 1);
      u_flash.memory_features_i0.read_mem_w(b2, base + 2);
      u_flash.memory_features_i0.read_mem_w(b3, base + 3);
      data = { b3[7:0], b2[7:0], b1[7:0], b0[7:0] };
    end
  endtask

  // ───────────────────────────────────────────────────────────────────────
  //  Main sequence
  // ───────────────────────────────────────────────────────────────────────
  initial begin
    logic [31:0] result_word;
    logic [31:0] fw;
    int unsigned wcnt;

    pass_cnt = 0; fail_cnt = 0;
    spi_release_cyc = 0; core_release_cyc = 0; periph_release_cyc = 0;
    saw_spi_activity = 1'b0;
    // Sentinel: if the BootROM's lui never retires, this value survives and the
    // check below fails loudly instead of comparing against X.
    x2_first_wr_val = 32'hDEAD_DEAD;

    // Waveforms are OPT-IN. Boot alone is ~200k cycles (the bootloader zeroes
    // all 16384 ISRAM+DSRAM words one AXI write at a time), so probing the full
    // hierarchy by default produces an enormous database and a slow run.
    // Enable when you actually need to debug:   xrun -f ... +WAVES
    if ($test$plusargs("WAVES")) begin
      $display("[TB] Waveform dumping ENABLED (+WAVES)");
      `ifdef XCELIUM
        $shm_open("soc_timer0_boot_run_tb.shm");
        $shm_probe(soc_timer0_boot_run_tb, "ASMC");
      `else
        `ifdef VCS
          $vcdpluson;
        `else
          $dumpfile("soc_timer0_boot_run_tb.vcd");
          $dumpvars(0, soc_timer0_boot_run_tb);
        `endif
      `endif
    end

    hard_rst_ni = 1'b0;
    soft_rst_ni = 1'b1;
    repeat (10) @(posedge clk);

    banner("RISCFORGE SoC — full boot-to-runtime test (Timer 0 program)");
    $display("[TB]  Flash image : ../mem_files/riscforge_timer0_flash.mem");
    $display("[TB]  Instr words : %0d -> ISRAM 0x%08h", NUM_INSTR_WORDS, ISRAM_BASE);
    $display("[TB]  Data  words : %0d -> DSRAM 0x%08h", NUM_DATA_WORDS,  DSRAM_BASE);

    // ══════════════════════════════════════════════════════════════════
    //  PHASE 0 — FLASH PRELOAD SANITY
    // ══════════════════════════════════════════════════════════════════
    // Reads the image straight back out of the flash model before boot even
    // starts. This confirms three things at once:
    //   * the mem_file_name parameter override actually took effect (if it
    //     were ignored the model stays fully erased and every word reads
    //     0xFFFFFFFF),
    //   * the file was found at the given relative path,
    //   * the little-endian byte layout the converter produced reassembles
    //     into the intended 32-bit words.
    // Without this, a failed preload would show up much later as ISRAM full
    // of 0xFFFFFFFF, which is far harder to diagnose.
    banner("PHASE 0: FLASH IMAGE PRELOAD (mem_file_name backdoor readback)");

    flash_read_word(0, fw);
    if (fw === 32'hFFFF_FFFF) begin
      $error("[TB] Flash word 0 reads 0xFFFFFFFF (erased) — the preload did NOT happen.");
      $error("[TB]   Check that ../mem_files/riscforge_timer0_flash.mem exists and that");
      $error("[TB]   the simulator's working directory is ips/RTL_SOC/.");
      $error("[TB]   If the tool ignored the mem_file_name parameter override, use");
      $error("[TB]   defparam u_flash.mem_file_name = \"...\"; instead.");
    end

    for (int i = 0; i < NUM_INSTR_WORDS; i++) begin
      flash_read_word(i, fw);
      check_word($sformatf("flash[%0d] (instr)", i), fw, golden_instr[i]);
    end
    for (int i = 0; i < NUM_DATA_WORDS; i++) begin
      flash_read_word(NUM_INSTR_WORDS + i, fw);
      check_word($sformatf("flash[%0d] (data)", NUM_INSTR_WORDS + i), fw, golden_data[i]);
    end

    // ══════════════════════════════════════════════════════════════════
    //  PHASE 1 — COLD BOOT
    // ══════════════════════════════════════════════════════════════════
    banner("PHASE 1: COLD BOOT (vendor flash, tPU = 300 us)");

    check("all resets LOW while hard_rst_ni asserted",
          core_rst_n_obs === 1'b0 && periph_rst_n_obs === 1'b0 && spi_rst_n_obs === 1'b0);

    $display("[TB] Releasing hard_rst_ni @cyc %0d", cyc_cnt);
    hard_rst_ni = 1'b1;

    wcnt = 0;
    while (!boot_done && wcnt < BOOT_TIMEOUT_CYCLES) begin
      @(posedge clk);
      wcnt++;
    end

    if (!boot_done) begin
      $error("[TB] TIMEOUT: boot_done not asserted after %0d cycles", BOOT_TIMEOUT_CYCLES);
      $error("[TB]   stuck in state=%s clear_cnt=%0d word_cnt=%0d",
             dut.i_bootloader.state_q.name(),
             dut.i_bootloader.clear_cnt_q, dut.i_bootloader.word_cnt_q);
      $finish;
    end

    $display("[TB] Cold boot completed @cyc %0d", cyc_cnt);
    check("SPI activity occurred during boot", saw_spi_activity === 1'b1);
    check("bootloader parked in S_DONE", dut.i_bootloader.state_q.name() == "S_DONE");

    // ── Reset release ordering ───────────────────────────────────────
    banner("PHASE 2: RESET SEQUENCE");
    check("spi_rst_n released",    spi_release_cyc    != 0);
    check("core_rst_n released",   core_release_cyc   != 0);
    check("periph_rst_n released", periph_release_cyc != 0);
    check("spi_rst_n released BEFORE core_rst_n",
          spi_release_cyc != 0 && core_release_cyc != 0 &&
          spi_release_cyc < core_release_cyc);
    check("core & periph released together", core_release_cyc == periph_release_cyc);
    $display("[TB]   (spi @cyc %0d, core @cyc %0d, periph @cyc %0d)",
             spi_release_cyc, core_release_cyc, periph_release_cyc);

    // ── Image landed in the right memories ───────────────────────────
    banner("PHASE 3: IMAGE PLACEMENT (SPI -> ISRAM / DSRAM)");

    // Diagnostics first — these explain any ISRAM/DSRAM mismatch below.
    $display("[TB] -- Boot write-path counters --");
    $display("[TB]   ISRAM writes reaching the macro : %0d  (expected %0d)",
             isram_wr_cnt, EXP_ISRAM_WR);
    $display("[TB]   DSRAM writes reaching the macro : %0d  (expected %0d)",
             dsram_wr_cnt, EXP_DSRAM_WR);
    $display("[TB]   ISRAM AW handshakes at bridge   : %0d", isram_aw_cnt);
    $display("[TB]   ISRAM error responses (SLVERR)  : %0d", isram_slverr_cnt);
    if (isram_aw_cnt > 0)
      $display("[TB]   last aw.prot seen by the gate   : 3'b%03b%s",
               aw_prot_seen,
               aw_prot_seen[0] ? "" : "   <-- prot[0]=0, PRIV_WRITE_ONLY rejects this");
    if (isram_wr_cnt == EXP_ISRAM_WR && isram_slverr_cnt == 0)
      $display("[TB]   >> ISRAM write path OK: every write reached the macro, no errors.");
    else if (isram_wr_cnt == 0 && isram_aw_cnt > 0)
      $display("[TB]   >> Writes reached the bridge but never the SRAM: rejected by the gate.");
    else if (isram_wr_cnt == 0 && isram_aw_cnt == 0)
      $display("[TB]   >> Nothing reached MST[0] at all: suspect crossbar routing/address map.");
    else
      $display("[TB]   >> Partial: %0d of %0d writes reached the macro, %0d errors.",
               isram_wr_cnt, EXP_ISRAM_WR, isram_slverr_cnt);

    $display("[TB] -- ISRAM (instruction words) --");
    for (int i = 0; i < NUM_INSTR_WORDS; i++)
      check_word($sformatf("ISRAM[%0d]", i), `ISRAM_W(i), golden_instr[i]);

    check_word("ISRAM[11] cleared beyond image", `ISRAM_W(NUM_INSTR_WORDS), 32'h0000_0000);

    $display("[TB] -- DSRAM (data words) --");
    for (int i = 0; i < NUM_DATA_WORDS; i++)
      check_word($sformatf("DSRAM[%0d]", i), `DSRAM_W(i), golden_data[i]);

    // ══════════════════════════════════════════════════════════════════
    //  PHASE 4 — RUNTIME
    // ══════════════════════════════════════════════════════════════════
    banner("PHASE 4: RUNTIME (BootROM -> ISRAM program)");

    // The program's final act before parking is storing its result to
    // DSRAM[0], which the boot image preloaded with 0xDEADBEEF. Waiting for
    // that word to change is a precise "program finished" trigger.
    wcnt = 0;
    while (`DSRAM_W(0) === DATA0_PRELOAD && wcnt < RUN_TIMEOUT_CYCLES) begin
      @(posedge clk);
      wcnt++;
    end
    result_word = `DSRAM_W(0);

    if (wcnt >= RUN_TIMEOUT_CYCLES) begin
      $error("[TB] TIMEOUT: DSRAM[0] never updated after %0d cycles", RUN_TIMEOUT_CYCLES);
      $error("[TB]   PC=0x%08h  x1=0x%08h x2=0x%08h x3=0x%08h x4=0x%08h x5=0x%08h",
             `CORE_PC, `XREG(1), `XREG(2), `XREG(3), `XREG(4), `XREG(5));
    end else begin
      $display("[TB] Program stored its result @cyc %0d (%0d cycles after boot)",
               cyc_cnt, wcnt);
    end

    repeat (20) @(posedge clk);   // let the pipeline drain into the park loop

    $display("[TB] -- BootROM preamble --");
    // Checked against the first-write latch, NOT the live register. The program
    // reuses x2 (`addi x2, x0, 9`), so `XREG(2)` reads 9 by now whether or not
    // the ROM ever ran — it cannot distinguish the two cases.
    check_word("x2 (sp) from BootROM lui — first write, before the program reused it",
               x2_first_wr_val, EXPECTED_SP);
    if (!x2_written)
      $display("[TB]   (x2 was NEVER written: the BootROM lui never retired)");
    else
      $display("[TB]   (first x2 write @cyc %0d; x2 written %0d times total; x2 now = 0x%08h)",
               x2_first_wr_cyc, x2_wr_count, `XREG(2));
    check("PC left BootROM and reached ISRAM", `CORE_PC >= ISRAM_BASE);

    $display("[TB] -- Program register state --");
    check_word("x1 = Timer 0 base",        `XREG(1), TIMER0_BASE);
    check_word("x3 = TIMER_CTRL readback", `XREG(3), EXPECTED_CTRL);
    check_word("x4 = DSRAM base",          `XREG(4), DSRAM_BASE);
    check_word("x5 = PASS code",           `XREG(5), EXPECTED_RESULT);

    $display("[TB] -- MMIO path (core -> AXI -> APB -> Timer 0) --");
    check_word("Timer 0 TIMER_CTRL register", `T0_CTRL, EXPECTED_CTRL);
    check("Timer 0 is counting (TIMER_VAL non-zero)", `T0_VAL != 32'h0);
    $display("[TB]   Timer 0 TIMER_VAL = 0x%08h", `T0_VAL);

    $display("[TB] -- Direct DSRAM store --");
    check_word("DSRAM[0] = program result", result_word, EXPECTED_RESULT);

    $display("[TB] -- Data image survived runtime --");
    for (int i = 1; i < NUM_DATA_WORDS; i++)
      check_word($sformatf("DSRAM[%0d] sentinel intact", i), `DSRAM_W(i), golden_data[i]);

    $display("[TB] -- Core parked in its final loop --");
    begin
      logic [31:0] pc_a, pc_b;
      pc_a = `CORE_PC;
      repeat (20) @(posedge clk);
      pc_b = `CORE_PC;
      // Stability ALONE is not enough: a pipeline deadlock also freezes the PC.
      // A run where the core hung on its first MMIO access passed this check
      // while stopped at 0x10018 (the fail-path addi), so the address has to be
      // verified too — the park loop is the final `beq x0, x0, 0` at word 10.
      check("PC parked at the final self-branch (stable AND at the right address)",
            (pc_a === pc_b) && (pc_b === ISRAM_BASE + 32'd40));
      $display("[TB]   final PC = 0x%08h (expected 0x%08h)%s",
               pc_b, ISRAM_BASE + 32'd40,
               (pc_a === pc_b) && (pc_b !== ISRAM_BASE + 32'd40)
                 ? "   <-- frozen, not parked: pipeline is stalled" : "");
    end

    // ══════════════════════════════════════════════════════════════════
    //  Summary
    // ══════════════════════════════════════════════════════════════════
    $display("[TB] ============================================================");
    if (fail_cnt == 0)
      $display("[TB]  *** ALL %0d CHECKS PASSED ***", pass_cnt);
    else
      $display("[TB]  *** %0d PASSED, %0d FAILED ***", pass_cnt, fail_cnt);
    $display("[TB] ============================================================");

    repeat (10) @(posedge clk);
    $finish;
  end

  // ───────────────────────────────────────────────────────────────────────
  //  Global timeout — 300 us power-up + ~16k-word SRAM clear + margin
  // ───────────────────────────────────────────────────────────────────────
  initial begin
    #20ms;
    $error("[TB] GLOBAL TIMEOUT — simulation exceeded 20 ms");
    $finish;
  end

endmodule : soc_timer0_boot_run_tb
